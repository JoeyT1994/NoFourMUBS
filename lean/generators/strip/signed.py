#!/usr/bin/env python3
"""Generate NoFourMUBs/PRM/CoverageSignedData.lean (the signed corner Laurent expansion, return K §2).

Untrusted: Lean re-checks everything (the expansion by the Kronecker identity checker, the regrouping
into moments by `ring`).

For a unit side (1; x; y) (columns a, b, c) with signature T = -perm * det^2 / (x_a x_b x_c y_a y_b y_c)
(= `Side.TS`), the signed corner value D = conj T - T (= Psi - conj Psi for Psi = perm det^2 / prod of
the entries, return K's D_C) is a Laurent polynomial with 48 terms
c * x_a^i0 y_a^j0 * x_b^i1 y_b^j1 * x_c^i2 y_c^j2 (`dTerms`), all exponents >= -2.

Summed over ordered column triples of a six-column strip, a term gives M(i0,j0) M(i1,j1) M(i2,j2)
(M(i,j) = sum_a x_a^i y_a^j); with the weight x_a y_a + x_b y_b + x_c y_c it gives the three products
with one index shifted by (1, 1).  With the orthogonality moments M(+-1,0), M(0,+-1), M(1,-1), M(-1,1)
zero and M(0,0) = 6 these are 6 * (return K (3)) and 6 * (return K (4)), which is asserted below.

  python3 lean/generators/strip/signed.py
"""
import collections
import itertools
from fractions import Fraction
from pathlib import Path

import sympy as sp

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'NoFourMUBs/PRM/CoverageSignedData.lean'

xa, xb, xc, ya, yb, yc = V = sp.symbols('xa xb xc ya yb yc')
ZEROS = {(1, 0), (-1, 0), (0, 1), (0, -1), (1, -1), (-1, 1)}
SHIFT = 2


def expansion():
    E = sp.Matrix([[1, 1, 1], [xa, xb, xc], [ya, yb, yc]])
    per = sum(sp.prod(E[i, p[i]] for i in range(3)) for p in itertools.permutations(range(3)))
    uv = xa * xb * xc * ya * yb * yc
    T = -per * E.det() ** 2 / uv
    Tb = T.xreplace({w: 1 / w for w in V})
    P = sp.Poly(sp.expand((Tb - T) * uv ** SHIFT), *V)
    terms = []
    for m, c in P.terms():
        e = [k - SHIFT for k in m]  # exponents of xa xb xc ya yb yc
        terms.append((int(c), e[0], e[3], e[1], e[4], e[2], e[5]))
    assert min(min(m) for m, _ in P.terms()) >= 0
    terms.sort()
    return terms


def regroup(terms, weighted):
    acc = collections.defaultdict(Fraction)
    for c, i0, j0, i1, j1, i2, j2 in terms:
        base = [(i0, j0), (i1, j1), (i2, j2)]
        variants = [base]
        if weighted:
            variants = [[(p[0] + 1, p[1] + 1) if q == slot else p for q, p in enumerate(base)]
                        for slot in range(3)]
        for pts in variants:
            if any(p in ZEROS for p in pts):
                continue
            key = tuple(sorted(p for p in pts if p != (0, 0)))
            acc[key] += Fraction(c) * 6 ** pts.count((0, 0)) / 6
    return {k: v for k, v in acc.items() if v}


def lean_int(z):
    return f'({z})' if z < 0 else str(z)


def main():
    terms = expansion()
    assert len(terms) == 48
    a, ab, b, bb, c, cb = (1, 1), (-1, -1), (2, -1), (-2, 1), (-1, 2), (1, -2)
    key = lambda *ps: tuple(sorted(ps))
    assert regroup(terms, False) == {key(ab, b, c): 1, key(a, bb, cb): -1}
    assert regroup(terms, True) == {key(b, c): 6, key(ab, c, (3, 0)): 1, key(ab, b, (0, 3)): 1,
                                    key(bb, cb, (2, 2)): -1, key(a, b, bb): -1, key(a, c, cb): -1}
    out = ['import NoFourMUBs.PRM.CoverageStripMomentData', '',
           '/-! # Signed corner Laurent expansion (return K §2)', '',
           'Generated by `lean/generators/strip/signed.py`; nothing here is trusted (see',
           '`CoverageSignedMoments`). -/', '',
           'namespace NoFourMUBs.PRM.Coverage.StripMoments', '',
           '/-- The 48 terms of the signed corner value `T̄ − T`. -/',
           'def dTerms : List LT := [']
    body = [f'  ⟨{lean_int(t[0])}, {", ".join(lean_int(e) for e in t[1:])}⟩' for t in terms]
    out.append(',\n'.join(body) + ']')
    out.append('')
    out.append('end NoFourMUBs.PRM.Coverage.StripMoments')
    OUT.write_text('\n'.join(out) + '\n')
    print(len(terms), 'terms; readouts (3) and (4) confirmed; wrote', OUT)


if __name__ == '__main__':
    main()

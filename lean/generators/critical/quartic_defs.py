#!/usr/bin/env python3
"""Write lean/NoFourMUBs/PRM/CoverageQuarticDefs.lean from MinimalConstruction/Proofs/critical_quartic.json.

The quartic Q(k, K) is factor 0 of the reduced square-sum numerator (c = k, d = K)."""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
d = json.loads((ROOT / 'MinimalConstruction/Proofs/critical_quartic.json').read_text())
q = d['factors'][0][0]
import sympy as sp
c_, d_ = sp.symbols('c d')
P = sp.Poly(sp.sympify(q.replace('^', '**')), c_, d_)
items = [f'({int(co)}, {i}, {j})' for (i, j), co in sorted(P.terms())]
lines, cur = [], ''
for t in items:
    if len(cur) + len(t) > 96:
        lines.append(cur); cur = t + ','
    else:
        cur = (cur + ' ' + t + ',').strip()
lines.append(cur)
body = '\n  '.join(lines).rstrip(',')
out = ROOT / 'lean/NoFourMUBs/PRM/CoverageQuarticDefs.lean'
out.write_text(f'''import Mathlib

/-!
# The scalar inputs of the critical strip classification (I4), stated

Definitions shared by the two halves of the Lean proof of `TopStripClassification`
(`CRITICAL_STRIP_CLASSIFICATION.md` §§3–4): the quartic `Q(k, K)` (factor 0 of the reduced
square-sum numerator in `critical_quartic.json`, regenerated by
`lean/generators/critical/quartic_defs.py`), the modulus-cubic data, and the two purely scalar
statements

* `ScalarClassification` — §3, the Bernstein/Sturm sign certificate;
* `PoleClassification` — §4, the pole substitutions.

Notation: `h = 1 + k²`, `q = 4/h`, `p = 9 − q`, `J = 8k/h²`, `W = q(q² − 8q + 18)/2`,
`f(T) = T³ − pT² + (W + K)T − K` (the modulus cubic, roots `X, Y, Z`, `K = XYZ`).
-/

noncomputable section

namespace NoFourMUBs.PRM.Coverage.Quartic

def hk (k : ℝ) : ℝ := 1 + k ^ 2
def qk (k : ℝ) : ℝ := 4 / hk k
def pk (k : ℝ) : ℝ := 9 - qk k
def Jk (k : ℝ) : ℝ := 8 * k / hk k ^ 2
def Wk (k : ℝ) : ℝ := qk k * (qk k ^ 2 - 8 * qk k + 18) / 2

/-- The modulus cubic. -/
def fM (k K T : ℝ) : ℝ := T ^ 3 - pk k * T ^ 2 + (Wk k + K) * T - K

/-- The Cauchy bound `K ≥ J²/4` and the three discriminant roots. -/
def Kmin (k : ℝ) : ℝ := 16 * k ^ 2 / hk k ^ 4
def K0 (k : ℝ) : ℝ := 4 * (9 * k ^ 2 + 1) / hk k ^ 3
def Kp (k : ℝ) : ℝ := (27 * k ^ 6 + 9 * k ^ 4 + 17 * k ^ 2 + 3 + 8 * k * hk k) / hk k ^ 3
def Kn (k : ℝ) : ℝ := (27 * k ^ 6 + 9 * k ^ 4 + 17 * k ^ 2 + 3 - 8 * k * hk k) / hk k ^ 3

/-- Moment-denominator data for the two halves, `σ = ±1`. -/
def zS (σ k : ℝ) : ℝ := -2 * (1 + σ * k) / hk k
def gS (σ k : ℝ) : ℝ := 3 * qk k + σ * Jk k
def alphaS (σ k : ℝ) : ℝ := 9 + gS σ k / zS σ k

/-- The coefficients `(c, i, j)` of `Q = Σ c kⁱ Kʲ`. -/
def qCoeffs : List (ℤ × ℕ × ℕ) := [
  {body}]

/-- The quartic `Q(k, K)`. -/
def Q (k K : ℝ) : ℝ := (qCoeffs.map fun c => (c.1 : ℝ) * k ^ c.2.1 * K ^ c.2.2).sum

/-- The three candidates of the theorem (`κ` = positive root of `3k³ + k² + k − 1`). -/
def Candidates (k K : ℝ) : Prop :=
  (3 * k ^ 3 + k ^ 2 + k - 1 = 0 ∧ K = Kmin k) ∨ (k = 1 / 3 ∧ K = 729 / 125) ∨ (k = 1 ∧ K = 5)

/-- **§3, the sign certificate.**  On physical data (`K ≥ J²/4`, nonnegative modulus-cubic
discriminant `−4(K − K0)(K − K₊)(K − K₋)`), `Q(k, K) = 0` only at the candidates. -/
def ScalarClassification : Prop :=
  ∀ k K : ℝ, 0 < k → Kmin k ≤ K → 0 ≤ -((K - K0 k) * (K - Kp k) * (K - Kn k)) → Q k K = 0 →
    Candidates k K

/-- **§4, the pole substitutions.**  If `K` is one of the four boundary values and the pole
coordinate `α_σ = 9 + g_σ/z_σ` (with `z_σ ≠ 0`) is a root of the modulus cubic, then `(k, K)` is a
candidate. -/
def PoleClassification : Prop :=
  ∀ σ k K : ℝ, (σ = 1 ∨ σ = -1) → 0 < k → (K = Kmin k ∨ K = K0 k ∨ K = Kp k ∨ K = Kn k) →
    zS σ k ≠ 0 → fM k K (alphaS σ k) = 0 → Candidates k K

end NoFourMUBs.PRM.Coverage.Quartic
''')
print('wrote', out)

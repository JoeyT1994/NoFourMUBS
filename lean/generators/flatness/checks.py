#!/usr/bin/env python3
"""Write the kernel-check modules NoFourMUBs/L1/FlatCheck{Mh,Qv,F}.lean.

Each identity is one `decide +kernel` theorem on `Circ.validR`; the modules only enumerate them.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
L1 = ROOT / 'NoFourMUBs/L1'

HEAD = """import NoFourMUBs.L1.FlatCircuits

/-! {doc}

Generated by `lean/generators/flatness/checks.py`. -/

namespace NoFourMUBs.L1.FlatCircuits

open NoFourMUBs.Kronecker

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
"""

FIN = ['0', '1', '2']


def module(name, doc, thms, collect):
    out = [HEAD.format(doc=doc)]
    out += thms
    out.append(collect)
    out.append('end NoFourMUBs.L1.FlatCircuits\n')
    (L1 / f'{name}.lean').write_text('\n'.join(out))


def quad(prefix, expr, stmt_name, stmt_doc, stmt_expr):
    thms, cases = [], []
    for q in range(2):
        for i in range(2):
            for a in range(3):
                for c in range(3):
                    nm = f'{prefix}_{q}{i}{a}{c}'
                    thms.append(f'theorem {nm} : {expr(q, i, a, c)}.num.validR 2 = true := by decide +kernel\n')
                    cases.append(nm)
    collect = (f'/-- {stmt_doc} -/\ntheorem {stmt_name} (q i : Fin 2) (a c : Fin 3) :\n'
               f'    {stmt_expr}.num.validR 2 = true := by\n'
               f'  fin_cases q <;> fin_cases i <;> fin_cases a <;> fin_cases c\n'
               + ''.join(f'  · exact {nm}\n' for nm in cases))
    return thms, collect


thms, collect = quad(
    'mhOk', lambda q, i, a, c: f'(mhUnred {q} {i} {a} {c} - mhData {q} {i} {a} {c})',
    'mh_valid', 'The reduced entries of `K Qh K*` are correct.',
    '(mhUnred q.val i.val a c - mhData q.val i.val a c)')
module('FlatCheckMh', '# Matched flatness: the 36 reduced entries of `K Qh K*`', thms, collect)

thms, collect = quad(
    'qvOk', lambda p, i, a, c: f'(Qv {p} {i} {a} {c} - qvData {p} {i} {a} {c})',
    'qv_valid', 'The reduced vertical third moments are correct.',
    '(Qv p.val i.val a c - qvData p.val i.val a c)'.replace('p.val', 'q.val'))
module('FlatCheckQv', '# Matched flatness: the 36 reduced vertical third moments', thms, collect)

for p in range(2):
    for q in range(2):
        thms = [f'theorem F{k}_{p}{q}_valid : (F{k} {p} {q}).num.validR 2 = true := by decide +kernel\n'
                for k in range(2)]
        module(f'FlatCheckF{p}{q}', f'# Matched flatness: the coefficients of the weighted defect `W{p+1}{q+1}` vanish '
               f'(`FLATNESS.md` (4.6))', thms, '')
collect = ('/-- The eight coefficient identities (4.6). -/\n'
           'theorem F_valid (p q : Fin 2) :\n'
           '    (F0 p.val q.val).num.validR 2 = true ∧ (F1 p.val q.val).num.validR 2 = true := by\n'
           '  fin_cases p <;> fin_cases q\n'
           + ''.join(f'  · exact ⟨F0_{p}{q}_valid, F1_{p}{q}_valid⟩\n' for p in range(2) for q in range(2)))
(L1 / 'FlatCheckF.lean').write_text(
    ''.join(f'import NoFourMUBs.L1.FlatCheckF{p}{q}\n' for p in range(2) for q in range(2)) +
    '\n/-! # Matched flatness: the eight coefficient identities\n\n'
    'Generated by `lean/generators/flatness/checks.py`. -/\n\nnamespace NoFourMUBs.L1.FlatCircuits\n\n'
    + collect + '\nend NoFourMUBs.L1.FlatCircuits\n')
print('wrote FlatCheckMh, FlatCheckQv, FlatCheckF*')

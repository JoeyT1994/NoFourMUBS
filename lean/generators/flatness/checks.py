#!/usr/bin/env python3
"""Write the kernel-check modules NoFourMUBs/L1/FlatCheck{Mh,Qv,F}.lean.

Each identity is one `decide +kernel` theorem on `Circ.validR`; the modules only enumerate them.  Only the entry
(p, q) = (0, 0) (zero-based; the weighted defect W11) is checked: the other three defects follow by relabelling
(handoff M; `FlatBridge.W_zero`).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
L1 = ROOT / 'NoFourMUBs/L1'

HEAD = """import NoFourMUBs.L1.FlatCircuits

/-! {doc}

Generated by `lean/generators/flatness/checks.py`. -/

namespace NoFourMUBs.L1.FlatCircuits

open NoFourMUBs.Kronecker

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
"""

FIN = ['0', '1', '2']


def module(name, doc, thms, collect):
    out = [HEAD.format(doc=doc)]
    out += thms
    out.append(collect)
    out.append('end NoFourMUBs.L1.FlatCircuits\n')
    (L1 / f'{name}.lean').write_text('\n'.join(out))


def quad(prefix, expr, stmt_name, stmt_doc, stmt_expr):
    """The 18 identities of the first index 0 (the second row of the side)."""
    thms, cases = [], []
    for i in range(2):
        for a in range(3):
            for c in range(3):
                nm = f'{prefix}_0{i}{a}{c}'
                thms.append(f'theorem {nm} : {expr(0, i, a, c)}.num.validR 2 = true := by decide +kernel\n')
                cases.append(nm)
    collect = (f'/-- {stmt_doc} -/\ntheorem {stmt_name} (i : Fin 2) (a c : Fin 3) :\n'
               f'    {stmt_expr}.num.validR 2 = true := by\n'
               f'  fin_cases i <;> fin_cases a <;> fin_cases c\n'
               + ''.join(f'  · exact {nm}\n' for nm in cases))
    return thms, collect


thms, collect = quad(
    'mhOk', lambda q, i, a, c: f'(mhUnred {q} {i} {a} {c} - mhData {q} {i} {a} {c})',
    'mh_valid', 'The reduced entries of `K Q⁽¹⁾ K*` are correct.',
    '(mhUnred 0 i.val a c - mhData 0 i.val a c)')
module('FlatCheckMh', '# Matched flatness: the 18 reduced entries of `K Q⁽¹⁾ K*` (horizontal side, row 1)', thms, collect)

thms, collect = quad(
    'qvOk', lambda p, i, a, c: f'(Qv {p} {i} {a} {c} - qvData {p} {i} {a} {c})',
    'qv_valid', 'The reduced vertical third moments are correct.',
    '(Qv 0 i.val a c - qvData 0 i.val a c)')
module('FlatCheckQv', '# Matched flatness: the 18 reduced vertical third moments (vertical side, row 1)', thms, collect)

thms = [f'theorem F{k}_00_valid : (F{k} 0 0).num.validR 2 = true := by decide +kernel\n' for k in range(2)]
module('FlatCheckW11', '# Matched flatness: the coefficients of the weighted defect `W11` vanish (`FLATNESS.md` (4.6))',
       thms, '')
collect = ('/-- The two coefficient identities (4.6) of `W11`. -/\n'
           'theorem F_valid : (F0 0 0).num.validR 2 = true ∧ (F1 0 0).num.validR 2 = true :=\n'
           '  ⟨F0_00_valid, F1_00_valid⟩\n')
(L1 / 'FlatCheckF.lean').write_text(
    'import NoFourMUBs.L1.FlatCheckW11\n'
    '\n/-! # Matched flatness: the two coefficient identities of `W11`\n\n'
    'The other three weighted defects follow by relabelling (`FlatBridge.W_zero`).  '
    'Generated by `lean/generators/flatness/checks.py`. -/\n\nnamespace NoFourMUBs.L1.FlatCircuits\n\n'
    + collect + '\nend NoFourMUBs.L1.FlatCircuits\n')
print('wrote FlatCheckMh, FlatCheckQv, FlatCheckW11, FlatCheckF')

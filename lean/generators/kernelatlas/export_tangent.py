"""Export the tangent-test (Stage C, C2(b)) kernel data of one atlas Record (KernelAtlas/Tangent.lean).

Usage: python3 export_tangent.py <record index> <out dir> [--subs 0,8 6,2 ...] [--all] [--preflight]

Requires the bin-tree data module of the same Record (export_record.py: `<out dir>/Data.lean`, same p, q).  Writes
  * `TangentData.lean`: `tcfg : TCfg` and `tq : TParQ` (lane radix, offsets, the exact integer frame T' = DT T + OT,
    per-depth coefficients) and `tparOK : TParOK cfg pq tcfg tq` by `decide +kernel`;
  * `TangentSub.lean`: one kernel declaration per selected sub-slab `(b1, b2)`
    `slabT cfg tcfg true true leafT T1_b1 [T2_b2] L3 L4 L5 = true` (direct test, tangent test, children);
  * with --all: `TangentSlabNN.lean` (12 modules, 12 declarations each) and `TangentCover.lean`, the end-to-end
    theorem for the Record.
The constants come from ktangent.py, an exact mirror of the Lean definitions; the kernel re-derives every claim.
Pre-flight (--preflight): the mirror's counts of direct tests, tangent tests and survivors, per selected sub-slab.
"""
import argparse, gzip, json, math, os, sys, time
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, 'proof', 'atlas'))
import kbins as KB
import ktangent as KT
from export_record import q_lit, radii

DT = 36 * 2 ** 30          # T = T^ / DT exactly (Tint in units 2^-30, horizontal projector in units 1/36)


def record_data(idx, p=28, q=20):
    import numpy as np
    from ballrecord import BallRecord
    d = json.load(gzip.open(os.path.join(ROOT, 'proof/atlas/results/atlas_certificate.json.gz'), 'rt'))
    rec = d['records'][idx]
    phi = [float.fromhex(x) for x in rec['phi']]
    Prad = [[Fr(phi[6 * j + i]) for i in range(6)] for j in range(6)]
    rcol, rF, _, _ = radii(rec)
    B = BallRecord(np.array(phi), Tint=rec.get('Tint'))
    rH, n0 = B.normal_bound(rec['R'])          # exact frame: no float-frame augmentation of n
    That = [[[0] * 6 for _ in range(6)] for _ in range(4)]
    for k in range(B.rec.dimT):
        for j in range(6):
            for i in range(6):
                x = B.rec.TB[k][6 * j + i] * DT
                assert x.denominator == 1
                That[k][j][i] = int(x)
    up = lambda x: KB.dyadic_up(Fr(x) * (1 + Fr(1, 10 ** 9)) / (2 * KB.PI_LO))
    rbar, rFbar, rHbar, nbar = up(rcol), up(rF), up(rH), up(n0)
    Kbar = 1 + Fr(1, 10 ** 9)
    EU = KB.eu_table(p)
    EP = KB.ep_table(Prad, p)
    epsU, epsP = KB.eps_tables(p, Prad)
    epsU, epsP = KB.dyadic_up(epsU), KB.dyadic_up(epsP)
    par = KB.Params(p, q, rbar, rFbar, Kbar, epsU, epsP)
    R5 = KB.roots(EU, EP, p)
    W0 = []
    for i in range(6):
        W0 += [EP[0][i][0] + par.BOFF, EP[0][i][1] + par.BOFF]
    tc = KT.TCfg(par, That, DT)
    tcol = KB.dyadic_up(max(Fr(sum(abs(That[k][j][i]) for j in range(6)), DT) for k in range(4) for i in range(6)))
    tp = KT.TPar(par, tc, rHbar, nbar, tcol, KB)
    info = dict(R=rec['R'], rcol=rcol, rF=rF, rH=rH, n=n0)
    return par, tc, tp, W0, R5, info


def write_data(outdir, base, idx, par, tc, tp, info):
    L = []
    w = L.append
    w('import %s.Data' % base)
    w('import NoFourMUBs.KernelAtlas.Tangent')
    w('')
    w('/-!')
    w('# Tangent-test data for atlas Record %d' % idx)
    w('')
    w('Generated by `lean/generators/kernelatlas/export_tangent.py`; do not edit.  Stage C radii (radians): r_H = %.12g,'
      % info['rH'])
    w('n = %.6g (exact frame).  Lane radix `R = 2^%d`, frame offset `OT = %d`, scale `2^%d`.' % (info['n'], tc.L, tc.OT, tc.g))
    w('-/')
    w('')
    w('namespace %s' % base)
    w('')
    w('open NoFourMUBs.KernelAtlas')
    w('')
    w('def tcfg : TCfg where')
    w('  R := %d' % tc.R)
    w('  OT := %d' % tc.OT)
    flat = [tc.Tp[k][j][i] for k in range(4) for j in range(6) for i in range(6)]
    w('  TpL := [%s]' % ', '.join(str(x) for x in flat))
    w('  ox := %d' % tc.ox)
    w('  og := %d' % tc.og)
    w('  OX := %d' % tc.OXp)
    w('  OG := %d' % tc.OGp)
    w('  c1 := %d' % tc.c1)
    w('  c0 := %d' % tc.c0)
    w('  ke := %d' % tp.ke)
    w('  g := %d' % tc.g)
    w('  lv := fun d => match d with')
    for dd in range(4):
        w('    | %s => ⟨%s⟩' % (str(dd) if dd < 3 else '_', ', '.join(str(x) for x in tp.lv[dd])))
    w('')
    w('def tq : TParQ where')
    w('  DT := %d' % DT)
    for nm, val in (('rHbar', tp.rHbar), ('nbar', tp.nbar), ('tcol', tp.tcol)):
        w('  %s := %s' % (nm, q_lit(val)))
    w('')
    w('theorem tparOK : TParOK cfg pq tcfg tq := by decide +kernel')
    w('')
    w('end %s' % base)
    with open(os.path.join(outdir, 'TangentData.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('idx', type=int)
    ap.add_argument('out')
    ap.add_argument('--subs', nargs='*', default=[])
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--preflight', action='store_true')
    ap.add_argument('--module', default=None)
    a = ap.parse_args()
    base = a.module or 'NoFourMUBs.KernelAtlas.Rec%d' % a.idx
    par, tc, tp, W0, R5, info = record_data(a.idx)
    os.makedirs(a.out, exist_ok=True)
    write_data(a.out, base, a.idx, par, tc, tp, info)
    subs = [tuple(int(t) for t in s.split(',')) for s in a.subs]
    pre = {}
    for (b1, b2) in subs:
        if a.preflight:
            t0 = time.time()
            ok, st = KT.run(par, tc, tp, W0, R5, use_tangent=True, only=(b1, b2))
            pre['%d_%d' % (b1, b2)] = dict(ok=ok, seconds=round(time.time() - t0, 2),
                                          **{'%s_%d' % k: v for k, v in sorted(st.items())})
    if subs:
        L = ['import %s.TangentData' % base, '',
             '/-! Record %d: selected sub-slabs with the direct test, the tangent test and the children (generated).' % a.idx]
        for k, v in pre.items():
            L.append('Mirror `%s`: `%s`.' % (k, json.dumps(v, sort_keys=True)))
        L += ['-/', '', 'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas', '']
        for (b1, b2) in subs:
            L.append('theorem tsub_%d_%d : slabT cfg tcfg true true leafT T1_%d [T2_%d] L3 L4 L5 = true := by decide +kernel'
                     % (b1, b2, b1, b2))
            L.append('')
        L.append('end %s' % base)
        with open(os.path.join(a.out, 'TangentSub.lean'), 'w') as f:
            f.write('\n'.join(L) + '\n')
    if a.all:
        for b1 in range(12):
            L = ['import %s.TangentData' % base, '',
                 '/-! Record %d, slab `b₁ = %d` with the tangent test: twelve sub-slabs, one kernel declaration each '
                 '(generated). -/' % (a.idx, b1), '', 'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas', '']
            for b2 in range(12):
                L.append('theorem tsub_%d_%d : slabT cfg tcfg true true leafT T1_%d [T2_%d] L3 L4 L5 = true := by '
                         'decide +kernel' % (b1, b2, b1, b2))
                L.append('')
            L.append('end %s' % base)
            with open(os.path.join(a.out, 'TangentSlab%02d.lean' % b1), 'w') as f:
                f.write('\n'.join(L) + '\n')
        L = ['import %s.TangentSlab%02d' % (base, b) for b in range(12)]
        L += ['', '/-!', '# Record %d: the bin tree with the direct and the tangent test, end to end (generated)' % a.idx, '',
              'Every phase vector `β ∈ [0,1]⁵` lies in a bin that is rejected by the direct test or by the tangent test',
              '(C2(b), multiplier `y = c`) for every admissible `δ` of the Record ball with the exact frame `Tmat tcfg tq`,',
              'or in a depth-0 (`M = 96`) bin.  Hypotheses: the operator-norm bound `K` and the Stage C radii',
              '`r ≤ r̄`, `r_F ≤ r̄_F`, `r_H ≤ r̄_H`, `n ≤ n̄` (cycles), which come from the normal bound.', '-/', '',
              'namespace %s' % base, '', 'open Hadamard6 NoFourMUBs NoFourMUBs.StageC NoFourMUBs.KernelAtlas', '']
        L.append('theorem tslabs : ∀ c1 ∈ L1, slabT cfg tcfg true true leafT c1 L2 L3 L4 L5 = true := by')
        L.append('  intro c1 hc1')
        L.append('  simp only [L1, List.mem_cons, List.mem_nil_iff, or_false] at hc1')
        L.append('  rcases hc1 with %s' % ' | '.join(['rfl'] * 12))
        for b1 in range(12):
            L.append('  · refine slabT_of_sub fun c2 hc2 => ?_')
            L.append('    simp only [L2, List.mem_cons, List.mem_nil_iff, or_false] at hc2')
            L.append('    rcases hc2 with %s' % ' | '.join(['rfl'] * 12))
            L.append('    exacts [%s]' % ', '.join('tsub_%d_%d' % (b1, b2) for b2 in range(12)))
        L.append('')
        L.append('theorem coverT {rH n r rF K : ℝ} (hK0 : 0 ≤ K)')
        L.append('    (hK : ∀ z, cnorm (Qop ((1 / (2 * Real.pi)) • Pmat tab.pq) z) ≤ K * cnorm z)')
        L.append('    (hKb : K ≤ pq.Kbar) (hr : r ≤ pq.rbar) (hrF : rF ≤ pq.rFbar) (hrH : rH ≤ tq.rHbar) (hn : n ≤ tq.nbar) :')
        L.append('    ∀ β : I6 → ℝ, β j0 = 0 → (∀ j, 0 ≤ β j ∧ β j ≤ 1) →')
        L.append('      Covered (Pmat tab.pq) (Tmat tcfg tq) rH n r rF cfg.W0 leafT β := by')
        L.append('  obtain ⟨hW, h1, h2, h3, h4, h5⟩ := tabB_spec tabOK')
        L.append('  obtain ⟨r1, r2, r3, r4, r5⟩ := rootsOK')
        L.append('  exact topT_sound parOK tparOK hW hK0 hK hKb hr hrF hrH hn true true leafT h1 h2 h3 h4 h5 r1 r2 r3 r4 r5 tslabs')
        L.append('')
        L.append('end %s' % base)
        with open(os.path.join(a.out, 'TangentCover.lean'), 'w') as f:
            f.write('\n'.join(L) + '\n')
    print(json.dumps(dict(idx=a.idx, L=tc.L, OT=tc.OT, preflight=pre, **info), indent=1))


if __name__ == '__main__':
    main()

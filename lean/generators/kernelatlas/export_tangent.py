"""Export the tangent-test (Stage C, C2(b)) kernel data of one atlas Record (KernelAtlas/Tangent.lean).

Usage: python3 export_tangent.py <record index> <out dir> [--subs 0,8 6,2 ...] [--all] [--preflight]

Requires the bin-tree data module of the same Record (export_record.py: `<out dir>/Data.lean`, same p, q).  Writes
  * `TangentData.lean`: `tcfg : TCfg` and `tq : TParQ` (lane radix, offsets, the exact integer frame T' = DT T + OT,
    per-depth coefficients) and `tparOK : TParOK cfg pq tcfg tq` by `decide +kernel`;
  * `TangentSub.lean`: one kernel declaration per selected sub-slab `(b1, b2)`
    `slabT cfg tcfg true true leafT T1_b1 [T2_b2] L3 L4 L5 = true` (direct test, tangent test, children);
  * with --all: `TangentSlabNN.lean` (12 modules, 12 declarations each) and `TangentCover.lean`, the end-to-end
    theorem for the Record.
The constants come from ktangent.py, an exact mirror of the Lean definitions; the kernel re-derives every claim.
Pre-flight (--preflight): the mirror's counts of direct tests, tangent tests and survivors, per selected sub-slab.
"""
import argparse, gzip, json, math, os, sys, time
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, 'proof', 'atlas'))
import kbins as KB
import ktangent as KT
from export_record import q_lit, radii

DT = 36 * 2 ** 30          # T = T^ / DT exactly (Tint in units 2^-30, horizontal projector in units 1/36)


def record_data(idx, p=28, q=20):
    import numpy as np
    from ballrecord import BallRecord
    d = json.load(gzip.open(os.path.join(ROOT, 'proof/atlas/results/atlas_certificate.json.gz'), 'rt'))
    rec = d['records'][idx]
    phi = [float.fromhex(x) for x in rec['phi']]
    Prad = [[Fr(phi[6 * j + i]) for i in range(6)] for j in range(6)]
    rcol, rF, rH, n0 = radii(rec)              # kernel normal-bound radii (knormal.py)
    B = BallRecord(np.array(phi), Tint=rec.get('Tint'))
    That = [[[0] * 6 for _ in range(6)] for _ in range(4)]
    for k in range(B.rec.dimT):
        for j in range(6):
            for i in range(6):
                x = B.rec.TB[k][6 * j + i] * DT
                assert x.denominator == 1
                That[k][j][i] = int(x)
    up = lambda x: KB.dyadic_up(Fr(x) * (1 + Fr(1, 10 ** 9)) / (2 * KB.PI_LO))
    rbar, rFbar, rHbar, nbar = up(rcol), up(rF), up(rH), up(n0)
    Kbar = 1 + Fr(1, 10 ** 9)
    EU = KB.eu_table(p)
    EP = KB.ep_table(Prad, p)
    epsU, epsP = KB.eps_tables(p, Prad)
    epsU, epsP = KB.dyadic_up(epsU), KB.dyadic_up(epsP)
    par = KB.Params(p, q, rbar, rFbar, Kbar, epsU, epsP)
    R5 = KB.roots(EU, EP, p)
    W0 = []
    for i in range(6):
        W0 += [EP[0][i][0] + par.BOFF, EP[0][i][1] + par.BOFF]
    tc = KT.TCfg(par, That, DT)
    tcol = KB.dyadic_up(max(Fr(sum(abs(That[k][j][i]) for j in range(6)), DT) for k in range(4) for i in range(6)))
    tp = KT.TPar(par, tc, rHbar, nbar, tcol, KB)
    info = dict(R=rec['R'], rcol=rcol, rF=rF, rH=rH, n=n0)
    return par, tc, tp, W0, R5, info


def write_data(outdir, base, idx, par, tc, tp, info):
    L = []
    w = L.append
    w('import %s.Data' % base)
    w('import NoFourMUBs.KernelAtlas.Tangent')
    w('')
    w('/-!')
    w('# Tangent-test data for atlas Record %d' % idx)
    w('')
    w('Generated by `lean/generators/kernelatlas/export_tangent.py`; do not edit.  Stage C radii (radians): r_H = %.12g,'
      % info['rH'])
    w('n = %.6g (exact frame).  Lane radix `R = 2^%d`, frame offset `OT = %d`, scale `2^%d`.' % (info['n'], tc.L, tc.OT, tc.g))
    w('-/')
    w('')
    w('namespace %s' % base)
    w('')
    w('open NoFourMUBs.KernelAtlas')
    w('')
    w('def tcfg : TCfg where')
    w('  R := %d' % tc.R)
    w('  OT := %d' % tc.OT)
    flat = [tc.Tp[k][j][i] for k in range(4) for j in range(6) for i in range(6)]
    w('  TpL := [%s]' % ', '.join(str(x) for x in flat))
    w('  ox := %d' % tc.ox)
    w('  og := %d' % tc.og)
    w('  OX := %d' % tc.OXp)
    w('  OG := %d' % tc.OGp)
    w('  c1 := %d' % tc.c1)
    w('  c0 := %d' % tc.c0)
    w('  ke := %d' % tp.ke)
    w('  g := %d' % tc.g)
    w('  lv := fun d => match d with')
    for dd in range(4):
        w('    | %s => ⟨%s⟩' % (str(dd) if dd < 3 else '_', ', '.join(str(x) for x in tp.lv[dd])))
    w('')
    w('def tq : TParQ where')
    w('  DT := %d' % DT)
    for nm, val in (('rHbar', tp.rHbar), ('nbar', tp.nbar), ('tcol', tp.tcol)):
        w('  %s := %s' % (nm, q_lit(val)))
    w('')
    w('theorem tparOK : TParOK cfg pq tcfg tq := by decide +kernel')
    w('')
    w('end %s' % base)
    with open(os.path.join(outdir, 'TangentData.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')


def write_labels(outdir, base, idx, par, tc, tp, W0, R5):
    """Cluster the kernel survivors (klabels.py) and write `LabelData.lean`: the label list and `labsOK`."""
    import klabels as KL
    rec = json.load(gzip.open(os.path.join(ROOT, 'proof/atlas/results/atlas_certificate.json.gz'), 'rt'))['records'][idx]
    S, _ = KL.survivors(par, tc, tp, W0, R5)
    labs = KL.cluster(S, rec['label_radius'])
    tests = sum(KL.first_label(k, labs) + 1 for k in S)
    L = ['import %s.TangentData' % base, 'import NoFourMUBs.KernelAtlas.Labels', '',
         '/-! Record %d: %d labels for the %d depth-0 survivors of the kernel bin tree (generated by `klabels.py`,'
         % (idx, len(labs), len(S)),
         'label radius %s; largest s = %.6f; %d label tests in the kernel search). -/' % (rec['label_radius'],
         float(max(s for _, s, _ in labs)), tests), '', 'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas', '',
         'def labs : List Lab := [']
    rows = []
    for w, s, _ in labs:
        assert (KL.SDEN % s.denominator) == 0
        rows.append('  ⟨%d, %d, %d, %d, %d, %d⟩' % (*w, s.numerator * (KL.SDEN // s.denominator)))
    L.append(',\n'.join(rows) + ']')
    L += ['', 'theorem labsOK_ : labsOK labs = true := by decide +kernel', '', 'end %s' % base]
    with open(os.path.join(outdir, 'LabelData.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    g = write_graph(outdir, base, idx, par, [(w, s) for w, s, _ in labs])
    return dict(survivors=len(S), labels=len(labs), tests=tests, **g)


def write_graph(outdir, base, idx, par, labs):
    sys.setrecursionlimit(100000)
    """Exact mirror of `edgeOB` / `edgeUB` (direct tests) and of `noTwo`; writes `Graph.lean` and `StageC.lean`."""
    EU = KB.eu_table(par.p)
    Z = Fr(2 ** par.p)
    n = len(labs)

    def dIdx(a, b):
        return (a + 192 - b) % 192

    def tests(A, B):
        zr = EU[0][0] + sum(EU[dIdx(a, b)][0] for a, b in zip(A[0], B[0]))
        zi = EU[0][1] + sum(EU[dIdx(a, b)][1] for a, b in zip(A[0], B[0]))
        N = zr * zr + zi * zi
        sa = Fr(A[1].numerator * (2 ** 30 // A[1].denominator) + B[1].numerator * (2 ** 30 // B[1].denominator), 2 ** 30)
        c = 2 * par.pihi * KB.S6HI * sa + 6 * par.epsU
        oex = (c * Z) ** 2 < N
        uex = ((KB.S6HI + c) * Z) ** 2 < N or (0 < KB.S6LO - c and N < ((KB.S6LO - c) * Z) ** 2)
        return oex, uex
    oR, uR = [0] * n, [0] * n
    for i in range(n):
        for j in range(n):
            oex, uex = tests(labs[i], labs[j])
            if not oex:
                oR[i] |= 1 << j
            if not uex:
                uR[i] |= 1 << j
    calls = [0]

    def cl(k, fuel, cand, need, acc):
        calls[0] += 1
        if need == 0:
            return k(acc)
        if not cand:
            return False
        if fuel == 0:
            return True
        j, rest = cand[0], cand[1:]
        return (cl(k, fuel - 1, [x for x in rest if oR[j] >> x & 1], need - 1, [x for x in acc if uR[j] >> x & 1])
                or cl(k, fuel - 1, rest, need, acc))
    found = cl(lambda acc: cl(lambda _: True, n, acc, 6, []), n, list(range(n)), 6, list(range(n)))
    assert not found, 'two cliques found: Stage C fails with the direct edge tests alone'
    nO = sum(bin(x).count('1') for x in oR) // 2
    nU = sum(bin(x).count('1') for x in uR)
    L = ['import %s.LabelData' % base, 'import NoFourMUBs.KernelAtlas.StageCK', '',
         '/-! Record %d: the O/U label graph from the direct edge tests (%d O pairs, %d U arcs; generated), and the' % (idx, nO, nU),
         'two-clique search (%d calls in the mirror). -/' % calls[0], '', 'namespace %s' % base, '',
         'open NoFourMUBs.KernelAtlas', '',
         'def oRows : List ℕ := [%s]' % ', '.join(str(x) for x in oR), '',
         'def uRows : List ℕ := [%s]' % ', '.join(str(x) for x in uR), '',
         'def oR (i : ℕ) : ℕ := oRows.getD i 0', 'def uR (i : ℕ) : ℕ := uRows.getD i 0', '',
         'theorem labsSmall_ : labsSmall labs = true := by decide +kernel', '',
         'theorem edgesOK_ : edgesOK tab pq labs oR uR = true := by decide +kernel', '',
         'theorem cliqueOK_ : noTwo labs.length oR uR = true := by decide +kernel', '', 'end %s' % base]
    with open(os.path.join(outdir, 'Graph.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    L = ['import %s.TangentCover' % base, 'import %s.Graph' % base, '',
         '/-! Record %d: the Stage C certificate, from the kernel checks (generated). -/' % idx, '',
         'namespace %s' % base, '', 'open Hadamard6 NoFourMUBs NoFourMUBs.StageC NoFourMUBs.KernelAtlas', '',
         '/-- **Stage C for Record %d**, given the normal-bound radii. -/' % idx,
         'noncomputable def stageC {rH n r rF K : ℝ} (hK0 : 0 ≤ K)',
         '    (hK : ∀ z, cnorm (Qop ((1 / (2 * Real.pi)) • Pmat tab.pq) z) ≤ K * cnorm z)',
         '    (hKb : K ≤ pq.Kbar) (hr : r ≤ pq.rbar) (hrF : rF ≤ pq.rFbar) (hrH : rH ≤ tq.rHbar) (hn : n ≤ tq.nbar) :',
         '    StageCCert ((1 / (2 * Real.pi)) • Pmat tab.pq) (Tmat tcfg tq) rH n r rF :=',
         '  stageCK (coverT hK0 hK hKb hr hrF hrH hn) parOK (tabB_euB tabOK) labsOK_ labsSmall_ edgesOK_ cliqueOK_',
         '', 'end %s' % base]
    with open(os.path.join(outdir, 'StageC.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    return dict(O_pairs=nO, U_arcs=nU, clique_calls=calls[0])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('idx', type=int)
    ap.add_argument('out')
    ap.add_argument('--subs', nargs='*', default=[])
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--preflight', action='store_true')
    ap.add_argument('--module', default=None)
    ap.add_argument('--labels', action='store_true', help='cluster the survivors and use leafL (label membership)')
    a = ap.parse_args()
    base = a.module or 'NoFourMUBs.KernelAtlas.Rec%d' % a.idx
    par, tc, tp, W0, R5, info = record_data(a.idx)
    os.makedirs(a.out, exist_ok=True)
    write_data(a.out, base, a.idx, par, tc, tp, info)
    leaf, imp = 'leafT', 'TangentData'
    if a.labels:
        info['labels'] = write_labels(a.out, base, a.idx, par, tc, tp, W0, R5)
        leaf, imp = '(leafL labs)', 'LabelData'
    subs = [tuple(int(t) for t in s.split(',')) for s in a.subs]
    pre = {}
    for (b1, b2) in subs:
        if a.preflight:
            t0 = time.time()
            ok, st = KT.run(par, tc, tp, W0, R5, use_tangent=True, only=(b1, b2))
            pre['%d_%d' % (b1, b2)] = dict(ok=ok, seconds=round(time.time() - t0, 2),
                                          **{'%s_%d' % k: v for k, v in sorted(st.items())})
    if subs:
        L = ['import %s.%s' % (base, imp), '',
             '/-! Record %d: selected sub-slabs with the direct test, the tangent test and the children (generated).' % a.idx]
        for k, v in pre.items():
            L.append('Mirror `%s`: `%s`.' % (k, json.dumps(v, sort_keys=True)))
        L += ['-/', '', 'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas', '']
        for (b1, b2) in subs:
            L.append('theorem tsub_%d_%d : slabT cfg tcfg true true %s T1_%d [T2_%d] L3 L4 L5 = true := by decide +kernel'
                     % (b1, b2, leaf, b1, b2))
            L.append('')
        L.append('end %s' % base)
        with open(os.path.join(a.out, 'TangentSub.lean'), 'w') as f:
            f.write('\n'.join(L) + '\n')
    if a.all:
        for b1 in range(12):
            L = ['import %s.%s' % (base, imp), '',
                 '/-! Record %d, slab `b₁ = %d` with the tangent test: twelve sub-slabs, one kernel declaration each '
                 '(generated). -/' % (a.idx, b1), '', 'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas', '']
            for b2 in range(12):
                L.append('theorem tsub_%d_%d : slabT cfg tcfg true true %s T1_%d [T2_%d] L3 L4 L5 = true := by '
                         'decide +kernel' % (b1, b2, leaf, b1, b2))
                L.append('')
            L.append('end %s' % base)
            with open(os.path.join(a.out, 'TangentSlab%02d.lean' % b1), 'w') as f:
                f.write('\n'.join(L) + '\n')
        L = ['import %s.TangentSlab%02d' % (base, b) for b in range(12)]
        L += ['', '/-!', '# Record %d: the bin tree with the direct and the tangent test, end to end (generated)' % a.idx, '',
              'Every phase vector `β ∈ [0,1]⁵` lies in a bin that is rejected by the direct test or by the tangent test',
              '(C2(b), multiplier `y = c`) for every admissible `δ` of the Record ball with the exact frame `Tmat tcfg tq`,',
              'or in a depth-0 (`M = 96`) bin.  Hypotheses: the operator-norm bound `K` and the Stage C radii',
              '`r ≤ r̄`, `r_F ≤ r̄_F`, `r_H ≤ r̄_H`, `n ≤ n̄` (cycles), which come from the normal bound.', '-/', '',
              'namespace %s' % base, '', 'open Hadamard6 NoFourMUBs NoFourMUBs.StageC NoFourMUBs.KernelAtlas', '']
        L.append('theorem tslabs : ∀ c1 ∈ L1, slabT cfg tcfg true true %s c1 L2 L3 L4 L5 = true := by' % leaf)
        L.append('  intro c1 hc1')
        L.append('  simp only [L1, List.mem_cons, List.mem_nil_iff, or_false] at hc1')
        L.append('  rcases hc1 with %s' % ' | '.join(['rfl'] * 12))
        for b1 in range(12):
            L.append('  · refine slabT_of_sub fun c2 hc2 => ?_')
            L.append('    simp only [L2, List.mem_cons, List.mem_nil_iff, or_false] at hc2')
            L.append('    rcases hc2 with %s' % ' | '.join(['rfl'] * 12))
            L.append('    exacts [%s]' % ', '.join('tsub_%d_%d' % (b1, b2) for b2 in range(12)))
        L.append('')
        L.append('theorem coverT {rH n r rF K : ℝ} (hK0 : 0 ≤ K)')
        L.append('    (hK : ∀ z, cnorm (Qop ((1 / (2 * Real.pi)) • Pmat tab.pq) z) ≤ K * cnorm z)')
        L.append('    (hKb : K ≤ pq.Kbar) (hr : r ≤ pq.rbar) (hrF : rF ≤ pq.rFbar) (hrH : rH ≤ tq.rHbar) (hn : n ≤ tq.nbar) :')
        L.append('    ∀ β : I6 → ℝ, β j0 = 0 → (∀ j, 0 ≤ β j ∧ β j ≤ 1) →')
        L.append('      Covered (Pmat tab.pq) (Tmat tcfg tq) rH n r rF cfg.W0 %s β := by' % leaf)
        L.append('  obtain ⟨hW, h1, h2, h3, h4, h5⟩ := tabB_spec tabOK')
        L.append('  obtain ⟨r1, r2, r3, r4, r5⟩ := rootsOK')
        L.append('  exact topT_sound parOK tparOK hW hK0 hK hKb hr hrF hrH hn true true %s h1 h2 h3 h4 h5 r1 r2 r3 r4 r5 tslabs' % leaf)
        L.append('')
        L.append('end %s' % base)
        with open(os.path.join(a.out, 'TangentCover.lean'), 'w') as f:
            f.write('\n'.join(L) + '\n')
    print(json.dumps(dict(idx=a.idx, L=tc.L, OT=tc.OT, preflight=pre, **info), indent=1, default=float))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Partial sums of the nonzero-J square sum (groups of the 66 momentPoly monomials), reduced.
Emits NoFourMUBs/PRM/CoverageStripIdNonzeroDataP{g}.lean and the grouped momentPoly in
NoFourMUBs/PRM/CoverageStripIdNonzeroPart.lean.  Untrusted (kernel-checked)."""
import re
import sys
from pathlib import Path
import common  # noqa: F401
from flint import fmpq
import exact_rational as er
import critical_moment_core as core
import gen_nonzero as G
from common import frac_data, lean_horner, lean_horner_salted, lean_exps, frac_tree, frac_listz

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / 'NoFourMUBs/PRM/CoverageStripMomentData.lean').read_text()
body = src[src.index('def momentPoly (M : ℤ × ℤ → ℂ) : ℂ :=') + len('def momentPoly (M : ℤ × ℤ → ℂ) : ℂ :='):
           src.index('/-- The sum over ordered')].strip()
lines = [l.strip().rstrip('+').strip() for l in body.split('\n') if l.strip()]
assert lines[0] == '1728'
mono = lines[1:]
assert len(mono) == 65


def parse(line):
    cc = int(re.match(r'\(?(-?\d+)\)?', line).group(1))
    ms = [(int(a.strip('()')), int(b.strip('()'))) for a, b in re.findall(r'M \((\(?-?\d+\)?), (\(?-?\d+\)?)\)', line)]
    return cc, ms


Q4 = {(2, 2), (-2, -2), (4, -2), (-4, 2), (-2, 4), (2, -4)}
quart = [i for i, l in enumerate(mono) if any(p in Q4 for p in parse(l)[1])]
def has(i, q):
    return q in parse(mono[i])[1]


pairs = [((-4, 2), (4, -2)), ((2, 2), (-2, -2)), ((2, -4), (-2, 4))]
rest = [i for i in quart if i not in (0, 22)]
idx = [[i for i in range(len(mono)) if i not in quart], [0, 22]] + \
    [[i for i in rest if has(i, a) or has(i, b)] for a, b in pairs]
assert sorted(sum(idx, [])) == list(range(len(mono)))
groups = [[mono[i] for i in g] for g in idx]
NG = len(groups)
# Lean: grouped momentPoly
L = ['import NoFourMUBs.PRM.CoverageStripIdQF', '', '/-! `momentPoly` split into groups of monomials (generated by',
     '`lean/generators/stripid/gen_nonzero_part.py`). -/', '', 'noncomputable section', '',
     'namespace NoFourMUBs.PRM.Coverage.StripId', '', 'open NoFourMUBs.Kronecker StripMoments', '']
for g, grp in enumerate(groups):
    first = '1728 +\n  ' if g == 0 else ''
    L.append(f'/-- Group {g} of the monomials of `momentPoly`. -/')
    L.append(f'def partC{g} (M : ℤ × ℤ → ℂ) : ℂ :=\n  ' + first + ' +\n  '.join(grp))
    L.append(f'def partQ{g} {{n m : ℕ}} {{C : Ctx n m}} (M : ℤ × ℤ → QF C) : QF C :=\n  ' + first + ' +\n  '.join(grp))
    L.append('')
L.append('theorem momentPoly_parts (M : ℤ × ℤ → ℂ) : momentPoly M = ' +
         ' + '.join(f'partC{g} M' for g in range(NG)) + ' := by')
L.append('  simp only [momentPoly, ' + ', '.join(f'partC{g}' for g in range(NG)) + ']')
L.append('  ring')
L.append('')
L.append('set_option maxHeartbeats 1000000 in')
L.append('theorem val_partQ {n m : ℕ} {C : Ctx n m} {ρ : Fin n → ℂ} {ζ : ℂ} (h : QF.Good C ρ ζ) (M : ℤ × ℤ → QF C) :')
L.append('    ' + ' ∧ '.join(f'(partQ{g} M).val ρ ζ = partC{g} (fun p => (M p).val ρ ζ)' for g in range(NG)) + ' := by')
L.append('  refine ⟨' + ', '.join(['?_'] * NG) + '⟩ <;>')
L.append('  · simp only [' + ', '.join(f'partQ{g}' for g in range(NG)) + ', ' + ', '.join(f'partC{g}' for g in range(NG)) +
         ', QF.val_add h, QF.val_sub h, QF.val_mul h, QF.val_neg, QF.val_one\', QF.val_ofNat\']')
L.append('')
L.append('end NoFourMUBs.PRM.Coverage.StripId')
(ROOT / 'NoFourMUBs/PRM/CoverageStripIdNonzeroPart.lean').write_text('\n'.join(L) + '\n')

# data: partial sums
head = '''import NoFourMUBs.PRM.CoverageStripIdNonzeroDefs

/-! Generated by `lean/generators/stripid/gen_nonzero_part.py`; checked by the kernel. -/

set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\nset_option linter.all false

noncomputable section

namespace NoFourMUBs.PRM.Coverage.StripId.Nonzero

open NoFourMUBs.Kronecker

'''
for g, grp in enumerate(groups):
    terms = [core.Quad(1728)] if g == 0 else []
    for line in grp:
        cc, ms = parse(line)
        val = core.Quad(fmpq(cc))
        for p in ms:
            val = val * G.m[p]
        terms.append(val)
    a = er.common_sum([t.a for t in terms])
    b = er.common_sum([t.b for t in terms])
    Da, ea = frac_data(a, G.TABLE)
    Db, eb = frac_data(b, G.TABLE)
    print(g, len(Da), ea, len(Db), eb, flush=True)
    txt = (f'/-- The reduced partial sum of group {g} (generated). -/\n'
           f'def partD{g} : Q := ⟨{frac_listz(a, G.TABLE)},\n  {frac_listz(b, G.TABLE)}⟩\n')
    (ROOT / f'NoFourMUBs/PRM/CoverageStripIdNonzeroDataP{g}.lean').write_text(
        head + txt + '\nend NoFourMUBs.PRM.Coverage.StripId.Nonzero\n')

# the pair products for group 1
PA = core.Quad(G.m[(-4, 2)]) * G.m[(2, -4)]
PB = core.Quad(G.m[(-2, 4)]) * G.m[(4, -2)]
txt = ''
for nm, x in (('pA', PA), ('pB', PB)):
    Da, ea = frac_data(x.a, G.TABLE)
    Db, eb = frac_data(x.b, G.TABLE)
    txt += (f'/-- The reduced product `{nm}` (generated). -/\n'
            f'def {nm} : Q := ⟨{frac_listz(x.a, G.TABLE)},\n  {frac_listz(x.b, G.TABLE)}⟩\n\n')
(ROOT / 'NoFourMUBs/PRM/CoverageStripIdNonzeroDataPA.lean').write_text(
    head + txt + 'end NoFourMUBs.PRM.Coverage.StripId.Nonzero\n')

# split helpers: partD1a = -pA * M(2,2) (reduced), partS = groups 0..2 summed (reduced)
T1a = core.Quad(-1) * PA * G.m[(2, 2)]
S012 = []
for g in range(3):
    for line in groups[g]:
        cc, ms = parse(line)
        val = core.Quad(fmpq(cc))
        for p in ms:
            val = val * G.m[p]
        S012.append(val)
S012.append(core.Quad(1728))
sa = er.common_sum([t.a for t in S012])
sb = er.common_sum([t.b for t in S012])
for nm, (xa, xb), fn in (('partD1a', (T1a.a, T1a.b), 'P1a'), ('partS', (sa, sb), 'PS')):
    txt = (f'/-- The reduced value `{nm}` (generated). -/\n'
           f'def {nm} : Q := ⟨{frac_listz(xa, G.TABLE)},\n  {frac_listz(xb, G.TABLE)}⟩\n')
    (ROOT / f'NoFourMUBs/PRM/CoverageStripIdNonzeroData{fn}.lean').write_text(
        head + txt + '\nend NoFourMUBs.PRM.Coverage.StripId.Nonzero\n')
    print(nm, 'written')

#!/usr/bin/env python3
"""Generate NoFourMUBs/PRM/CoverageStripIdNonzeroDataH.lean: the reduced staged data of the two
halves (λ's, products, moments) for the nonzero-J identity.  Untrusted (kernel-checked)."""
from pathlib import Path
import common  # noqa: F401
import critical_moment_core as core
import gen_nonzero as G
import staged
from common import frac_data, lean_horner, lean_horner_salted, lean_exps, frac_tree, frac_listz

ROOT = Path(__file__).resolve().parents[2]
lamA, fA, mA = staged.half(G.vals, G.gp, G.zp, G.X, G.Y)
lamB, fB, mB = staged.half([-v for v in G.vals], G.gm, G.zm, G.X, G.Y)
# sanity: the staged halves reproduce the paper's halves
for p in G.USED:
    for x, y in ((mA[p], G.first[p]), (mB[p], G.second[p])):
        x, y = core.Quad(x), core.Quad(y)
        assert not (x.a - y.a).n and not (x.b - y.b).n
    s = core.Quad(mA[p]) + core.Quad(mB[p])
    assert not (s.a - G.m[p].a).n and not (s.b - G.m[p].b).n


def lean_frac(x):
    D, e = frac_data(x, G.TABLE)
    return f'⟨{lean_horner_salted(D)}, {lean_exps(e)}⟩'


DEFS = []


def lean_q(x, name):
    x = core.Quad(x)
    return f'⟨{frac_listz(x.a, G.TABLE)},\n    {frac_listz(x.b, G.TABLE)}⟩'


LAM = ['la', 'lb', 'lc', 'ba', 'bb', 'bc']
FLD = ['u', 'v', 'w', 'U', 'V', 'W', 'pi', 'PI', 'up', 'vp', 'UP', 'VP']
out = []
for H, lam, fld, mom in (('A', lamA, fA, mA), ('B', lamB, fB, mB)):
    out.append(f'/-- The `λ`s of half `{H}` (reduced, generated). -/')
    out.append(f'def lam{H} (i : ℕ) : Q :=')
    out.append('  match i with')
    for i, nm in enumerate(LAM):
        out.append(f'  | {i if i < 5 else "_"} => {lean_q(lam[nm], f"lam{H}{i}")}')
    out.append('')
    out.append(f'/-- The products of half `{H}` (reduced, generated). -/')
    out.append(f'def fld{H} (i : ℕ) : Q :=')
    out.append('  match i with')
    for i, nm in enumerate(FLD):
        out.append(f'  | {i if i < 11 else "_"} => {lean_q(fld[nm], f"fld{H}{i}")}')
    out.append('')
    out.append(f'/-- The moments of half `{H}` (reduced, generated). -/')
    out.append(f'def mom{H} (p : ℤ × ℤ) : Q :=')
    for i, p in enumerate(G.USED):
        kw = 'if' if i == 0 else 'else if'
        out.append(f'  {kw} p = {G.lean_pair(p)} then {lean_q(mom[p], f"mom{H}{i}")}')
    out.append('  else 0')
    out.append('')
head = '''import NoFourMUBs.PRM.CoverageStripIdNonzeroDefs

/-! Generated by `lean/generators/stripid/gen_nonzero_stage.py`; checked by the kernel in
`CoverageStripIdNonzeroCheckH*`. -/

set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\nset_option linter.all false

noncomputable section

namespace NoFourMUBs.PRM.Coverage.StripId.Nonzero

open NoFourMUBs.Kronecker

'''
(ROOT / 'NoFourMUBs/PRM/CoverageStripIdNonzeroDataH.lean').write_text(
    head + '\n'.join(DEFS) + '\n\n' + '\n'.join(out) + '\nend NoFourMUBs.PRM.Coverage.StripId.Nonzero\n')
print('ok')

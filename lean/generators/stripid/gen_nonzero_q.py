"""Generate NoFourMUBs/PRM/CoverageStripIdNonzeroDataQ.lean: the quotient q with
   n h⁸ + 2¹⁷ k² (3k² + 1)³ Q_h (Π ℓ)³ = q G
(n from gen_nonzero.py, Q_h = h⁴ Q(k, K), hK = XY·hZ, G = h³ (XY + XZ + YZ − XYZ − W)).  Untrusted."""
import pickle
import re
from pathlib import Path
import common  # noqa: F401
from common import QCTX, poly_dict, lean_horner, lean_horner_salted, poly_tree, lean_listz

ROOT = Path(__file__).resolve().parents[2]
SCR = Path('/private/tmp/claude-503/-Users-jtindall-Files-NoFourMUBS/c71c0e42-2268-4e63-8463-bc12919f98b3/scratchpad')
nD, ne = pickle.load(open(SCR / 'nz_n.pkl', 'rb'))
assert ne == [0, 0, 4, 5, 5, 5, 5, 5, 5, 5]
X, Y, k, _ = QCTX.gens()
h = 1 + k * k
n = QCTX.from_dict({(a, b, c, 0): v for (a, b, c), v in nD.items()})
L = [2 + 6 * k * k - (1 + k) * h * (X + Y), 6 * h + 4 * k - (1 + k) * h * (9 - Y), 6 * h + 4 * k - (1 + k) * h * (9 - X),
     2 + 6 * k * k - (1 - k) * h * (X + Y), 6 * h - 4 * k - (1 - k) * h * (9 - Y), 6 * h - 4 * k - (1 - k) * h * (9 - X)]
P = 1
for l in L:
    P = P * l
hZ = 9 * h - 4 - h * X - h * Y
Kh = X * Y * hZ
src = (ROOT / 'NoFourMUBs/PRM/CoverageQuarticDefs.lean').read_text()
body = src[src.index('def qCoeffs'):src.index('def Q ')]
QC = [tuple(map(int, mm)) for mm in re.findall(r'\((-?\d+), (\d+), (\d+)\)', body)]
Qh = 0
for cc, i, j in QC:
    Qh = Qh + cc * k ** i * Kh ** j * h ** (4 - j)
G = h ** 3 * X * Y + h ** 2 * (X + Y) * hZ - h ** 2 * X * Y * hZ - 2 * (16 - 32 * h + 18 * h * h)
R = n * h ** 8 + 2 ** 17 * k ** 2 * (3 * k * k + 1) ** 3 * Qh * P ** 3
q, rem = divmod(R, G)
assert rem == 0
print('q', len(q), q.degrees())
head = '''import NoFourMUBs.PRM.CoverageStripIdNonzeroDefs

/-! Generated by `lean/generators/stripid/gen_nonzero_q.py`; checked by the kernel in
`CoverageStripIdNonzeroCheckQ`. -/

set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\nset_option linter.all false

noncomputable section

namespace NoFourMUBs.PRM.Coverage.StripId.Nonzero

open NoFourMUBs.Kronecker

'''
(ROOT / 'NoFourMUBs/PRM/CoverageStripIdNonzeroDataQ.lean').write_text(
    head + '/-- The quotient `(n h⁸ + 2¹⁷ k² (3k² + 1)³ Q_h (Π ℓ)³) / G` (generated). -/\n' +
    f'def qC : V := {lean_listz(poly_dict(q))}' + '\n\nend NoFourMUBs.PRM.Coverage.StripId.Nonzero\n')

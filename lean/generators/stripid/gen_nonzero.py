#!/usr/bin/env python3
"""Generate NoFourMUBs/PRM/CoverageStripIdNonzeroData.lean (nonzero-J strip identity data).

Untrusted: every datum is re-checked by the Lean kernel (CoverageStripIdNonzeroCheck*.lean).
Frame: s = t = 1, s̄ = X, t̄ = Y, r = ζ with Yζ² - Jζ + XZ = 0, r̄ = (J - Yζ)/X, h = 1 + k²,
J = 8k/h², Z = 9 - 4/h - X - Y; halves z± = -2(1 ± k)/h, g± = 12/h ± 8k/h².
"""
import pickle
import sys
import time
from pathlib import Path
import common  # noqa: F401  (sets the path)
from flint import fmpq
import exact_rational as er
from exact_rational import F, CTX
import critical_moment_core as core
from common import QCTX, frac_data, poly_dict, lean_horner, lean_horner_salted, lean_exps, frac_tree, poly_tree, frac_listz, lean_listz

ROOT = Path(__file__).resolve().parents[2]
SCR = Path('/private/tmp/claude-503/-Users-jtindall-Files-NoFourMUBS/c71c0e42-2268-4e63-8463-bc12919f98b3/scratchpad')
t0 = time.time()
X, Y, c, _ = [F(v) for v in CTX.gens()]
q = 4 / (1 + c * c)
J = 8 * c / (1 + c * c) ** 2
zp = -2 * (1 + c) / (1 + c * c)
zm = -2 * (1 - c) / (1 + c * c)
gp = 3 * q + J
gm = 3 * q - J
core.Z = 9 - q - X - Y
core.R2 = -X * core.Z / Y
core.R1 = J / Y
rr = core.Quad(0, 1)
vals = [core.Quad(1), core.Quad(X), core.Quad(1), core.Quad(Y), rr, (core.Quad(J) - rr * Y) / X]
first = core.side(*vals, g=gp, zz=zp)
second = core.side(*[-v for v in vals], g=gm, zz=zm)
m = {k: first[k] + second[k] for k in first}
tab = core.squared_corner_moment_coefficients()

Xp, Yp, k, _ = QCTX.gens()
h = 1 + k * k
TABLE = [Xp, Yp, h, QCTX.constant(2),
         2 + 6 * k * k - (1 + k) * h * (Xp + Yp), 6 * h + 4 * k - (1 + k) * h * (9 - Yp),
         6 * h + 4 * k - (1 + k) * h * (9 - Xp),
         2 + 6 * k * k - (1 - k) * h * (Xp + Yp), 6 * h - 4 * k - (1 - k) * h * (9 - Yp),
         6 * h - 4 * k - (1 - k) * h * (9 - Xp)]

USED = [(-4, 2), (-3, 0), (-3, 1), (-3, 2), (-3, 3), (-2, -2), (-2, -1), (-2, 0), (-2, 1), (-2, 2), (-2, 3),
        (-2, 4), (-1, -2), (-1, -1), (-1, 2), (-1, 3), (0, -3), (0, -2), (0, 2), (0, 3), (1, -3), (1, -2),
        (1, 1), (1, 2), (2, -4), (2, -3), (2, -2), (2, -1), (2, 0), (2, 1), (2, 2), (3, -3), (3, -2), (3, -1),
        (3, 0), (4, -2)]


def lean_pair(p):
    return '(' + ', '.join(f'({v})' if v < 0 else str(v) for v in p) + ')'


def lean_frac(x):
    D, e = frac_data(x, TABLE)
    return f'⟨{lean_horner_salted(D)}, {lean_exps(e)}⟩'


if __name__ == '__main__':
    out = []
    branches = []
    for i, p in enumerate(USED):
        v = m[p]
        f0, f1 = frac_listz(v.a, TABLE), frac_listz(v.b, TABLE)
        kw = 'if' if i == 0 else 'else if'
        branches.append(f'  {kw} p = {lean_pair(p)} then ⟨{f0}, {f1}⟩')
    out.append('/-- The combined moments `M_A + M_B`, reduced (generated). -/')
    out.append('def mD (p : ℤ × ℤ) : Q :=')
    out += branches
    out.append('  else 0')
    print('moments', time.time() - t0, flush=True)
    terms = []
    for key, cc in tab.items():
        val = core.Quad(fmpq(str(cc)))
        for p in key:
            val = val * m[p]
        terms.append(val)
    a = er.common_sum([t.a for t in terms])
    b = er.common_sum([t.b for t in terms])
    assert not b.n
    nD, ne = frac_data(a, TABLE)
    print('n', len(nD), ne, time.time() - t0, flush=True)
    pickle.dump((nD, ne), open(SCR / 'nz_n.pkl', 'wb'))
    head = '''import NoFourMUBs.PRM.CoverageStripIdNonzeroDefs

/-! Generated by `lean/generators/stripid/gen_nonzero.py`; checked by the kernel in
`CoverageStripIdNonzeroCheck*`. -/

set_option maxRecDepth 1000000\nset_option maxHeartbeats 0\nset_option linter.all false

noncomputable section

namespace NoFourMUBs.PRM.Coverage.StripId.Nonzero

open NoFourMUBs.Kronecker

'''
    tail = '\n\nend NoFourMUBs.PRM.Coverage.StripId.Nonzero\n'
    (ROOT / 'NoFourMUBs/PRM/CoverageStripIdNonzeroData.lean').write_text(head + '\n'.join(out) + tail)
    (ROOT / 'NoFourMUBs/PRM/CoverageStripIdNonzeroDataN.lean').write_text(
        head.replace('CoverageStripIdNonzeroDefs', 'CoverageStripIdNonzeroData') +
        '/-- The numerator of the square sum over `2⁵ h⁴ Π ℓ⁵` (generated). -/\n' +
        f'def nC : V := {lean_listz(nD)}' + tail)

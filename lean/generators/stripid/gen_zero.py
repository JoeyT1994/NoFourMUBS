#!/usr/bin/env python3
"""Generate NoFourMUBs/PRM/CoverageStripIdZeroData.lean (zero-J strip identity data).

Untrusted: every datum is re-checked by the Lean kernel (CoverageStripIdZeroCheck*.lean).
Frame: s = t = 1, s̄ = X, t̄ = Y, r = ζ with ζ² = -XZ/Y, r̄ = -Yζ/X, Z = 9 - z² - X - Y (J = 0).
"""
import time
from pathlib import Path
import common  # noqa: F401  (sets the path)
from flint import fmpq
import exact_rational as er
from exact_rational import F, CTX
import critical_moment_core as core
from common import QCTX, frac_data, poly_dict, lean_horner, lean_exps

ROOT = Path(__file__).resolve().parents[2]
t0 = time.time()
X, Y, z, _ = [F(v) for v in CTX.gens()]
q = z * z
J = F(0)
core.Z = 9 - q - X - Y
core.R2 = -X * core.Z / Y
core.R1 = J / Y
rr = core.Quad(0, 1)
vals = [core.Quad(1), core.Quad(X), core.Quad(1), core.Quad(Y), rr, (core.Quad(J) - rr * Y) / X]
first = core.side(*vals, g=3 * q, zz=z)
second = core.side(*[-v for v in vals], g=3 * q, zz=z)
m = {k: first[k] + second[k] for k in first}
tab = core.squared_corner_moment_coefficients()

Xp, Yp, zp, _ = QCTX.gens()
TABLE = [Xp, Yp, zp, Xp + Yp + zp ** 2 + 3 * zp, 3 * zp + 9 - Yp, 3 * zp + 9 - Xp]

USED = [(-4, 2), (-3, 0), (-3, 1), (-3, 2), (-3, 3), (-2, -2), (-2, -1), (-2, 0), (-2, 1), (-2, 2), (-2, 3),
        (-2, 4), (-1, -2), (-1, -1), (-1, 2), (-1, 3), (0, -3), (0, -2), (0, 2), (0, 3), (1, -3), (1, -2),
        (1, 1), (1, 2), (2, -4), (2, -3), (2, -2), (2, -1), (2, 0), (2, 1), (2, 2), (3, -3), (3, -2), (3, -1),
        (3, 0), (4, -2)]


def lean_pair(p):
    return '(' + ', '.join(f'({v})' if v < 0 else str(v) for v in p) + ')'


def lean_frac(x):
    D, e = frac_data(x, TABLE)
    return f'⟨{lean_horner(D)}, {lean_exps(e)}⟩'


out = []
out.append('/-- The combined moments `M_A + M_B`, reduced (generated). -/')
out.append('def mD (p : ℤ × ℤ) : Q :=')
for i, p in enumerate(USED):
    v = m[p]
    kw = 'if' if i == 0 else 'else if'
    out.append(f'  {kw} p = {lean_pair(p)} then ⟨{lean_frac(v.a)},\n    {lean_frac(v.b)}⟩')
out.append('  else 0')

# the whole-strip sum
terms = []
for key, c in tab.items():
    val = core.Quad(fmpq(str(c)))
    for p in key:
        val = val * m[p]
    terms.append(val)
a = er.common_sum([t.a for t in terms])
b = er.common_sum([t.b for t in terms])
assert not b.n
nD, ne = frac_data(a, TABLE)
assert ne == [0, 0, 12, 5, 5, 5], ne
out.append('')
out.append('/-- The numerator of the square sum over `z¹² (e₀e₁e₂)⁵` (generated). -/')
out.append(f'def nC : V := {lean_horner(nD)}')

Zp = 9 - zp ** 2 - Xp - Yp
Kp = Xp * Yp * Zp
G = Xp * Yp + Xp * Zp + Yp * Zp - Xp * Yp * Zp - zp ** 2 * (zp + 3) ** 2
Bp = zp ** 2 * (zp + 3) ** 4 + (zp + 2) ** 2 * Kp
T = -3888 * zp * (zp + 2) ** 2 * (zp + 3) ** 2 * (Kp + (zp - 1) * (zp + 3) ** 3) * Bp ** 2
E = TABLE[3] * TABLE[4] * TABLE[5]
num = QCTX.from_dict({(k[0], k[1], k[2], 0): v for k, v in nD.items()})
R = num - T * zp ** 12 * E ** 2
q2, rem = divmod(R, G)
assert rem == 0
out.append('')
out.append('/-- The quotient `(n − T z¹² E²) / G` (generated). -/')
out.append(f'def q2C : V := {lean_horner(poly_dict(q2))}')

head = '''import NoFourMUBs.PRM.CoverageStripIdZeroDefs

/-! Generated by `lean/generators/stripid/gen_zero.py`; checked by the kernel in
`CoverageStripIdZeroCheck*`. -/

set_option maxRecDepth 100000

noncomputable section

namespace NoFourMUBs.PRM.Coverage.StripId.Zero

open NoFourMUBs.Kronecker

'''
(ROOT / 'NoFourMUBs/PRM/CoverageStripIdZeroData.lean').write_text(
    head + '\n'.join(out) + '\n\nend NoFourMUBs.PRM.Coverage.StripId.Zero\n')
print('done', time.time() - t0)

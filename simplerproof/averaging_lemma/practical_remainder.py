"""Rational remainder audit for the practical near-F6 implication at M<5.

Consumes exact jets regenerated by practical_local_jet.py and
practical_cubic_bound.py. Every inequality below uses exact rationals.
"""
from fractions import Fraction as Q
from itertools import combinations,combinations_with_replacement,product
from pathlib import Path
from collections import defaultdict
import importlib.util,json,math,sys,time,argparse
import sympy as S

HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]
sys.path.insert(0,str(ROOT/'ProvenResults/FourierCornerRigidity'))
from exact_algebra import determinant_terms


def sqrt_upper(q,scale=10**6):
    q=Q(q);n=math.isqrt(q.numerator*scale*scale//q.denominator)+1
    ans=Q(n,scale);assert ans*ans>=q
    return ans


def run(rho=Q(1,5), error_cap=Q(1,3), threshold=Q(99,500), output='practical_remainder.json', s_min=None, s_max=None):
    started=time.monotonic()
    second=json.loads((HERE/'practical_local_jet.json').read_text())
    third=json.loads((HERE/'practical_cubic_bound.json').read_text())
    spec=importlib.util.spec_from_file_location('tangent_source_remainder',ROOT/'RouteC/averaging/task2_hessian_exact.py')
    source=importlib.util.module_from_spec(spec);spec.loader.exec_module(source)
    T=S.Matrix.hstack(*(S.Matrix(source.gauge_project(t)).reshape(36,1) for t in source.tangent_basis()))
    N2=S.Matrix(second['normal_quadratic_over_sqrt3']);N3=S.Matrix(third['normal_cubic'])
    z=S.symbols('a b c d');m2=list(combinations_with_replacement(range(4),2));m3=list(combinations_with_replacement(range(4),3))
    n2=N2*S.Matrix([S.prod(z[j] for j in m) for m in m2])
    n3=N3*S.Matrix([S.prod(z[j] for j in m) for m in m3])
    q1=z[0]**2-z[0]*z[1]+z[1]**2;q2=z[2]**2-z[2]*z[3]+z[3]**2
    assert S.expand(3*(n2.T*n2)[0]-S.Rational(4,3)*q1*q2)==0
    assert S.expand((n3.T*n3)[0]-q1*q2*(q1+q2)/9)==0
    co=list(map(S.Rational,[1,'1/2','-1/2',-1,'-1/2','1/2']))
    si=list(map(S.Rational,[0,'1/2','1/2',0,'-1/2','-1/2']))
    J=[]
    for i,j in combinations(range(6),2):
        jr=[S.Integer(0)]*36;ji=jr.copy()
        for c in range(6):
            k=(i-j)*c%6
            jr[6*i+c]=-si[k];jr[6*j+c]=si[k]
            ji[6*i+c]=co[k];ji[6*j+c]=-co[k]
        J.extend([jr,ji])
    J=S.Matrix(J);C=S.eye(6)-S.ones(6)/6;Pi=S.kronecker_product(C,C)
    PN=Pi-T*(T.T*T).inv()*T.T;G=J.T*S.diag(*([3,1]*15))*J
    eigen=G.eigenvals()
    assert min(x for x in eigen if x>0)==3 and eigen[0]==15
    print('exact Gram spectrum:',{str(k):v for k,v in eigen.items()},flush=True)

    smax=2*rho if s_max is None else s_max
    c=Q(49,60);c1=c;c2=Q(1,10);c3=Q(1,88);f3=Q(7,18);f4=Q(49,360)
    assert c*c>Q(2,3) and c2*c2>Q(1,108) and c3*c3>Q(1,7776)
    assert f3*f3>Q(4,27) and f4*f4>Q(1,54)
    if s_min is not None:c1=min(c1,rho/s_min)
    # The segment joins the ACTUAL u (known only to satisfy ||u||<=rho)
    # to u3. A bound on u3 alone is not a bound on that whole segment.
    radius=max(rho,min(rho,Q(49,60)*smax)+c2*smax**2+c3*smax**3)
    contraction=2*c*radius
    assert contraction<1
    t=c2+c3*smax
    residual4=2*c*c1*c3+c*t*t+f3*(3*c1*c1*t+3*c1*t*t*smax+t**3*smax**2)+f4*(c1+c2*smax+c3*smax**2)**4
    error4=residual4/(1-contraction)
    if error_cap is None:error_cap=Q(math.ceil(error4*1000),1000)
    assert error4<=error_cap, (float(error4),float(error_cap))

    verts=[(S.Rational(2,3),S.Rational(1,3)),(S.Rational(1,3),S.Rational(2,3)),
           (S.Rational(-1,3),S.Rational(1,3)),(S.Rational(-2,3),S.Rational(-1,3)),
           (S.Rational(-1,3),S.Rational(-2,3)),(S.Rational(1,3),S.Rational(-1,3))]
    def transform(degree,v):
        mon=list(combinations_with_replacement(range(4),degree));lookup={m:i for i,m in enumerate(mon)}
        out=S.zeros(len(mon),len(mon))
        for a,m in enumerate(mon):
            for idx in product(range(4),repeat=degree):
                out[a,lookup[tuple(sorted(idx))]]+=S.prod(v[idx[k]][m[k]] for k in range(degree))
        for col,m in enumerate(mon):
            multiplicity=math.factorial(degree)
            for k in set(m):multiplicity//=math.factorial(m.count(k))
            out[:,col]/=multiplicity
        return out
    terms=determinant_terms();sectors=[]
    assert all(abs(v)==1 for v in terms.values())
    for sec in third['sectors']:
        i,j=sec['i'],sec['j'];v=[verts[i]+(0,0),verts[(i+1)%6]+(0,0),(0,0)+verts[j],(0,0)+verts[(j+1)%6]]
        tv=T*S.Matrix(v).T;nb2=N2*transform(2,v);nb3=N3*transform(3,v)
        direct4=Q(0);grad=Q(0);linear=S.zeros(1,36)
        for sign,idx in zip([1,-1],sec['corners']):
            rec=second['corner_records'][idx];rr,cc=rec['rows'],rec['cols']
            indices=[6*r+s for r in rr for s in cc]
            for (a,b,c_,d),coef in terms.items():
                raw=(a+b+c_+d,-a-c_,-b-d,-a-b,a,b,-c_-d,c_,d)
                ell=S.zeros(1,36)
                for n,e in zip(indices,raw):ell[n]=e
                k=sum(r*s*e for (r,s),e in zip(product(rr,cc),raw))%6
                linear+=S.Rational(sign*coef,2)*co[k]*ell
                x=Q(max(abs(t) for t in ell*tv))
                y=Q(7,4)*Q(max(abs(t) for t in ell*nb2))
                zz=Q(max(abs(t) for t in ell*nb3))
                yl=y+zz*smax
                trig_sin=Q(7,4)*abs(Q(si[k]));trig_cos=abs(Q(co[k]))
                one=trig_sin*(x*zz+yl*yl/2)+trig_cos*(3*x*x*yl+3*x*yl*yl*smax+yl**3*smax**2)/6+(x+y*smax+zz*smax**2)**4/24
                direct4+=one/2
                normalnorm=sqrt_upper((ell*PN*ell.T)[0])
                grad+=normalnorm*(smax*(x+y*smax+zz*smax**2)+normalnorm*error_cap*smax**4)/2
        normal_linear=sqrt_upper((linear*PN*linear.T)[0])
        grad+=normal_linear
        total4=direct4+grad*error_cap
        sectors.append(dict(i=i,j=j,direct4=str(direct4),gradient=str(grad),
            normal_linear=str(normal_linear),total4=str(total4),total4_decimal=float(total4)))
    maximum=max(Q(x['total4']) for x in sectors)
    # The next inequalities are the desired finite-radius gate. Record a
    # failure honestly so the next iteration targets the actual bottleneck.
    lower=lambda s:12*s-2*s**3-maximum*s**4
    distance=threshold/6+(Q(1,200)+Q(5,1056))*threshold**3+Q(5,12)*error_cap*threshold**4
    lower_endpoint=threshold if s_min is None else s_min
    annulus=(lower(lower_endpoint)>0 and lower(lower_endpoint)**2>5 and
                lower(smax)>0 and lower(smax)**2>5)
    sufficient=annulus and distance<Q(1,30)
    report=dict(scope='Rational remainder bounds for ||horizontal phase||<='+str(rho),
        rho=str(rho),S_threshold=str(threshold),normal_error_cap=str(error_cap),
        S_interval=[str(lower_endpoint),str(smax)],
        annulus_exclusion_passed=annulus,inner_distance_passed=distance<Q(1,30),
        local_cutoff_5_gate_passed=sufficient,global_cover_complete=False,
        Gram_eigenvalues={str(k):v for k,v in eigen.items()},normal_error_order4=str(error4),
        maximum_paired_remainder_order4=str(maximum),maximum_paired_remainder_decimal=float(maximum),
        lower_at_threshold=str(lower(lower_endpoint)),lower_at_outer_S=str(lower(smax)),
        distance_bound=str(distance),distance_decimal=float(distance),sectors=sectors,
        seconds=time.monotonic()-started)
    (HERE/output).write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items() if k!='sectors'},indent=2))
    return report


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--rho',default='1/5');p.add_argument('--error-cap',default='1/3')
    p.add_argument('--threshold',default='99/500');p.add_argument('--output',default='practical_remainder.json')
    p.add_argument('--s-min');p.add_argument('--s-max')
    args=p.parse_args();run(Q(args.rho),None if args.error_cap=='auto' else Q(args.error_cap),Q(args.threshold),args.output,
        None if args.s_min is None else Q(args.s_min),None if args.s_max is None else Q(args.s_max))

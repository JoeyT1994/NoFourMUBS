#!/usr/bin/env python3
"""Exact algebra and rational interval checks for FOLD_BRANCH.md.

All acceptance decisions use integers, rational polynomials, or rational
intervals. The Fourier input is independently regenerated by verify_maxima.py.
"""
from fractions import Fraction
from pathlib import Path
import json
import sympy as s

HERE = Path(__file__).resolve().parent
p, j, w, t = s.symbols('p j w t')
x, y, z, q = s.symbols('x y z q')
g = 27 - 3*p + j
eta = 9 - p + j
chi = w - (p-9)*(p-18) + (p-15)*j
F = s.expand(4*g*g*eta - chi*chi)
T = F.subs(j, -j)
comp = {p:x+y+z, w:x*y+x*z+y*z-x*y*z}
R4 = F.subs(comp)
T4 = T.subs(comp)


def same(a, b):
    assert s.cancel(a-b) == 0, (a,b)


def frac(a):
    a = s.Rational(a)
    return Fraction(int(a.p), int(a.q))


def mul(A, B):
    v = [a*b for a in A for b in B]
    return min(v), max(v)


def enclose(poly, lo, hi):
    ans = (Fraction(0), Fraction(0))
    for c in s.Poly(poly, t).all_coeffs():
        v = mul(ans, (lo,hi))
        c = frac(c)
        ans = (v[0]+c, v[1]+c)
    return ans


def variations(signs):
    signs = [i for i in signs if i]
    return sum(a != b for a,b in zip(signs, signs[1:]))


def sturm_count(poly, lo=None, hi=None):
    seq = [s.Poly(a,t) for a in s.sturm(poly,t)]
    def signs_at(value, direction):
        if value is None:
            return [int(s.sign(a.LC())) *
                    ((-1)**a.degree() if direction < 0 else 1) for a in seq]
        return [int(s.sign(a.eval(s.Rational(value.numerator,value.denominator))))
                for a in seq]
    return variations(signs_at(lo,-1))-variations(signs_at(hi,1))


def verify_stationarity():
    j0 = 9-p-t*t
    w0 = -(t+3)*(p*t+p-2*t*t-9*t-9)
    gh = 18-2*p+t*t
    same(T.subs({j:j0,w:w0}),0)
    same(chi.subs(j,-j).subs({j:j0,w:w0}),2*gh*t)
    f = -4*(p+t*t-9)*(p+t*t+6*t+9)*(p*p-2*p*t-16*p+2*t*t+18*t+63)
    same(F.subs({j:j0,w:w0}),f)
    fp, ft = s.diff(f,p), s.diff(f,t)
    basis = list(s.groebner([fp,ft],p,t,order='lex'))
    assert len(basis) == 2
    sextic = 9*t**6+135*t**5+854*t**4+2838*t**3+5070*t*t+4392*t+1296
    expected = t**5*(t+2)*(t+3)*(t*t+6*t+12)*(t*t+8*t+24)*sextic
    same(basis[1],expected)
    pcoef = s.Poly(basis[0],p).coeff_monomial(p)
    assert pcoef != 0 and s.Poly(basis[0],p).degree() == 1
    pvalue = s.solve(basis[0],p)[0]
    for tv,pv in [(0,9),(-2,5),(-3,0)]:
        same(pvalue.subs(t,tv),pv)
        same(f.subs({t:tv,p:pv}),0)
    same(t*t+6*t+12,(t+3)**2+3)
    same(t*t+8*t+24,(t+4)**2+8)
    pred = -(45*t**5+567*t**4+2875*t**3+7005*t*t+7512*t+1674)/114
    same(s.rem(pvalue-pred,sextic,t),0)
    rred = s.rem(f.subs(p,pred),sextic,t)
    lam = s.factor(chi.subs({j:j0,w:w0})/(2*gh*t))
    n,d = s.fraction(lam)
    nr = s.rem(n.subs(p,pred),sextic,t)
    dr = s.rem(d.subs(p,pred),sextic,t)
    bounds = [
        (Fraction(-1917226736061,10**12),Fraction(-1917226736059,10**12)),
        (Fraction(-565807686229,10**12),Fraction(-565807686226,10**12)),
    ]
    assert sturm_count(sextic) == 2
    for interval in bounds:
        assert sturm_count(sextic,*interval) == 1
    positive_R = enclose(rred,*bounds[0])
    negative_R = enclose(rred,*bounds[1])
    numerator = enclose(nr,*bounds[0])
    denominator = enclose(dr,*bounds[0])
    assert positive_R[0] > 0
    assert negative_R[1] < 0
    assert ((numerator[0] > 0 and denominator[0] > 0) or
            (numerator[1] < 0 and denominator[1] < 0))
    print('PASS: exact fold stationary elimination; two real sextic roots.')
    print('PASS: one root has R<0; the other has R>0 and lambda>0.')


def verify_exceptional_invariants():
    same(T4.subs({y:x,j:x*(3-z)}),-(x-1)**2*(x-z)**2*(z-9)**2)
    equal_T = -(j+q*q-3*q)**2*(4*j+q*q+18*q-27)
    two1_T = -(j+q-3)**2*(4*j+q*q-6*q-3)
    same(T4.subs({x:q,y:q,z:q}),equal_T)
    same(T4.subs({x:1,y:1,z:q}),two1_T)
    j_equal = (27-q*q-18*q)/4
    equal_R = -(q+3)**2*(5*q-9)**2*(q*q+18*q-27)/8
    same(R4.subs({x:q,y:q,z:q,j:j_equal}),equal_R)
    same((4*x*y*z-j*j).subs({x:q,y:q,z:q,j:j_equal}),
         -(q-9)**3*(q-1)/16)
    cubic = 5*q**3+79*q*q-45*q-135
    same(s.diff(equal_R,q),-3*(q+3)*(5*q-9)*cubic/4)
    assert cubic.subs(q,s.Rational(7,5)) == -s.Rational(736,25)
    # cubic' > 0 on [1,7/5], since cubic''>0 and cubic'(1)>0.
    assert s.diff(cubic,q).subs(q,1) > 0
    assert s.diff(cubic,q,2).subs(q,1) > 0
    assert s.diff(cubic,q,3) > 0
    assert (q*q+18*q-27).subs(q,s.Rational(7,5)) > 0
    # At (1,1,q), Hessian(W) has both signs on sum-zero directions.
    W = comp[w]
    H = s.hessian(W,(x,y,z)).subs({x:1,y:1,z:q})
    a,b = s.Matrix([1,-1,0]),s.Matrix([1,1,-2])
    same((a.T*H*a)[0],2*(q-1))
    same((b.T*H*b)[0],-2*(q-1))
    print('PASS: exceptional invariant factorizations and transverse Hessian signs.')


def verify_two1_pole_family():
    A,U = s.symbols('A U', nonzero=True)
    data = json.loads((HERE.parent/'inputs/rfourier.json').read_text())
    values=[]
    for which in [-1,0,1,2,3]:
        terms={}
        for k1,k2,k3,k4,re,im in data:
            assert s.Rational(im) == 0
            coeff=s.Rational(re)*(-1)**((k2+k4)%2)
            if which >= 0:
                coeff *= (k1,k2,k3,k4)[which]
            key=(k1+k2+k3+k4,k3+k4)
            terms[key]=terms.get(key,0)+coeff
        values.append(s.factor(sum(c*A**k[0]*U**k[1]
                                   for k,c in terms.items() if c)))
    same(values[0],-64*(U*U+1)*(U*U+U+1)**2*(U*U+4*U+1)/U**4)
    # R>0 implies A,U and U^2+U+1 are nonzero, so these removals are valid.
    polys=[s.cancel(v*A*U**4/(64*(U*U+U+1))) for v in values[1:]]
    assert all(s.denom(v) == 1 for v in polys)
    basis=list(s.groebner(polys,A,U,order='lex'))
    assert basis == [A*A-1,U*U-1]
    print('PASS: at a two-one pole, seed stationarity forces A^2=U^2=1, hence Q=0.')


if __name__ == '__main__':
    verify_stationarity()
    verify_exceptional_invariants()
    verify_two1_pole_family()
    print('PASS: fold branch algebra (geometric lifting and pole classification are proved in the text).')

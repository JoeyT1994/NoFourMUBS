"""Normal-bound data of one Record for the kernel (`FrameK.lean`, ...).

Frame part: the exact frame T = That / DT (rows j, columns i), its Gram matrix G, and the rational constants of
`frameOK`: e_G >= ||G - I||_F, g with g^2 (1 - e_G) >= 1, lam = 1 + e_G, t^2 >= the absolute row sums of every
column Gram, and the exact inverse Gi = G^{-1}.
"""
import math, os
from fractions import Fraction as Fr

SDEN = 2 ** 40


def mod(base):
    """The Lean module path of a generated namespace `NoFourMUBs.KernelAtlas.RecN` (library `KernelAtlas`)."""
    return base.replace('NoFourMUBs.KernelAtlas.', 'KernelAtlas.', 1)


def dy_up(x, den=SDEN):
    """Smallest k/den >= x."""
    x = Fr(x)
    return Fr(-((-x.numerator * den) // x.denominator), den)


def sqrt_up(x, den=SDEN):
    """A dyadic >= sqrt(x) (x a nonnegative Fraction)."""
    s = dy_up(Fr(math.sqrt(float(x))) * (1 + Fr(1, 10 ** 12)), den)
    while s * s < x:
        s += Fr(1, den)
    return s


def inv4(G):
    """Exact inverse of a 4x4 Fraction matrix (Gauss-Jordan)."""
    n = 4
    A = [list(G[i]) + [Fr(int(i == j)) for j in range(n)] for i in range(n)]
    for c in range(n):
        p = next(r for r in range(c, n) if A[r][c] != 0)
        A[c], A[p] = A[p], A[c]
        piv = A[c][c]
        A[c] = [x / piv for x in A[c]]
        for r in range(n):
            if r != c and A[r][c] != 0:
                f = A[r][c]
                A[r] = [x - f * y for x, y in zip(A[r], A[c])]
    return [row[n:] for row in A]


def frame_consts(That, DT):
    F = [[[Fr(That[k][j][i], DT) for i in range(6)] for j in range(6)] for k in range(4)]
    G = [[sum(F[k][j][i] * F[l][j][i] for j in range(6) for i in range(6)) for l in range(4)] for k in range(4)]
    E2 = sum((G[k][l] - (1 if k == l else 0)) ** 2 for k in range(4) for l in range(4))
    eG = sqrt_up(E2)
    assert eG < 1
    g = sqrt_up(1 / (1 - eG))
    lam = 1 + eG
    tt = max(sum(abs(sum(F[k][j][i] * F[l][j][i] for j in range(6))) for l in range(4)) for i in range(6) for k in range(4))
    t = sqrt_up(tt)
    Gi = inv4(G)
    assert all(sum(G[k][l] * Gi[l][m] for l in range(4)) == (1 if k == m else 0) for k in range(4) for m in range(4))
    return dict(F=F, G=G, eG=eG, g=g, lam=lam, t=t, Gi=Gi)


def q_lit(x):
    x = Fr(x)
    return '(%d : ℚ)' % x.numerator if x.denominator == 1 else '((%d : ℚ) / %d)' % (x.numerator, x.denominator)


def write_frame(outdir, base, idx, That, DT):
    fc = frame_consts(That, DT)
    L = ['import %s.TangentData' % mod(base), 'import KernelAtlas.FrameK', '',
         '/-! Record %d: the frame constants of the normal bound (generated by `knormal.py`):' % idx,
         '`e_G = %.3e`, `g = %.12f`, `λ = %.12f`, `t = %.9f`. -/' % (fc['eG'], fc['g'], fc['lam'], fc['t']), '',
         'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas', '',
         'def fq : FrameQ where',
         '  eG := %s' % q_lit(fc['eG']), '  g := %s' % q_lit(fc['g']), '  lam := %s' % q_lit(fc['lam']),
         '  t := %s' % q_lit(fc['t']),
         '  Gi := ![%s]' % ', '.join('![%s]' % ', '.join(q_lit(x) for x in row) for row in fc['Gi']), '',
         'theorem frameOK_ : frameOK (frameOf tcfg tq) fq = true := by decide +kernel', '', 'end %s' % base]
    with open(os.path.join(outdir, 'Frame.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    return dict(eG=float(fc['eG']), g=float(fc['g']), lam=float(fc['lam']), t=float(fc['t']))


# ---------------------------------------------------------------- sigma (SigmaK.lean)
PN, NTN = 64, 60            # precision and Taylor order of the normal-bound table `tabN`
LDEN = 40


def tabN_data(Prad):
    import kbins as KB
    X = [[KB.cis_round(-Prad[j][i], PN, NTN) for i in range(6)] for j in range(6)]
    for j in range(6):
        for i in range(6):
            assert abs(Prad[j][i]) / (NTN + 1) <= Fr(1, 2)
    eps = dy_up(max(KB.taylor_rem(-Prad[j][i], NTN) for j in range(6) for i in range(6)) + Fr(1, 2 ** PN))
    return X, eps


def omega_gamma(eps):
    om = eps * (1 + eps) + eps
    return om, om * (1 + om) + om


def sigma_cert(X, eps, F, sigma, cpen=Fr(10), tau=1e-3):
    """The exact mirror of `sigmaOK`: returns (s, Lrows) or raises."""
    import numpy as np
    om, gam = omega_gamma(eps)
    s = sigma * sigma + 36 * gam
    W = [[[(X[a][c][0] * X[b][c][0] + X[a][c][1] * X[b][c][1], X[a][c][0] * X[b][c][1] - X[a][c][1] * X[b][c][0])
           for c in range(6)] for b in range(6)] for a in range(6)]
    D4 = Fr(1, 2 ** (4 * PN))
    cq = lambda a, b, c, c2: Fr(W[a][b][c][0] * W[a][b][c2][0] + W[a][b][c][1] * W[a][b][c2][1]) * D4
    def mt(p, q, p2, q2):
        v = -cq(p, p2, q, q2) - cq(p2, p, q, q2)
        if p == p2:
            v += sum(cq(p, b, q, q2) for b in range(6)) + sum(cq(a, p, q, q2) for a in range(6))
        return v / 2
    def aq(p, q, p2, q2):
        return int(p == p2) + int(q == q2) + sum(F[k][p][q] * F[k][p2][q2] for k in range(4))
    N = [[mt(x // 6, x % 6, y // 6, y % 6) + cpen * aq(x // 6, x % 6, y // 6, y % 6) - (s if x == y else 0)
          for y in range(36)] for x in range(36)]
    Lf = np.linalg.cholesky(np.array([[float(v) for v in row] for row in N]) - tau * np.eye(36))
    Li = [[int(round(Lf[x][z] * 2 ** LDEN)) if z <= x else 0 for z in range(36)] for x in range(36)]
    L = [[Fr(v, 2 ** LDEN) for v in row] for row in Li]
    R = [[N[x][y] - sum(L[x][z] * L[y][z] for z in range(36)) for y in range(36)] for x in range(36)]
    for x in range(36):
        assert sum(abs(R[x][y]) for y in range(36) if y != x) <= R[x][x], 'row %d not dominant' % x
        assert sum(abs(R[y][x]) for y in range(36) if y != x) <= R[x][x], 'column %d not dominant' % x
    return s, [row[:x + 1] for x, row in enumerate(Li)], dict(gamma=float(gam), min_diag=float(min(R[x][x] for x in range(36))))


def e0_j1(X, eps, F):
    """Exact mirrors of `e0OK` and `j1OK`: the smallest dyadic e0, j1 that pass."""
    om, gam = omega_gamma(eps)
    W = [[[(X[a][c][0] * X[b][c][0] + X[a][c][1] * X[b][c][1], X[a][c][0] * X[b][c][1] - X[a][c][1] * X[b][c][0])
           for c in range(6)] for b in range(6)] for a in range(6)]
    D4 = Fr(1, 2 ** (4 * PN))
    tot = Fr(0)
    for a in range(6):
        for b in range(6):
            s1 = sum(W[a][b][c][0] for c in range(6)) - (6 * 2 ** (2 * PN) if a == b else 0)
            s2 = sum(W[a][b][c][1] for c in range(6))
            tot += Fr(s1 * s1 + s2 * s2) * D4
    e0 = sqrt_up(tot + 1296 * om * om)
    totj = Fr(0)
    for k in range(4):
        for a in range(6):
            for b in range(6):
                d = [F[k][a][c] - F[k][b][c] for c in range(6)]
                m1 = sum(W[a][b][c][0] * d[c] for c in range(6))
                m2 = sum(W[a][b][c][1] * d[c] for c in range(6))
                totj += (m1 * m1 + m2 * m2) * D4 + om * om * sum(abs(x) for x in d) ** 2
    j1 = sqrt_up(totj)
    return e0, j1


def write_sigma(outdir, base, idx, Prad, That, DT, sigma):
    X, eps = tabN_data(Prad)
    F = [[[Fr(That[k][j][i], DT) for i in range(6)] for j in range(6)] for k in range(4)]
    s, Lrows, st = sigma_cert(X, eps, F, sigma)
    e0, j1 = e0_j1(X, eps, F)
    st.update(e0=float(e0), j1=float(j1))
    L = ['import %s.Frame' % mod(base), 'import KernelAtlas.E0K', '',
         '/-! Record %d: the normal-space bound `σ = %s` (generated by `knormal.py`; γ = %.2e, smallest remainder'
         % (idx, sigma, st['gamma']), 'diagonal %.2e). -/' % st['min_diag'], '', 'namespace %s' % base, '',
         'open NoFourMUBs.KernelAtlas', '',
         '/-- The high-precision table of `exp(−i P)` (`p = %d`, Taylor order %d), on the same centre as `tab`. -/'
         % (PN, NTN),
         'def tabN : Tab where', '  p := %d' % PN, '  nT := %d' % NTN, '  EUL := []',
         '  EPL := [%s]' % ', '.join('[%s]' % ', '.join('(%d, %d)' % e for e in row) for row in X),
         '  PqL := tab.PqL', '  epsU := 0', '  epsP := %s' % q_lit(eps), '',
         'set_option maxHeartbeats 0 in', 'def sigq : SigQ where', '  cpen := 10', '  s := %s' % q_lit(s),
         '  Lrows := [%s]' % ', '.join('[%s]' % ', '.join(str(v) for v in row) for row in Lrows),
         '  Lden := %d' % LDEN, '',
         'theorem sigmaOK_ : sigmaOK tabN (frameOf tcfg tq) sigq %s = true := by decide +kernel' % q_lit(sigma), '',
         'def e0q : ℚ := %s' % q_lit(e0), '', 'def j1q : ℚ := %s' % q_lit(j1), '',
         'theorem e0OK_ : e0OK tabN e0q = true := by decide +kernel', '',
         'theorem j1OK_ : j1OK tabN (frameOf tcfg tq) j1q = true := by decide +kernel', '',
         'end %s' % base]
    with open(os.path.join(outdir, 'Sigma.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    return dict(sigma=float(sigma), eps=float(eps), **st)


# ---------------------------------------------------------------- radii and bars from the kernel constants
S3HI = Fr(1732050808, 10 ** 9)          # sqrt(3) <= S3HI


def sqrt_down(x, den=SDEN):
    """A dyadic <= sqrt(x) (x >= 0)."""
    s = Fr(math.floor(math.sqrt(float(x)) * (1 - 1e-12) * den), den)
    while s > 0 and s * s > x:
        s -= Fr(1, den)
    return max(s, Fr(0))


def kernel_consts(rec, DT):
    """All normal-bound constants of the kernel route for one Record (a dict of Fractions)."""
    import numpy as np, sys
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'proof', 'atlas'))
    from ballrecord import BallRecord
    phi = [float.fromhex(x) for x in rec['phi']]
    B = BallRecord(np.array(phi), Tint=rec.get('Tint'))
    That = [[[int(B.rec.TB[k][6 * j + i] * DT) for i in range(6)] for j in range(6)] for k in range(4)]
    for k in range(4):
        for j in range(6):
            for i in range(6):
                assert Fr(That[k][j][i], DT) == B.rec.TB[k][6 * j + i]
    Prad = [[Fr(phi[6 * j + i]) for i in range(6)] for j in range(6)]
    X, eps = tabN_data(Prad)
    fc = frame_consts(That, DT)
    e0, j1 = e0_j1(X, eps, fc['F'])
    sigma = Fr(str(B.sigma))
    R = Fr(rec['R'])
    gR = fc['g'] * R
    bbar = e0 + j1 * gR + S3HI * fc['lam'] * gR * gR
    D = sigma * sigma - 4 * S3HI * bbar
    assert D > 0 and 2 * S3HI * R < sigma
    slo = sqrt_down(D)
    nbar = 2 * bbar / (sigma + slo)
    return dict(That=That, Prad=Prad, X=X, eps=eps, fc=fc, e0=e0, j1=j1, sigma=sigma, R=R, bbar=bbar, slo=slo,
                rH=gR, n=nbar, r=fc['t'] * gR + nbar, rF=R)


def kernel_radii(rec, DT=36 * 2 ** 30):
    """(r_col, r_F, r_H, n) in radians from the kernel constants (upper bounds of the RecordCert radii)."""
    kc = kernel_consts(rec, DT)
    return kc['r'], kc['rF'], kc['rH'], kc['n']


def write_record(outdir, base, idx, kc):
    L = ['import %s.StageC' % mod(base), 'import %s.Sigma' % mod(base), 'import KernelAtlas.NormalK', '',
         '/-! Record %d as a `RecordCert`, every field checked by the kernel (generated by `knormal.py`). -/' % idx, '',
         'namespace %s' % base, '', 'open Hadamard6 NoFourMUBs NoFourMUBs.StageC NoFourMUBs.KernelAtlas', '',
         'def bars : BarsQ where', '  R := %s' % q_lit(kc['R']), '  sigma := %s' % q_lit(kc['sigma']),
         '  e0 := e0q', '  j1 := j1q', '  slo := %s' % q_lit(kc['slo']), '',
         'theorem barsOK_ : barsOK bars fq pq tq = true := by decide +kernel', '',
         '/-- **Record %d, certified.** -/' % idx,
         'noncomputable def cert : RecordCert :=',
         '  recordK (tb := tab) (tbN := tabN) (F := frameOf tcfg tq) (fq := fq) (S := sigq) (B := bars) (pq := pq) (tq := tq)',
         '    rfl frameOK_ sigmaOK_ e0OK_ j1OK_ barsOK_',
         '    fun hK0 hK hKb hr hrF hrH hn => by rw [frameOf_toR]; exact stageC hK0 hK hKb hr hrF hrH hn', '',
         'end %s' % base]
    with open(os.path.join(outdir, 'Record.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')


def main():
    import argparse, json, sys, gzip
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from export_tangent import DT
    ap = argparse.ArgumentParser()
    ap.add_argument('idx', type=int)
    ap.add_argument('out')
    ap.add_argument('--module', default=None)
    a = ap.parse_args()
    base = a.module or 'NoFourMUBs.KernelAtlas.Rec%d' % a.idx
    rec = json.load(gzip.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..',
                                           'proof/atlas/results/atlas_certificate.json.gz'), 'rt'))['records'][a.idx]
    kc = kernel_consts(rec, DT)
    out = dict(frame=write_frame(a.out, base, a.idx, kc['That'], DT))
    out['sigma'] = write_sigma(a.out, base, a.idx, kc['Prad'], kc['That'], DT, kc['sigma'])
    write_record(a.out, base, a.idx, kc)
    out['radii'] = {k: float(kc[k]) for k in ('rH', 'n', 'r', 'rF', 'bbar', 'slo')}
    print(json.dumps(out))


if __name__ == '__main__':
    main()

"""Generate the assembly of the kernel atlas into one `AtlasCertificate` (`docs/KERNEL_ASSEMBLY.md`).

Usage (repository root):
  python3 kernel_atlas/generators/export_assembly.py --chunks K1 K2 ...   # Atlas/Chunk<k>.lean for these chunks
  python3 kernel_atlas/generators/export_assembly.py --all                # every chunk and Atlas/Final.lean
  [--out DIR]   (default kernel_atlas/lean/KernelAtlas/Atlas)

Chunk k covers atlas Records 100k … 100k + 99 (fewer in the last); it needs every one of them built
(`Rec<n>/BoundaryCover.lean`).  It defines `cert<k> i` (Record 100k + i; the first Record out of range), proves
`cert<k>_P`, `cert<k>_R` (the table entries, by `rfl`) and `bnd<k>`: the boundary covers of its Records for any family
`A` whose members `A (idx t)` have the table's centres and radii.  `Final.lean` imports all chunks, Tao's Record and
the special fields, and defines `ι = Fin (N + 1)` (Tao's Record last), `A`, `atlasCert : AtlasCertificate` and
`no_four_mubs_kernel : ¬ FourMUBs`.  The statements do not depend on N, so the same generator serves a pilot (chunks
only) and the whole atlas.
"""
import argparse, gzip, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
CHUNK = 100


def chunk_file(k, N):
    idx = list(range(k * CHUNK, min(N, (k + 1) * CHUNK)))
    S = len(idx)
    first = idx[0]
    L = ['import KernelAtlas.Rec%d.BoundaryCover' % n for n in idx]
    L += ['', '/-! Atlas chunk %d: Records %d–%d (generated by `export_assembly.py`). -/' % (k, idx[0], idx[-1]), '',
          'namespace NoFourMUBs.KernelAtlas.Atlas', '', 'open Hadamard6 NoFourMUBs NoFourMUBs.KernelAtlas', '',
          'set_option maxRecDepth 100000', '',
          '/-- Record `%d + i` (out of range: Record %d). -/' % (first, first),
          'noncomputable def cert%d (i : ℕ) : RecordCert :=' % k, '  match i with']
    L += ['  | %d => Rec%d.cert' % (n - first, n) for n in idx] + ['  | _ => Rec%d.cert' % first, '']
    L += ['theorem cert%d_P (i : ℕ) : (cert%d i).P = Pmat (pqL (Table.cen%d i)) := by' % (k, k, k), '  match i with']
    L += ['  | %d => rfl' % (n - first) for n in idx] + ['  | _ + %d => rfl' % S, '']
    L += ['theorem cert%d_R (i : ℕ) : (cert%d i).R = ((Table.rad%d i : ℚ) : ℝ) := by' % (k, k, k), '  match i with']
    L += ['  | %d => rfl' % (n - first) for n in idx] + ['  | _ + %d => rfl' % S, '']
    L += ['/-- The boundary covers of chunk %d, for any family with the table\'s centres and radii. -/' % k,
          'theorem bnd%d {ι : Type*} (A : ι → RecordCert) (idx : ℕ → ι)' % k,
          '    (hA : ∀ i, i < 100 → 100 * %d + i < Table.N → A (idx (100 * %d + i)) = cert%d i)' % (k, k, k),
          '    (hP : ∀ t < Table.N, (A (idx t)).P = Pmat (pqL (Table.cen t)))',
          '    (hR : ∀ t < Table.N, (Table.rad t : ℝ) ≤ (A (idx t)).R) :',
          '    ∀ i, i < 100 → 100 * %d + i < Table.N → Nonempty (BoundaryCover A (idx (100 * %d + i))) := by' % (k, k),
          '  intro i h1 h2', '  match i, h1, h2 with']
    L += ['  | %d, h1, h2 => exact Rec%d.boundaryT A _ (hA %d h1 h2) idx hP hR' % (n - first, n, n - first) for n in idx]
    L += ['  | i + %d, h1, h2 => exfalso; unfold Table.N at h2; omega' % S, '', 'end NoFourMUBs.KernelAtlas.Atlas']
    return '\n'.join(L) + '\n'


def final_file(K):
    L = ['import KernelAtlas.Atlas.Chunk%d' % k for k in range(K)]
    L += ['import KernelAtlas.RecTao.Record', 'import KernelAtlas.Special.Exact', 'import NoFourMUBs.Final', '',
          '/-!', '# The kernel atlas: one `AtlasCertificate` and `¬ FourMUBs` (generated by `export_assembly.py`)', '',
          '`ι = Fin (N + 1)`: the `N` atlas Records (chunks of 100) and Tao\'s Record. Every field comes from a kernel',
          'check: the Records\' `cert` (Stage C and the normal bound), their `boundaryT` (Lemma 4.1, linked through the',
          'atlas table), Tao\'s `RecTao`, and `Special.fourier`.', '-/', '',
          'namespace NoFourMUBs.KernelAtlas.Atlas', '', 'open Hadamard6 NoFourMUBs NoFourMUBs.KernelAtlas', '',
          'set_option maxRecDepth 100000', '',
          'noncomputable def certK (k : ℕ) : ℕ → RecordCert :=', '  match k with']
    L += ['  | %d => cert%d' % (k, k) for k in range(K)] + ['  | _ => cert0', '']
    L += ['theorem certK_P (k i : ℕ) : (certK k i).P = Pmat (pqL (Table.cenK k i)) := by', '  match k with']
    L += ['  | %d => exact cert%d_P i' % (k, k) for k in range(K)] + ['  | _ + %d => exact cert0_P i' % K, '']
    L += ['theorem certK_R (k i : ℕ) : (certK k i).R = ((Table.radK k i : ℚ) : ℝ) := by', '  match k with']
    L += ['  | %d => exact cert%d_R i' % (k, k) for k in range(K)] + ['  | _ + %d => exact cert0_R i' % K, '']
    L += ['noncomputable def certAt (t : ℕ) : RecordCert := certK (t / 100) (t % 100)', '',
          'theorem certAt_eq (k i : ℕ) (h : i < 100) : certAt (100 * k + i) = certK k i := by',
          '  unfold certAt; rw [show (100 * k + i) / 100 = k by omega, show (100 * k + i) % 100 = i by omega]', '',
          '/-- The family: atlas Record `t < N` at `t`, Tao\'s Record at `N`. -/',
          'noncomputable def A (i : Fin (Table.N + 1)) : RecordCert := if i.val = Table.N then RecTao.cert else certAt i.val',
          '', 'def idx (t : ℕ) : Fin (Table.N + 1) := ⟨t % (Table.N + 1), Nat.mod_lt _ (Nat.succ_pos _)⟩', '',
          'theorem idx_val {t : ℕ} (h : t < Table.N) : (idx t).val = t := Nat.mod_eq_of_lt (by omega)', '',
          'theorem A_idx {t : ℕ} (h : t < Table.N) : A (idx t) = certAt t := by',
          '  simp only [A, idx_val h, if_neg (Nat.ne_of_lt h)]', '',
          'theorem hP : ∀ t < Table.N, (A (idx t)).P = Pmat (pqL (Table.cen t)) := fun t h => by',
          '  rw [A_idx h]; exact certK_P _ _', '',
          'theorem hR : ∀ t < Table.N, (Table.rad t : ℝ) ≤ (A (idx t)).R := fun t h => by',
          '  rw [A_idx h]; exact (certK_R _ _).symm.le', '',
          'theorem bndK (k : ℕ) : ∀ i, i < 100 → 100 * k + i < Table.N →',
          '    Nonempty (BoundaryCover A (idx (100 * k + i))) := by', '  match k with']
    L += ['  | %d => exact bnd%d A idx (fun i h1 h2 => (A_idx h2).trans (certAt_eq %d i h1)) hP hR' % (k, k, k)
          for k in range(K)]
    L += ['  | k + %d => intro i h1 h2; exfalso; unfold Table.N at h2; omega' % K, '',
          'theorem boundaryAll (l : Fin (Table.N + 1)) : Nonempty (BoundaryCover A l) := by',
          '  by_cases h : l.val = Table.N',
          '  · exact RecTao.boundary A l (by simp only [A, h, if_true])',
          '  · have hl : l.val < Table.N := by omega',
          '    have e : idx (100 * (l.val / 100) + l.val % 100) = l := by',
          '      ext; rw [idx_val (by omega)]; omega',
          '    have := bndK (l.val / 100) (l.val % 100) (Nat.mod_lt _ (by norm_num)) (by omega)',
          '    rwa [e] at this', '',
          'theorem lt_N : Table.N < Table.N + 1 := Nat.lt_succ_self _', '',
          '/-- **The kernel atlas certificate.** -/',
          'noncomputable def atlasCert : AtlasCertificate where',
          '  ι := Fin (Table.N + 1)',
          '  A := A',
          '  boundary := boundaryAll',
          '  tao := RecTao.tao A ⟨Table.N, lt_N⟩ (by simp only [A, if_true])',
          '  fourier := Special.fourier A (idx 877) (by rw [hP 877 (by unfold Table.N; omega)]; rfl)',
          '    (hR 877 (by unfold Table.N; omega))', '',
          '/-- **There are no four mutually unbiased bases in `ℂ⁶`**, with the atlas checked by the kernel. -/',
          'theorem no_four_mubs_kernel : ¬ FourMUBs := Final.no_four_mubs atlasCert', '',
          'end NoFourMUBs.KernelAtlas.Atlas']
    return '\n'.join(L) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--chunks', type=int, nargs='*', default=[])
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--out', default=os.path.join(ROOT, 'kernel_atlas/lean/KernelAtlas/Atlas'))
    a = ap.parse_args()
    N = len(json.load(gzip.open(os.path.join(ROOT, 'proof/atlas/results/atlas_certificate.json.gz'), 'rt'))['records'])
    K = (N + CHUNK - 1) // CHUNK
    os.makedirs(a.out, exist_ok=True)
    ks = list(range(K)) if a.all else a.chunks
    for k in ks:
        with open(os.path.join(a.out, 'Chunk%d.lean' % k), 'w') as f:
            f.write(chunk_file(k, N))
    if a.all:
        with open(os.path.join(a.out, 'Final.lean'), 'w') as f:
            f.write(final_file(K))
    print('wrote %d chunks%s (N = %d, K = %d)' % (len(ks), ' and Final.lean' if a.all else '', N, K))


if __name__ == '__main__':
    main()

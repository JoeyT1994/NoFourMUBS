"""The shared table of the kernel seed balls (KERNEL_SEED.md section 7): every ball's kernel data `d<l> : SeedD` and
inverse `i<l> : InvD` (`seed_kball.kseed`), in modules of 100 (`SeedA/Tab<k>.lean`), and the accessors `Nb`,
`Dt l = d<l mod Nb>`, `It l` (`SeedA/TabAll.lean`).  Every per-ball module and the assembly read the data from here,
so the links between a ball's certificate and its neighbours' are definitional.

  python3 kernel_atlas/generators/seed_table.py CERT.json.gz [--out DIR] [--workers 8]
"""
import argparse, concurrent.futures as cf, gzip, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import seed_kball as K                                       # noqa: E402

CH = 100
NS = 'NoFourMUBs.KernelAtlas.SeedA'


def one(s):
    D, I, _ = K.kseed(s)
    return D, I


def write(seeds_data, out):
    Nb = len(seeds_data)
    os.makedirs(out, exist_ok=True)
    nk = (Nb + CH - 1) // CH
    for k in range(nk):
        idx = range(k * CH, min(Nb, (k + 1) * CH))
        L = ['import KernelAtlas.Seed.Frame', '', '/-! Seed table, balls %d–%d (generated by `seed_table.py`). -/'
             % (idx[0], idx[-1]), '', 'namespace %s' % NS, '', 'open NoFourMUBs.KernelAtlas.Seed', '']
        for l in idx:
            D, I = seeds_data[l]
            L += K.seedD_lean('d%d' % l, D)
            L += ['noncomputable def i%d : InvD where' % l, '  adj := %s' % K.lst(I['adj']), '  det := %d' % I['det'], '']
        L += ['noncomputable def Dt%d (i : ℕ) : SeedD :=' % k, '  match i with']
        L += ['  | %d => d%d' % (l - k * CH, l) for l in idx] + ['  | _ => d%d' % idx[0], '']
        L += ['noncomputable def It%d (i : ℕ) : InvD :=' % k, '  match i with']
        L += ['  | %d => i%d' % (l - k * CH, l) for l in idx] + ['  | _ => i%d' % idx[0], '', 'end %s' % NS]
        K.put(os.path.join(out, 'Tab%d.lean' % k), L)
    L = ['import KernelAtlas.SeedA.Tab%d' % k for k in range(nk)]
    L += ['', '/-! The seed table: `Nb` balls; `Dt l`, `It l` read ball `l mod Nb` (generated by `seed_table.py`). -/', '',
          'namespace %s' % NS, '', 'open NoFourMUBs.KernelAtlas.Seed', '', 'def Nb : ℕ := %d' % Nb, '',
          'noncomputable def DtK (k : ℕ) : ℕ → SeedD :=', '  match k with']
    L += ['  | %d => Dt%d' % (k, k) for k in range(nk)] + ['  | _ => Dt0', '']
    L += ['noncomputable def ItK (k : ℕ) : ℕ → InvD :=', '  match k with']
    L += ['  | %d => It%d' % (k, k) for k in range(nk)] + ['  | _ => It0', '']
    L += ['/-- Ball `l mod Nb`. -/', 'noncomputable def Dt (l : ℕ) : SeedD := DtK (l %% Nb / %d) (l %% Nb %% %d)' % (CH, CH), '',
          'noncomputable def It (l : ℕ) : InvD := ItK (l %% Nb / %d) (l %% Nb %% %d)' % (CH, CH), '', 'end %s' % NS]
    K.put(os.path.join(out, 'TabAll.lean'), L)
    return nk


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('cert'); ap.add_argument('--out', default=K.OUT); ap.add_argument('--workers', type=int, default=8)
    a = ap.parse_args()
    op = gzip.open if a.cert.endswith('.gz') else open
    seeds = json.load(op(a.cert, 'rt'))['seeds']
    if isinstance(seeds, dict):                     # a subset export: keys are ball indices
        raise SystemExit('the table needs the whole certificate (a list of seeds)')
    with cf.ProcessPoolExecutor(a.workers) as ex:
        data = list(ex.map(one, seeds, chunksize=16))
    nk = write(data, a.out)
    print('wrote %d balls in %d table modules to %s' % (len(data), nk, a.out))


if __name__ == '__main__':
    main()

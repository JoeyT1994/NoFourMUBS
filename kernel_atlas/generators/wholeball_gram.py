"""Generate the exact centre-to-Gram stages for one seed (not a C1 module).

The entry enclosures use the same dyadic side and forced-completion arithmetic
as the Lean centre checker. Matrices are outward-rounded with a checked
containment condition. The proposed inverse is checked by an exact Neumann
residual; W encloses the specified Gram inverse, not the proposal itself.
"""
import argparse
from fractions import Fraction as Q
import gzip
from itertools import combinations
import json
from pathlib import Path

import seed_c1 as S
from wholeball_centre import prepare, emit as emit_centre
from wholeball_matrix import MatrixBox, frozen_normal_basis, inverse_witness, matrix_expr
from wholeball_scalar import lean_rational, write_module, OUTPUT_ROOT


def entry_models(b, d):
    h = d['hb']
    e = [S.expI(h, S.thetaT(b, d, k)) for k in range(4)]
    kh = S.sideK(h, S.gramH(h, e), d['phH'], d['YH'], d['tubeH'])
    kv = S.sideK(h, S.gramV(h, e), d['phV'], d['YV'], d['tubeV'])
    if not kh[0] or not kv[0]:
        raise ArithmeticError('side check failed')
    eb = S.ET(e)
    hb = S.BT(S.tubeRows(h, d['phH'], kh[1]))
    vb = S.CT3(S.tubeRows(h, d['phV'], kv[1]))
    ok, db = S.forcedT(h, d['Xp'], d['A0'], eb, hb, vb)
    if not ok:
        raise ArithmeticError('forced block check failed')
    return [[(eb if i < 3 and j < 3 else hb if i < 3 else vb if j < 3 else db)
             [3 * (i % 3) + j % 3] for j in range(6)] for i in range(6)]


def jacobian_box(b, d):
    entries = [[S.ivc(d['hb'], t) for t in row] for row in entry_models(b, d)]
    pairs = list(combinations(range(6), 2))
    mid, rad = [], []
    for a in range(30):
        i, j = pairs[a % 15]
        mx, rx = [], []
        for p in range(36):
            k = p % 6
            sign = int(p // 6 == i) - int(p // 6 == j)
            z, r = S.ivI(S.ivm(entries[i][k], S.ivConj(entries[j][k])))
            mx.append(sign * Q(z[0 if a < 15 else 1], S.SC))
            rx.append(abs(sign) * Q(r, S.SC))
        mid.append(mx)
        rad.append(rx)
    return MatrixBox(mid, rad)


def box_expr(box):
    return '{\n      mid := ' + matrix_expr(box.mid) + ',\n      rad := ' + matrix_expr(box.rad) + '\n    }'


def emit(seed, index, basis, output):
    b, d = prepare(seed)
    x = frozen_normal_basis(basis)
    jac = jacobian_box(b, d).rounded()
    a = jac.mul(MatrixBox.exact(x)).rounded()
    gram = a.transpose().mul(a).rounded()
    proposed, q, y, error = inverse_witness(gram)
    output = Path(output).resolve()
    rel = output.relative_to(OUTPUT_ROOT.resolve()).with_suffix('')
    if len(rel.parts) != 1 or not rel.name.isidentifier() or not rel.name.isascii():
        raise ValueError('Gram module must be directly in the WholeBall folder')
    centre_name = f'Centre{index}'
    emit_centre(seed, index, output.parent / (centre_name + '.lean'))
    ns = 'NoFourMUBs.KernelAtlas.WholeBall.' + rel.name
    source = (
        'import KernelAtlas.WholeBall.CentreGram\n'
        f'import KernelAtlas.WholeBall.{centre_name}\n'
        'import KernelAtlas.WholeBall.BasisNorm\n\n'
        '-- Generated by wholeball_gram.py. This certifies centre/Gram stages only.\n'
        'set_option maxHeartbeats 0\nset_option maxRecDepth 1000000\n\n'
        f'namespace {ns}\n\n'
        f'def data : CentreGramData :=\n  {{ J := {box_expr(jac)},\n'
        f'    A := {box_expr(a)},\n    G := {box_expr(gram)},\n'
        f'    Y := {matrix_expr(proposed)},\n'
        f'    residualBound := {lean_rational(q)},\n'
        f'    inverseBound := {lean_rational(y)},\n'
        f'    inverseError := {lean_rational(error)} }}\n\n'
        f'theorem checked : centreGramCheck {centre_name}.ball {centre_name}.centre\n'
        '    BasisNorm.matrix data = true := by decide +kernel\n\n'
        f'end {ns}\n')
    write_module(output, source)
    return {'neumann_q': float(q), 'inverse_error': float(error), 'index': index}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('certificate', type=Path)
    parser.add_argument('index', type=int)
    parser.add_argument('--basis', type=Path, default=Path('proof/seed_atlas/cert/wholeball_basis.json'))
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    opener = gzip.open if args.certificate.suffix == '.gz' else open
    with opener(args.certificate, 'rt') as stream:
        seeds = json.load(stream)['seeds']
    if not 0 <= args.index < len(seeds):
        parser.error('seed index out of range')
    print(json.dumps(emit(seeds[args.index], args.index, args.basis, args.output), sort_keys=True))


if __name__ == '__main__':
    main()

"""Generate the exact tangent/second-jet stage of a real whole-ball centre.

This module certifies U and H2 and their spectral bounds. It is a component of
the whole-ball pipeline, not an hC1 exporter. Every rounded interval and LDL
factor is checked exactly before emission and again by the Lean kernel.
"""
import argparse
from fractions import Fraction as Q
import gzip
from itertools import combinations
import json
from pathlib import Path

import numpy as np
import seed_c1 as S
from wholeball_centre import prepare
from wholeball_gram import entry_models, jacobian_box, box_expr, emit as emit_gram
from wholeball_matrix import (MatrixBox, frozen_normal_basis, inverse_witness,
                             matrix_expr, vector_expr, transpose, shift, ldl,
                             spectral_check, sqrt_upper, upper_grid)
from wholeball_scalar import rational, lean_rational, write_module, OUTPUT_ROOT


def seed_basis():
    return [[Q(36 * (i == a and j == b) - 6 * (i == a) - 6 * (j == b) + 1, 36)
             for a, b in ((1, 1), (1, 2), (2, 1), (2, 2))]
            for i in range(6) for j in range(6)]


def frequencies():
    return [[Q(int(k == q and i == p) - int(k == q and j == p))
             for p in range(6) for q in range(6)]
            for i, j in combinations(range(6), 2) for k in range(6)]


def coefficient_box(b, d):
    entries = [[S.ivc(d['hb'], t) for t in row] for row in entry_models(b, d)]
    terms = [S.ivm(entries[i][k], S.ivConj(entries[j][k]))
             for i, j in combinations(range(6), 2) for k in range(6)]
    return MatrixBox(
        [[Q(z[0 if a < 15 else 1], S.SC) if a % 15 == t // 6 else Q(0)
          for t, (z, r) in enumerate(terms)] for a in range(30)],
        [[Q(r, S.SC) if a % 15 == t // 6 else Q(0)
          for t, (z, r) in enumerate(terms)] for a in range(30)])


def prepare_jets(seed, basis):
    b, d = prepare(seed)
    x = MatrixBox.exact(frozen_normal_basis(basis))
    v = MatrixBox.exact(seed_basis())
    values = seed['Mth']
    if len(values) != 16:
        raise ValueError('expected sixteen row-major seed-frame entries')
    m = MatrixBox.exact([[rational(values[4 * i + j]) for j in range(4)] for i in range(4)])
    jac = jacobian_box(b, d).rounded()
    a = jac.mul(x).rounded()
    gram = a.transpose().mul(a).rounded()
    proposed, q, y, error = inverse_witness(gram)
    w = MatrixBox(proposed, [[error] * 21 for _ in range(21)]).mul(a.transpose()).rounded()
    jv = jac.mul(v).rounded()
    wjv = w.mul(jv).rounded()
    u = v.sub(x.mul(wjv)).mul(m).rounded()
    s = MatrixBox.exact(frequencies()).mul(u).rounded()
    z = coefficient_box(b, d).rounded()
    b2 = z.mul(s.row_tensor(s)).neg().rounded()
    wb = w.mul(b2).rounded()
    h = x.mul(wb).neg().rounded()
    return dict(W=w, JV=jv, WJV=wjv, U=u, S=s, Z=z, B=b2, WB=wb, H=h), v.mid, m.mid


def norm_certificate(box):
    rows = len(box.mid) < len(box.mid[0])
    a = transpose(box.mid) if rows else box.mid
    # Floating point proposes a bound; exact LDL reconstruction certifies it.
    approximate = np.linalg.norm(np.array(a, dtype=float), 2)
    bound = upper_grid(Q.from_float(approximate * 1.000001 + 1e-12), 40)
    lower, pivots = ldl(shift(a, bound))
    if not spectral_check(a, bound, lower, pivots):
        raise ArithmeticError('spectral witness rejected')
    error = sqrt_upper(sum((v*v for row in box.rad for v in row), Q(0)))
    source = ('{\n      midpointBound := ' + lean_rational(bound) + ',\n'
              '      errorBound := ' + lean_rational(error) + ',\n'
              '      witness := .' + ('rows' if rows else 'columns') +
              ' {\n        L := ' + matrix_expr(lower) + ',\n        d := ' + vector_expr(pivots) + '\n      }\n    }')
    return bound + error, source


def emit(seed, index, basis, output):
    boxes, v, m = prepare_jets(seed, basis)
    output = Path(output).resolve()
    rel = output.relative_to(OUTPUT_ROOT.resolve()).with_suffix('')
    if len(rel.parts) != 1 or not rel.name.isidentifier() or not rel.name.isascii():
        raise ValueError('jet module must be directly in the WholeBall folder')
    emit_gram(seed, index, basis, output.parent / f'Gram{index}.lean')
    u, uc = norm_certificate(boxes['U'])
    beta, bc = norm_certificate(boxes['H'])
    ns = 'NoFourMUBs.KernelAtlas.WholeBall.' + rel.name
    source = ('import KernelAtlas.WholeBall.CentreJets\n'
              f'import KernelAtlas.WholeBall.Gram{index}\n\n'
              '-- Generated by wholeball_jets.py. Predictor stage only, not hC1.\n'
              'set_option maxHeartbeats 0\nset_option maxRecDepth 1000000\n\n'
              f'namespace {ns}\n\n'
              f'def V : Matrix (Fin 36) (Fin 4) ℚ := {matrix_expr(v)}\n\n'
              f'def M : Matrix (Fin 4) (Fin 4) ℚ := {matrix_expr(m)}\n\n'
              'def data : CentreJetData :=\n  {\n' +
              ',\n'.join('    ' + name + ' := ' + box_expr(box) for name, box in boxes.items()) +
              '\n  }\n\n'
              f'theorem checked : centreJetCheck Centre{index}.ball Centre{index}.centre\n'
              f'    BasisNorm.matrix V M Gram{index}.data data = true := by decide +kernel\n\n'
              f'end {ns}\n')
    norm_name = rel.name + 'Norms'
    norm_source = ('import KernelAtlas.WholeBall.NormCertificate\n'
                   f'import KernelAtlas.WholeBall.{rel.name}\n\n'
                   'set_option maxHeartbeats 0\nset_option maxRecDepth 1000000\n\n'
                   f'namespace {ns}\n\n'
                   f'def u : ℚ := {lean_rational(u)}\n'
                   f'def beta : ℚ := {lean_rational(beta)}\n'
                   f'def uCertificate : NormCertificate 36 4 := {uc}\n\n'
                   f'def betaCertificate : NormCertificate 36 16 := {bc}\n\n'
                   'theorem u_checked : data.U.certifyNorm u uCertificate = true := by decide +kernel\n\n'
                   'theorem beta_checked : data.H.certifyNorm beta betaCertificate = true := by decide +kernel\n\n'
                   f'end {ns}\n')
    write_module(output.parent / (norm_name + '.lean'), norm_source)
    write_module(output, source)
    return {'index': index, 'u': float(u), 'beta': float(beta)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('certificate', type=Path)
    parser.add_argument('index', type=int)
    parser.add_argument('--basis', type=Path, default=Path('proof/seed_atlas/cert/wholeball_basis.json'))
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    opener = gzip.open if args.certificate.suffix == '.gz' else open
    with opener(args.certificate, 'rt') as stream:
        seeds = json.load(stream)['seeds']
    if not 0 <= args.index < len(seeds):
        parser.error('seed index out of range')
    print(json.dumps(emit(seeds[args.index], args.index, args.basis, args.output), sort_keys=True))


if __name__ == '__main__':
    main()

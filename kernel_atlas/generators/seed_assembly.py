"""The assembly of the kernel seed atlas (KERNEL_SEED.md section 7): chunks of 100 balls and the final module.

  SeedA/Chunk<k>.lean   imports balls 100k … 100k+99 (`B<j>.Cert`, `B<j>.Bnd`); `certC<k> i` (ball 100k+i), its link to
                        the table (`certC<k>_link`, by `rfl`), and `bndC<k>`: their boundary covers for any family whose
                        members carry the table's data
  SeedA/Final.lean      σs = Fin Nb (the balls), the records' family and covers, Tao and the Fourier anchor from
                        `SeedA.Records` (the record side), and `no_four_mubs_seed_kernel : ¬ FourMUBs`

`--stub-records` writes a `SeedA/Records.lean` whose fields are `sorry` (to type-check the assembly before the record
side is built); `--stub-balls` writes `B<j>/Cert.lean`, `B<j>/Bnd.lean` stubs for balls not built.

  python3 kernel_atlas/generators/seed_assembly.py --nb NB [--chunks K ...] [--final] [--stub-records] [--stub-balls]
"""
import argparse, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import seed_kball as K                                       # noqa: E402

CH = 100
NS = 'NoFourMUBs.KernelAtlas.SeedA'
OUT = K.OUT


def chunk(k, Nb):
    idx = list(range(k * CH, min(Nb, (k + 1) * CH)))
    n = len(idx)
    L = []
    for j in idx: L += ['import KernelAtlas.SeedA.B%d.Cert' % j, 'import KernelAtlas.SeedA.B%d.Bnd' % j]
    L += ['import KernelAtlas.SeedA.TabAll', '', '/-! Seed atlas chunk %d: balls %d–%d (generated by `seed_assembly.py`). -/'
          % (k, idx[0], idx[-1]), '', 'namespace %s' % NS, '',
          'open NoFourMUBs.KernelAtlas.Seed NoFourMUBs.SeedAtlas', '', 'set_option maxRecDepth 100000', '',
          '/-- Ball `%d + i` (out of range: ball %d). -/' % (idx[0], idx[0]),
          'noncomputable def certC%d (i : ℕ) : SeedBallCert :=' % k, '  match i with']
    L += ['  | %d => B%d.cert' % (j - idx[0], j) for j in idx] + ['  | _ => B%d.cert' % idx[0], '']
    L += ['theorem certC%d_link (i : ℕ) (h : i < %d) : (certC%d i).theta0 = th0R (Dt%d i).B ∧' % (k, n, k, k),
          '    (certC%d i).Mth = MthR (Dt%d i).B ∧ (certC%d i).r = rn (Dt%d i).r ∧ ((certC%d i).o : ℤ) = (Dt%d i).B.o := by'
          % (k, k, k, k, k, k), '  match i, h with']
    L += ['  | %d, _ => exact ⟨rfl, rfl, rfl, by decide⟩' % (j - idx[0]) for j in idx]
    L += ['  | i + %d, h => exfalso; omega' % n, '']
    L += ['/-- The boundary covers of chunk %d. -/' % k,
          'theorem bndC%d {σs ιr : Type} (S : σs → SeedBallCert) (A : ιr → RecordCert) (ofS : ℕ → σs) (ofR : ℕ → ιr)' % k,
          '    (hl : ∀ l, BallLink S ofS l (Dt l)) (i : ℕ) (h : i < %d) :' % n,
          '    Nonempty (SeedBoundaryCover S A (ofS (%d + i))) := by' % idx[0], '  match i, h with']
    for j in idx:
        L += ['  | %d, _ =>' % (j - idx[0]),
              '    obtain ⟨h0, hM, hr, ho⟩ := hl %d' % j,
              '    exact B%d.bnd S A ofS ofR ⟨h0, hM, hr, Units.ext (by rw [ho]; decide)⟩ hl' % j]
    L += ['  | i + %d, h => exfalso; omega' % n, '', 'end %s' % NS]
    return '\n'.join(L) + '\n'


def final(Nb):
    nk = (Nb + CH - 1) // CH
    L = ['import KernelAtlas.SeedA.Chunk%d' % k for k in range(nk)]
    L += ['import KernelAtlas.SeedA.Records', '', '/-!',
          '# The kernel seed atlas: `¬ FourMUBs` with every field kernel-checked (generated by `seed_assembly.py`)', '',
          '`σs = Fin Nb`: the seed balls (`B<j>.cert`, chunks of 100), whose boundary covers (`B<j>.bnd`) are linked through',
          'the shared table; the records, their boundary covers (`rec` and T1′), Tao and the Fourier anchor from',
          '`SeedA.Records`.', '-/', '', 'namespace %s' % NS, '',
          'open NoFourMUBs.KernelAtlas.Seed NoFourMUBs.SeedAtlas', '', 'set_option maxRecDepth 100000', '',
          'noncomputable def certK (k : ℕ) : ℕ → SeedBallCert :=', '  match k with']
    L += ['  | %d => certC%d' % (k, k) for k in range(nk)] + ['  | _ => certC0', '']
    L += ['/-- The family of seed balls. -/', 'noncomputable def S (i : Fin Nb) : SeedBallCert := certK (i.val / 100) (i.val % 100)',
          '', 'def ofS (l : ℕ) : Fin Nb := ⟨l % Nb, Nat.mod_lt _ (by decide)⟩', '',
          'theorem link_lt (t : ℕ) (h : t < Nb) : BallLink S ofS t (Dt t) := by',
          '  have e : (ofS t).val = t := Nat.mod_eq_of_lt h', '  unfold BallLink S Dt', '  rw [e, Nat.mod_eq_of_lt h]',
          '  have hk : t / 100 < %d := by unfold Nb at h; omega' % nk,
          '  generalize hq : t / 100 = k at hk ⊢', '  match k, hk with']
    for k in range(nk):
        n = min(Nb, (k + 1) * CH) - k * CH
        L += ['  | %d, _ =>' % k, '    have hi : t %% 100 < %d := by unfold Nb at h; omega' % n,
              '    obtain ⟨a, b, c, d⟩ := certC%d_link (t %% 100) hi' % k,
              '    exact ⟨a, b, c, d⟩']
    L += ['', 'theorem hl : ∀ l, BallLink S ofS l (Dt l) := fun l => by',
          '  have h := link_lt (l % Nb) (Nat.mod_lt _ (by decide))',
          '  unfold BallLink at h ⊢', '  unfold Dt at h ⊢', '  simpa only [ofS, Nat.mod_mod] using h', '',
          'theorem hb (j : Fin Nb) : Nonempty (SeedBoundaryCover S A j) := by',
          '  have e : ofS j.val = j := Fin.ext (Nat.mod_eq_of_lt j.2)',
          '  rw [← e, show j.val = 100 * (j.val / 100) + j.val % 100 by omega]',
          '  have hk : j.val / 100 < %d := by have := j.2; unfold Nb at this; omega' % nk,
          '  generalize hq : j.val / 100 = k at hk ⊢', '  match k, hk with']
    for k in range(nk):
        n = min(Nb, (k + 1) * CH) - k * CH
        L += ['  | %d, _ => exact bndC%d S A ofS ofR hl _ (by have := j.2; unfold Nb at this; omega)' % (k, k)]
    L += ['', '/-- **There are no four mutually unbiased bases in `ℂ⁶`**, every input checked by the kernel. -/',
          'theorem no_four_mubs_seed_kernel : ¬ NoFourMUBs.FourMUBs :=',
          '  seed_kernel_of S A hb (recBnd S ofS hl) tao fourier', '', 'end %s' % NS]
    return '\n'.join(L) + '\n'


STUB_RECORDS = '''import KernelAtlas.Seed.Links
import KernelAtlas.SeedA.TabAll

/-! STUB (smoke test only): the record side of the kernel seed atlas, every field `sorry`. -/

namespace NoFourMUBs.KernelAtlas.SeedA

open NoFourMUBs.KernelAtlas.Seed NoFourMUBs.SeedAtlas Hadamard6 NoFourMUBs.Step2

def Nr : ℕ := 2

noncomputable def A : Fin Nr → NoFourMUBs.RecordCert := sorry

def ofR (l : ℕ) : Fin Nr := ⟨l % Nr, Nat.mod_lt _ (by decide)⟩

theorem recBnd {σs : Type} (S : σs → SeedBallCert) (ofS : ℕ → σs) (hl : ∀ l, BallLink S ofS l (Dt l)) :
    ∀ l, Nonempty (RecBoundaryCover S A l) := sorry

theorem tao : ∀ ω, IsPrimitiveCubicPhase ω → ∃ K, InAtlas A K ∧ Equivalent (taoMatrix ω) K := sorry

theorem fourier : FourierAnchorCertificate (InAtlas A) := sorry

end NoFourMUBs.KernelAtlas.SeedA
'''


def stub_ball(j, o=1):
    d = os.path.join(OUT, 'B%d' % j)
    os.makedirs(d, exist_ok=True)
    base = '%s.B%d' % (NS, j)
    hd = ['import KernelAtlas.Seed.Links', 'import KernelAtlas.SeedA.TabAll', '', '/-! STUB (smoke test only). -/', '',
          'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas.Seed NoFourMUBs.KernelAtlas.SeedA', '']
    K.put(os.path.join(d, 'Cert.lean'), hd + [
        'noncomputable def seed : SeedD := d%d' % j, '',
        'noncomputable def cert : NoFourMUBs.SeedAtlas.SeedBallCert :=',
        '  ballCert seed %d sorry sorry sorry sorry sorry' % o, '', 'end %s' % base])
    K.put(os.path.join(d, 'Bnd.lean'), ['import KernelAtlas.SeedA.B%d.Cert' % j] + hd[2:] + [
        'theorem bnd {σs ιr : Type} (S : σs → NoFourMUBs.SeedAtlas.SeedBallCert) (A : ιr → NoFourMUBs.RecordCert)',
        '    (ofS : ℕ → σs) (ofR : ℕ → ιr) {jj : σs}',
        '    (hj : (S jj).theta0 = th0R seed.B ∧ (S jj).Mth = MthR seed.B ∧ (S jj).r = rn seed.r ∧ (S jj).o = %d)' % o,
        '    (hl : ∀ l, BallLink S ofS l (Dt l)) : Nonempty (NoFourMUBs.SeedAtlas.SeedBoundaryCover S A jj) := sorry',
        '', 'end %s' % base])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--nb', type=int, required=True)
    ap.add_argument('--chunks', type=int, nargs='*', default=None)
    ap.add_argument('--final', action='store_true')
    ap.add_argument('--stub-records', action='store_true')
    ap.add_argument('--stub-balls', type=int, nargs='*', default=[])
    a = ap.parse_args()
    nk = (a.nb + CH - 1) // CH
    for k in (a.chunks if a.chunks is not None else range(nk)):
        K.put(os.path.join(OUT, 'Chunk%d.lean' % k), chunk(k, a.nb).splitlines())
    if a.final: K.put(os.path.join(OUT, 'Final.lean'), final(a.nb).splitlines())
    if a.stub_records: K.put(os.path.join(OUT, 'Records.lean'), STUB_RECORDS.splitlines())
    for j in a.stub_balls: stub_ball(j)
    print('wrote to', OUT)


if __name__ == '__main__':
    main()

"""Emit the enclosure proof for the existing dRT arithmetic circuit.

No numerical result is trusted: the generated theorem composes the Taylor-model soundness lemmas.
Run from the repository root; outputs are Edge/R4Model.lean and Edge/R4Deriv.lean.
"""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'kernel_atlas/generators/edge_c1e.py'
TARGET = ROOT / 'kernel_atlas/lean/KernelAtlas/Edge/R4Model.lean'


def generate():
    tree = ast.parse(SOURCE.read_text())
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'dRT')
    nodes = [(n.targets[0].id, n.value) for n in fn.body if isinstance(n, ast.Assign)]
    result = next(n.value for n in fn.body if isinstance(n, ast.Return))
    def constant(node):
        if isinstance(node, ast.Name) and node.id == 'ONE':
            return 1
        a, b = node.elts
        assert isinstance(b, ast.Constant) and b.value == 0
        if isinstance(a, ast.Name) and a.id == 'SC':
            return 1
        assert isinstance(a, ast.BinOp) and isinstance(a.op, ast.Mult) and a.right.id == 'SC'
        return a.left.value
    def expression(node, mode):
        if isinstance(node, ast.Name):
            return ('h_' if mode == 'proof' else '') + node.id
        op = node.func.id
        args = node.args[1:] if op == 'mul' else node.args
        if op == 'const':
            c = constant(args[0])
            return f'(has_grid_int u {c})' if mode == 'proof' else f'({c} : ℂ)'
        vals = [expression(a, mode) for a in args]
        if mode == 'proof':
            return '(has_' + op + (' hu' if op == 'mul' else '') + ' ' + ' '.join(vals) + ')'
        if op in ('add', 'sub', 'mul'):
            return '(' + (' ' + {'add': '+', 'sub': '-', 'mul': '*'}[op] + ' ').join(vals) + ')'
        if op == 'neg':
            return '(-' + vals[0] + ')'
        if op == 'conj':
            return '((starRingEnd ℂ) ' + vals[0] + ')'
        if op == 'mulI':
            return '(I * ' + vals[0] + ')'
        raise ValueError(op)
    lines = ['import KernelAtlas.Edge.C1eSide', 'import KernelAtlas.Seed.T2', '', '/-!',
             '# Enclosure of the fourth-angle discriminant derivative', '',
             'Generated by `kernel_atlas/generators/edge_r4.py` from the dRT arithmetic circuit.',
             '`has_dRT` certifies its evaluation. The derivative identity is a separate theorem.',
             '-/', '', 'open Complex', '', 'noncomputable section', '',
             'namespace NoFourMUBs.KernelAtlas.Edge', '', 'open Seed', '',
             '/-- Exact evaluation of the fourth-angle derivative circuit. -/',
             'def dR4C (a b c d : ℂ) : ℂ :=']
    for name, node in nodes:
        lines.append(f'  let {name} := {expression(node, "value")}')
    lines += ['  ' + expression(result, 'value'), '',
              'lemma has_grid_int (u : Fin 4 → ℝ) (n : ℤ) :',
              '    (const (n * 2 ^ pp, 0)).Has u (n : ℂ) := by',
              '  have H := has_const (wT n) u', '  rw [cz_wT] at H', '  exact H', '',
              'set_option maxHeartbeats 2000000 in',
              '/-- Every model operation in `dRT` encloses the corresponding circuit value. -/',
              'theorem has_dRT {h : List ℕ} {u : Fin 4 → ℝ} (hu : InBox h u)',
              '    {a b c d : CT} {ar br cr dr : ℂ}',
              '    (h_a : a.Has u ar) (h_b : b.Has u br) (h_c : c.Has u cr) (h_d : d.Has u dr) :',
              '    (dRT h a b c d).Has u (dR4C ar br cr dr) := by']
    for name, node in nodes:
        lines.append(f'  have h_{name} := {expression(node, "proof")}')
    lines += ['  have H := ' + expression(result, 'proof'),
              '  simpa only [dRT, dR4C, oneZ, one_mul, Int.cast_ofNat, Int.cast_one] using H',
              '', 'end NoFourMUBs.KernelAtlas.Edge', '']
    TARGET.write_text('\n'.join(lines))
    primal = ast.parse('sub(mul(h, const((4 * SC, 0)), mul(h, gg, eta)), mul(h, chi, chi))', mode='eval').body
    derivatives = dict(one='0', s='0', t='f_dt τ', r='f_dr τ', X='0', Yv='f_dY τ', Z='f_dZ τ',
                       p='f_dp τ', srt='f_dsrt τ', J='f_dJ τ', XY='f_X τ * f_dY τ', W='f_dW τ',
                       c3='0', g='f_dg τ', eta='f_deta τ', p9='f_dp τ', p15='f_dp τ', p18='f_dp τ',
                       chi='f_dchi τ', gg='2 * f_g τ * f_dg τ')
    def fexpr(node, arg='z'):
        if isinstance(node, ast.Name):
            return node.id if node.id in ('a', 'b', 'c') else f'(f_{node.id} {arg})'
        op = node.func.id
        args = node.args[1:] if op == 'mul' else node.args
        if op == 'const': return f'({constant(args[0])} : ℂ)'
        vals = [fexpr(a, arg) for a in args]
        if op in ('add', 'sub', 'mul'):
            return '(' + (' ' + {'add': '+', 'sub': '-', 'mul': '*'}[op] + ' ').join(vals) + ')'
        if op == 'neg': return '(-' + vals[0] + ')'
        if op == 'conj': return '((starRingEnd ℂ) ' + vals[0] + ')'
        if op == 'mulI': return '(I * ' + vals[0] + ')'
        raise ValueError(op)
    def dproof(node):
        if isinstance(node, ast.Name): return 'h_' + node.id
        op = node.func.id
        args = node.args[1:] if op == 'mul' else node.args
        if op == 'const': return f'(hasDerivAt_const τ ({constant(args[0])} : ℂ))'
        vals = [dproof(a) for a in args]
        if op in ('add', 'sub', 'mul'): return f'({vals[0]}.{op} {vals[1]})'
        if op == 'neg': return f'({vals[0]}.neg)'
        if op == 'conj': return f'({vals[0]}.star)'
        if op == 'mulI': return f'((hasDerivAt_const τ I).mul {vals[0]})'
        raise ValueError(op)
    out = ['import KernelAtlas.Edge.R4Model', 'import KernelAtlas.Edge.Regular', '',
           '/-! The derivative identity for the existing fourth-angle circuit. Generated by edge_r4.py. -/', '',
           'open Complex NoFourMUBs.SeedAtlas', '', 'noncomputable section', '',
           'namespace NoFourMUBs.KernelAtlas.Edge', '',
           'def r4C (a b c d : ℂ) : ℂ :=']
    for name, node in nodes:
        if name in derivatives: out.append(f'  let {name} := {expression(node, "value")}')
    out += ['  ' + expression(primal, 'value'), '',
            'set_option maxRecDepth 4096 in', 'set_option maxHeartbeats 200000 in',
            'theorem hasDerivAt_r4C (a b c : ℂ) (τ : ℝ) :',
            '    HasDerivAt (fun z : ℝ => r4C a b c (exp ((z : ℂ) * I)))',
            '      (dR4C a b c (exp ((τ : ℂ) * I))) τ := by',
            '  let f_d : ℝ → ℂ := fun z => exp ((z : ℂ) * I)',
            '  have h_a := hasDerivAt_const τ a',
            '  have h_b := hasDerivAt_const τ b',
            '  have h_c := hasDerivAt_const τ c',
            '  have h_d : HasDerivAt f_d (I * f_d τ) τ := Method.hasDerivAt_exp_mul_I τ']
    for name, node in nodes:
        out.append(f'  let f_{name} : ℝ → ℂ := fun z => {fexpr(node)}')
    clear = 'clear_value f_d ' + ' '.join('f_' + name for name, _ in nodes)
    for name, node in nodes:
        if name in derivatives:
            delta = derivatives[name]
            unfold = [x for x in ('f_dt', 'f_dr', 'f_dY', 'f_dZ', 'f_dp', 'f_dsrt', 'f_dJ', 'f_dW',
                                 'f_dg', 'f_deta', 'f_dchi') if x in delta]
            if name == 'W': unfold += ['f_XY']
            out += [f'  have h_{name} : HasDerivAt f_{name} ({delta}) τ := by',
                    f'    exact {dproof(node)}.congr_deriv (by',
                    *(['      dsimp (config := {zetaDelta := false}) only [' + ', '.join(unfold) + ']'] if unfold else []),
                    '      ' + clear, '      (try simp only [Complex.star_def, map_zero, Pi.mul_apply]) <;> ring)']
    out += [f'  have H := {dproof(primal)}',
            '  refine (H.congr_deriv ?_).congr_of_eventuallyEq (Filter.Eventually.of_forall fun z => ?_)',
            '  · change _ = ' + fexpr(result, 'τ'),
            '    simp (config := {zetaDelta := false}) only [f_gg]', '    ' + clear, '    ring', '  · rfl', '',
            'end NoFourMUBs.KernelAtlas.Edge', '']
    TARGET.with_name('R4Deriv.lean').write_text('\n'.join(out))


if __name__ == '__main__':
    generate()

"""The shared atlas table: every Record's binary64 centre and radius, once (`KernelAtlas/Table/`).

Usage (repository root): python3 kernel_atlas/generators/export_table.py [out dir, default kernel_atlas/lean/KernelAtlas/Table]

Writes `T<k>.lean` for k = 0 … ⌈N/100⌉ − 1 (Records 100k … 100k + 99: `c<n> : List (List ℚ)`, the centre in the layout
of `Tab.PqL`; `r<n> : ℚ`, the radius; `cen<k>`, `rad<k>`: the chunk as functions of i = n − 100k) and `All.lean`
(`N`, `cen t`, `rad t`).  Records reference the table instead of repeating literals (`export_record.py`: `tab.PqL :=
Table.c<n>`; `knormal.py`: `bars.R := Table.r<n>`; `export_boundary.py`: targets' `Pt := Table.c<t>`,
`Rt := Table.r<t>`), so a Record's centre and the centre its neighbours' boundary data name are the same constant, and
the assembly's links are `rfl`/`decide` (`Assembly.lean`).
"""
import gzip, json, os, sys
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from export_record import q_lit

CHUNK = 100


def centre_lit(rec):
    P = [[Fr(float.fromhex(rec['phi'][6 * j + i])) for i in range(6)] for j in range(6)]
    return '[%s]' % ', '.join('[%s]' % ', '.join(q_lit(x) for x in row) for row in P)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'kernel_atlas/lean/KernelAtlas/Table')
    os.makedirs(out, exist_ok=True)
    recs = json.load(gzip.open(os.path.join(ROOT, 'proof/atlas/results/atlas_certificate.json.gz'), 'rt'))['records']
    N = len(recs)
    K = (N + CHUNK - 1) // CHUNK
    for k in range(K):
        idx = list(range(k * CHUNK, min(N, (k + 1) * CHUNK)))
        L = ['import Mathlib.Data.Rat.Defs', '',
             '/-! The atlas table, Records %d–%d: binary64 centres and radii (generated by `export_table.py`). -/'
             % (idx[0], idx[-1]), '', 'namespace NoFourMUBs.KernelAtlas.Table', '']
        for n in idx:
            L += ['noncomputable def c%d : List (List ℚ) := %s' % (n, centre_lit(recs[n])),
                  'noncomputable def r%d : ℚ := %s' % (n, q_lit(Fr(recs[n]['R']))), '']
        L += ['/-- The chunk as a function of `i = n − %d` (out of range: the first Record). -/' % idx[0],
              'noncomputable def cen%d (i : ℕ) : List (List ℚ) :=' % k, '  match i with']
        L += ['  | %d => c%d' % (n - idx[0], n) for n in idx] + ['  | _ => c%d' % idx[0], '']
        L += ['noncomputable def rad%d (i : ℕ) : ℚ :=' % k, '  match i with']
        L += ['  | %d => r%d' % (n - idx[0], n) for n in idx] + ['  | _ => r%d' % idx[0], '',
                                                                   'end NoFourMUBs.KernelAtlas.Table']
        with open(os.path.join(out, 'T%d.lean' % k), 'w') as f:
            f.write('\n'.join(L) + '\n')
    L = ['import KernelAtlas.Table.T%d' % k for k in range(K)]
    L += ['', '/-! The atlas table: `N` Records, `cen t`, `rad t` (generated by `export_table.py`). -/', '',
          'namespace NoFourMUBs.KernelAtlas.Table', '', 'def N : ℕ := %d' % N, '',
          'noncomputable def cenK (k : ℕ) : ℕ → List (List ℚ) :=', '  match k with']
    L += ['  | %d => cen%d' % (k, k) for k in range(K)] + ['  | _ => cen0', '',
                                                           'noncomputable def radK (k : ℕ) : ℕ → ℚ :=', '  match k with']
    L += ['  | %d => rad%d' % (k, k) for k in range(K)] + ['  | _ => rad0', '',
          '/-- The centre of atlas Record `t`. -/',
          'noncomputable def cen (t : ℕ) : List (List ℚ) := cenK (t / %d) (t %% %d)' % (CHUNK, CHUNK), '',
          '/-- The radius of atlas Record `t`. -/',
          'noncomputable def rad (t : ℕ) : ℚ := radK (t / %d) (t %% %d)' % (CHUNK, CHUNK), '',
          'end NoFourMUBs.KernelAtlas.Table']
    with open(os.path.join(out, 'All.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('table: %d Records in %d chunks' % (N, K))


if __name__ == '__main__':
    main()

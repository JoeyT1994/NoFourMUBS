"""Export one atlas Record to a Lean data file for the kernel bin checker (KernelAtlas/Bins.lean).

Usage: python3 export_record.py <record index> <out dir> [--p 28] [--q 20] [--module Lean.Namespace]

Reads proof/atlas/results/atlas_certificate.json.gz, recomputes the Record's Stage C radii with ballrecord.py (the
same Arb code certify.py uses), and writes:
  * `cfg : Cfg` and `pq : ParQ` (thresholds and their rational side conditions),
  * the 60 coordinate trees (5 coordinates x 12 level-12 roots, depth 3) as literals,
  * `parOK : ParOK cfg pq` by `decide +kernel`,
  * mode `slabs`: one theorem per level-12 slab `slabOK cfg leafT (root b) L2 L3 L4 L5 = true` (12 theorems);
    mode `sub`: a single 1/144 sub-slab (first two coordinates fixed), for timing.
The integers are produced by kbins.py, an exact mirror of the Lean definitions; the kernel re-derives the truth
of every claim (the data are only a certificate).
"""
import argparse, gzip, json, math, os, sys, time
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, 'proof', 'atlas'))
import kbins as KB


def mod(base):
    """The Lean module path of a generated namespace `NoFourMUBs.KernelAtlas.RecN` (library `KernelAtlas`)."""
    return base.replace('NoFourMUBs.KernelAtlas.', 'KernelAtlas.', 1)


def q_lit(x):
    x = Fr(x)
    if x.denominator == 1:
        return '(%d : ℚ)' % x.numerator
    return '((%d : ℚ) / %d)' % (x.numerator, x.denominator)


def v12(v):
    return '⟨%s⟩' % ', '.join(str(int(t)) for t in v)


def ct(node):
    k, v, l, r = node
    if l is None:
        return 'CT.node %d %s CT.leaf CT.leaf' % (k, v12(v))
    return 'CT.node %d %s\n    (%s)\n    (%s)' % (k, v12(v), ct(l), ct(r))


def radii(rec):
    """r (per column), rF, rH and n in radians, from the kernel normal-bound constants (`knormal.py`)."""
    from knormal import kernel_radii
    return kernel_radii(rec)


def radii_python(rec):
    """r (per column) and rF (Frobenius) in radians, recomputed as in ballrecord.stage_c."""
    import numpy as np
    from ballrecord import BallRecord
    from flint import arb, arb_mat
    from record import opnorm_upper
    P = np.array([float.fromhex(x) for x in rec['phi']])
    B = BallRecord(P, Tint=rec.get('Tint'))
    R = rec['R']
    rH, n = B.normal_bound(R)
    B.tcol = max(opnorm_upper(arb_mat([[B.rec.Tb[6 * j + i, k] for k in range(4)] for j in range(6)])) for i in range(6))
    rcol = min(R, (B.tcol * rH + n) * (1 + 1e-12))
    k = B.rec.dimT
    dT = float(np.abs(np.array([[float(abs(B.rec.Tb[e, j] - arb(float(B.rec.Tbn[e, j]))).upper()) for j in range(k)]
                                for e in range(36)])).sum())
    n = n + dT * rH * (1 + 1e-12)
    rF = min(R, math.sqrt(B.lam_max) * rH + n) * (1 + 1e-12)
    return rcol, rF, rH, n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('idx', type=int)
    ap.add_argument('out')
    ap.add_argument('--p', type=int, default=28)
    ap.add_argument('--q', type=int, default=20)
    ap.add_argument('--mode', default='slabs')
    ap.add_argument('--module', default=None)
    a = ap.parse_args()
    d = json.load(gzip.open(os.path.join(ROOT, 'proof/atlas/results/atlas_certificate.json.gz'), 'rt'))
    rec = d['records'][a.idx]
    phi = [float.fromhex(x) for x in rec['phi']]
    Prad = [[Fr(phi[6 * j + i]) for i in range(6)] for j in range(6)]
    KB.check_consts()
    p, q = a.p, a.q
    rcol, rF, rH, nN = radii(rec)
    # cycles, rounded up generously (the Lean theorem takes r <= rbar, rF <= rFbar as hypotheses)
    rbar = KB.dyadic_up(Fr(rcol) * (1 + Fr(1, 10 ** 9)) / (2 * KB.PI_LO))
    rFbar = KB.dyadic_up(Fr(rF) * (1 + Fr(1, 10 ** 9)) / (2 * KB.PI_LO))
    Kbar = 1 + Fr(1, 10 ** 9)
    EU = KB.eu_table(p)
    EP = KB.ep_table(Prad, p)
    epsU, epsP = KB.eps_tables(p, Prad)
    epsU, epsP = KB.dyadic_up(epsU), KB.dyadic_up(epsP)
    par = KB.Params(p, q, rbar, rFbar, Kbar, epsU, epsP)
    R5 = KB.roots(EU, EP, p)
    W0 = []
    for i in range(6):
        W0 += [EP[0][i][0] + par.BOFF, EP[0][i][1] + par.BOFF]
    t0 = time.time()
    ok, st = KB.run(par, W0, R5)
    mirror = dict(ok=ok, seconds=round(time.time() - t0, 1), stats={'%s_%d' % k: v for k, v in st.items()})
    outdir = a.out                                       # a directory: <outdir>/Data.lean, SlabNN.lean, Cover.lean
    os.makedirs(outdir, exist_ok=True)
    base = a.module or 'NoFourMUBs.KernelAtlas.Rec%d' % a.idx
    hdr = ('R = %s rad, label radius %s.  Stage C radii (radians, kernel normal bound, `knormal.py`): r_col = %.12g, r_F = %.12g, '
           'r_H = %.12g, n = %.6g.' % (rec['R'], rec['label_radius'], rcol, rF, rH, nN))
    L = []
    w = L.append
    w('import KernelAtlas.Tables')
    w('')
    w('/-!')
    w('# Kernel bin-tree data for atlas Record %d' % a.idx)
    w('')
    w('Generated by `kernel_atlas/generators/export_record.py`; do not edit.  ' + hdr)
    w('Precision p = %d, q = %d, Taylor order %d.  Exact-integer mirror (`kbins.py`) of the checker on this Record:' % (p, q, KB.NTAYLOR))
    w('`%s`.' % json.dumps(mirror['stats'], sort_keys=True))
    w('-/')
    w('')
    w('namespace %s' % base)
    w('')
    w('open NoFourMUBs.KernelAtlas')
    w('')
    w('def cfg : Cfg where')
    w('  boff := %d' % par.BOFF)
    w('  Z := %d' % par.Z)
    w('  six := %d' % par.SIX_Z2)
    w('  s6z := %d' % par.S6Z)
    w('  q2 := %d' % par.Q2)
    w('  eq := %d' % par.EQ)
    w('  W0 := %s' % v12(W0))
    w('  lv := fun d => match d with')
    for dd in range(4):
        w('    | %s => ⟨%d, %d, %d⟩' % (str(dd) if dd < 3 else '_', par.thi[dd], par.tlo[dd], par.thr[dd]))
    w('')
    w('def pq : ParQ where')
    for nm, val in (('pihi', par.pihi), ('s6lo', KB.S6LO), ('s6hi', KB.S6HI), ('i6hi', KB.I6HI), ('x29hi', KB.X29HI),
                    ('rbar', rbar), ('rFbar', rFbar), ('Kbar', Kbar), ('E', par.E), ('eps1', par.eps1)):
        w('  %s := %s' % (nm, q_lit(val)))
    w('')
    epsUd, epsPd = epsU, epsP
    assert Fr(1, 2 ** p) + epsUd * (1 + epsPd) + epsPd <= par.eps1 and epsPd <= par.eps1
    w('def tab : Tab where')
    w('  p := %d' % p)
    w('  nT := %d' % KB.NTAYLOR)
    w('  EUL := [%s]' % ', '.join('(%d, %d)' % e for e in EU))
    w('  EPL := [%s]' % ', '.join('[%s]' % ', '.join('(%d, %d)' % e for e in row) for row in EP))
    w('  PqL := [%s]' % ', '.join('[%s]' % ', '.join(q_lit(x) for x in row) for row in Prad))
    w('  epsU := %s' % q_lit(epsUd))
    w('  epsP := %s' % q_lit(epsPd))
    w('')
    for m in range(5):
        for b in range(12):
            w('def T%d_%d : CT :=\n  %s' % (m + 1, b, ct(R5[m][b])))
            w('')
        w('def L%d : List CT := [%s]' % (m + 1, ', '.join('T%d_%d' % (m + 1, b) for b in range(12))))
        w('')
    w('/-- Leaf predicate of this benchmark: depth-0 survivors are accepted (a full Stage C checks label membership). -/')
    w('def leafT : LeafFn := fun _ _ _ _ _ _ => true')
    w('')
    w('theorem parOK : ParOK cfg pq := by decide +kernel')
    w('')
    w('theorem tabOK : tabB tab cfg pq L1 L2 L3 L4 L5 = true := by decide +kernel')
    w('')
    w('theorem rootsOK : RootsK L1 ∧ RootsK L2 ∧ RootsK L3 ∧ RootsK L4 ∧ RootsK L5 := by decide +kernel')
    w('')
    w('end %s' % base)
    with open(os.path.join(outdir, 'Data.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    for b1 in range(12):
        L = ['import %s.Data' % mod(base), '',
             '/-! Record %d, slab `b₁ = %d`: twelve sub-slabs, one kernel declaration each (generated). -/' % (a.idx, b1), '',
             'namespace %s' % base, '', 'open NoFourMUBs.KernelAtlas', '']
        for b2 in range(12):
            L.append('theorem sub_%d_%d : slabOK cfg leafT T1_%d [T2_%d] L3 L4 L5 = true := by decide +kernel' % (b1, b2, b1, b2))
            L.append('')
        L.append('end %s' % base)
        with open(os.path.join(outdir, 'Slab%02d.lean' % b1), 'w') as f:
            f.write('\n'.join(L) + '\n')
    L = ['import %s.Slab%02d' % (mod(base), b) for b in range(12)]
    L += ['', '/-!', '# Record %d: the direct-test bin tree, end to end (generated)' % a.idx, '',
          'Every phase vector `β ∈ [0,1]⁵` lies in a bin that is rejected by the direct single-vector test for every',
          'admissible `δ` of the Record ball, or in a depth-0 (`M = 96`) bin.  Hypotheses: the operator-norm bound `K`',
          'and the Stage C radii `r ≤ r̄`, `r_F ≤ r̄_F` (cycles), which come from the normal bound (not yet in the kernel).',
          '-/', '', 'namespace %s' % base, '', 'open Hadamard6 NoFourMUBs NoFourMUBs.StageC NoFourMUBs.KernelAtlas', '']
    L.append('theorem slabs : ∀ c1 ∈ L1, slabOK cfg leafT c1 L2 L3 L4 L5 = true := by')
    L.append('  intro c1 hc1')
    L.append('  simp only [L1, List.mem_cons, List.mem_nil_iff, or_false] at hc1')
    L.append('  rcases hc1 with %s' % ' | '.join(['rfl'] * 12))
    for b1 in range(12):
        L.append('  · refine slabOK_of_sub fun c2 hc2 => ?_')
        L.append('    simp only [L2, List.mem_cons, List.mem_nil_iff, or_false] at hc2')
        L.append('    rcases hc2 with %s' % ' | '.join(['rfl'] * 12))
        L.append('    exacts [%s]' % ', '.join('sub_%d_%d' % (b1, b2) for b2 in range(12)))
    L.append('')
    L.append('theorem cover {T : Fin 4 → RMat6} {rH n r rF K : ℝ} (hK0 : 0 ≤ K)')
    L.append('    (hK : ∀ z, cnorm (Qop ((1 / (2 * Real.pi)) • Pmat tab.pq) z) ≤ K * cnorm z)')
    L.append('    (hKb : K ≤ pq.Kbar) (hr : r ≤ pq.rbar) (hrF : rF ≤ pq.rFbar) :')
    L.append('    ∀ β : I6 → ℝ, β j0 = 0 → (∀ j, 0 ≤ β j ∧ β j ≤ 1) →')
    L.append('      Covered (Pmat tab.pq) T rH n r rF cfg.W0 leafT β := by')
    L.append('  obtain ⟨hW, h1, h2, h3, h4, h5⟩ := tabB_spec tabOK')
    L.append('  obtain ⟨r1, r2, r3, r4, r5⟩ := rootsOK')
    L.append('  exact topOK_sound parOK hW hK0 hK hKb hr hrF leafT h1 h2 h3 h4 h5 r1 r2 r3 r4 r5 slabs')
    L.append('')
    L.append('end %s' % base)
    with open(os.path.join(outdir, 'Cover.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(json.dumps(dict(idx=a.idx, rcol=rcol, rF=rF, rH=rH, n=nN, p=p, q=q, mirror=mirror,
                          E=float(par.E), eps1=float(par.eps1)), indent=1, default=float))


if __name__ == '__main__':
    main()

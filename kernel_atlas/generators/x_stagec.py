"""Kernel Stage C data for return X's neighbourhood of F6 (lean/NoFourMUBs/X/README.md).

Usage (from the repository root, with numpy):
  python3 kernel_atlas/generators/x_stagec.py OUTDIR [--rho 3/20] [--normal 147/8000] [--col 21/200]
      [--label-radius X] [--no-search] [--module NS]
  python3 kernel_atlas/generators/x_stagec.py OUTDIR --compile [--jobs 2] [--resume]

The Record pipeline of `seed_stagec.py` (v2 bin tree with label leaves, direct and joint edges, clique search) on
  centre  P~ = the table centre: P~[j][i] = 2 pi~ (j i mod 6) / 6 with pi~ = PI_LO (radians, rational);
  frame   T = V, the four horizontal natural tangent generators of F6 (return X eq. (7)); V = VT / 6, VT integral,
          so the integer frame is exact with DT = 6;
  radii   (radians) r_H = r_F = rad (>= rho + eps, eps = 10^-18 >= ||P_F - P~||_F), n, r_col.
Writes Data, T2Data, L2Data, H2Slab*, CoverH2, Rows2, Hints2, Edg*, [Clq*], Graph2, StageC2 (the Record modules,
`seed_stagec.py`'s writers), Sigma.lean (sigma, e0, j1 at P~ on a high-precision table, `knormal.py`'s mirrors) and
XC.lean: `core`, return X at radius rho for the exact F6 (`KernelAtlas/X/StageC.lean`, `x_core`).
Nothing here is trusted: the kernel re-derives every claim; floats are only predictors.
"""
import argparse, collections, json, os, sys, time
from fractions import Fraction as Fr

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import seed_stagec as SS                                                # noqa: E402

KB, KL2, SC, kpack = SS.KB, SS.KL2, SS.SC, SS.kpack
DTX = 6
SS.DT = DTX                   # the integer frame T' - OT = VT = 6 V (Frame and write_t2data read SS.DT)

BASE = 'NoFourMUBs.KernelAtlas.X.SC'


def vt():
    """VT[k][j][i] = 6 V_k: the horizontal projection (times 6) of return X's generators (7), as verify_cover.py."""
    out = []
    for k in range(4):
        f = [0, int(k == 0), int(k == 1)]
        g = [0, int(k == 2), int(k == 3)]
        v = [[(j % 2) * f[i % 3] + (i % 2) * g[j % 3] for i in range(6)] for j in range(6)]
        rows = [sum(r) for r in v]
        cols = [sum(v[j][i] for j in range(6)) for i in range(6)]
        tot = sum(rows)
        assert tot % 6 == 0
        out.append([[6 * v[j][i] - rows[j] - cols[i] + tot // 6 for i in range(6)] for j in range(6)])
    return out


EPSX = Fr(1, 10 ** 18)        # `epsX` of KernelAtlas/X/StageC.lean: ||P_F - P~||_F <= 6 (10/6)(PI_HI - PI_LO) <= EPSX
S2HI = Fr(1414213563, 10 ** 9)
KN = SS.KN


def x_data(rad, normal, col):
    assert 10 * (KB.PI_HI - KB.PI_LO) <= EPSX
    Prad = [[2 * KB.PI_LO * ((j * i) % 6) / 6 for i in range(6)] for j in range(6)]
    That = vt()
    rads = dict(rH=rad, n=normal, rcol=col, rF=rad)
    Uf = np.array([[[That[k][j][i] / DTX for k in range(4)] for i in range(6)] for j in range(6)]).reshape(36, 4)
    return dict(Prad=Prad, That=That, rads=rads, Uf=Uf, eps=EPSX)


def scalar_ok(rho, sigma, e0, j1, R):
    """The exact mirror of the scalar part of `xB`."""
    re = rho + EPSX
    return (0 < sigma and rho >= 0 and j1 >= 0 and e0 >= 0 and re <= R['rH'] and re <= R['rF'] and
            e0 + j1 * re + S2HI * re * re <= sigma * R['n'] and re * re <= 3 * (R['rcol'] - R['n']) ** 2 and
            R['n'] <= R['rcol'])


def write_sigma(outdir, base, title, xd, sigma, tau):
    """Sigma.lean: `tabN`, `sigq`, `sigmaOK_`, `e0OK_`, `j1OK_` on the frame `frameOf tcfg2 tq2` (as `knormal.py`)."""
    q = SS.q_lit
    X, eps = KN.tabN_data(xd['Prad'])
    F = [[[Fr(xd['That'][k][j][i], DTX) for i in range(6)] for j in range(6)] for k in range(4)]
    s, Lrows, st = KN.sigma_cert(X, eps, F, sigma, tau=tau)
    e0, j1 = KN.e0_j1(X, eps, F)
    L = ['import %s.T2Data' % SS.mod(base), 'import KernelAtlas.E0K', '',
         '/-! %s: `σ = %s`, `e₀`, `j₁` at the centre `P̃` with the frame `V` (generated by `x_stagec.py`; γ = %.2e,'
         % (title, sigma, st['gamma']), 'smallest remainder diagonal %.2e). -/' % st['min_diag']] + SS.head(base) + [
        '/-- The high-precision table of `exp(−i P̃)` (`p = %d`, Taylor order %d), on the same centre as `tab`. -/'
        % (KN.PN, KN.NTN),
        'def tabN : Tab where', '  p := %d' % KN.PN, '  nT := %d' % KN.NTN, '  EUL := []',
        '  EPL := [%s]' % ', '.join('[%s]' % ', '.join('(%d, %d)' % e for e in row) for row in X),
        '  PqL := tab.PqL', '  epsU := 0', '  epsP := %s' % q(eps), '',
        'set_option maxHeartbeats 0 in', 'def sigq : SigQ where', '  cpen := 10', '  s := %s' % q(s),
        '  Lrows := [%s]' % ', '.join('[%s]' % ', '.join(str(v) for v in row) for row in Lrows),
        '  Lden := %d' % KN.LDEN, '',
        'def sigmaq : ℚ := %s' % q(sigma), '', 'def e0q : ℚ := %s' % q(e0), '', 'def j1q : ℚ := %s' % q(j1), '',
        'theorem sigmaOK_ : sigmaOK tabN (frameOf tcfg2 tq2) sigq sigmaq = true := by decide +kernel', '',
        'theorem e0OK_ : e0OK tabN e0q = true := by decide +kernel', '',
        'theorem j1OK_ : j1OK tabN (frameOf tcfg2 tq2) j1q = true := by decide +kernel', '',
        'end %s' % base]
    SS.put(outdir, 'Sigma', L)
    return e0, j1, st


def write_xc(outdir, base, title, xd, rho):
    R = xd['rads']
    q = SS.q_lit
    L = ['import %s.StageC2' % SS.mod(base), 'import %s.Sigma' % SS.mod(base), 'import KernelAtlas.X.StageC', '',
         '/-! %s: return X at radius `ρ = %s` for the exact F6, every check by the kernel (generated by' % (title, rho),
         '`x_stagec.py`). -/'] + SS.head(base, 'Hadamard6', 'NoFourMUBs', 'NoFourMUBs.StageC', 'NoFourMUBs.KernelAtlas',
                                         'NoFourMUBs.KernelAtlas.X', 'NoFourMUBs.X') + [
        'def rads : XRadii where',
        '  rH := %s' % q(R['rH']), '  n := %s' % q(R['n']), '  rcol := %s' % q(R['rcol']), '  rF := %s' % q(R['rF']), '',
        'def rhoq : ℚ := %s' % q(rho), '',
        '/-- Centre `P̃`, frame `V`, the radii under the bars, `K̄`, and the scalar conditions at `ρ`. -/',
        'theorem hx : xB tab tcfg2 tq2 pq rads rhoq sigmaq e0q j1q = true := by decide +kernel', '',
        '/-- **Return X at radius `ρ`** (`x_core`). -/',
        'theorem core : ∀ δ : RMat6, IsHorizontal δ → frob δ ≤ (rhoq : ℝ) → Hadamard6.IsHadamard (phaseMat (PF + δ)) →',
        '    ¬ QuartetEdge (phaseMat (PF + δ)) :=',
        '  x_core (tbN := tabN) hx rfl sigmaOK_ e0OK_ j1OK_ fun hK0 hK hKb hr hrF hrH hn => stageC2 hK0 hK hKb hr hrF hrH hn',
        '', 'end %s' % base]
    SS.put(outdir, 'XC', L)


def generate(outdir, base, rho, rad, normal, col, sigma, tau, label_radius, search, log=print):
    sys.set_int_max_str_digits(0)
    sys.setrecursionlimit(100000)
    os.makedirs(outdir, exist_ok=True)
    t0 = time.time()
    xd = x_data(rad, normal, col)
    cd = SS.checker_data(xd)
    e0, j1, sst = write_sigma(outdir, base, 'return X (F6, rho = %s)' % rho, xd, sigma, tau)
    assert scalar_ok(rho, sigma, e0, j1, xd['rads']), 'the scalar conditions of xB fail'
    log('sigma %s: e0 = %.3e, j1 = %.3e, %s' % (sigma, e0, j1, sst))
    title = 'return X (F6, rho = %s)' % rho
    info = dict(rho=str(rho), rad=str(rad), n=str(normal), col=str(col), sigma=str(sigma), e0=float(e0), j1=float(j1), rbar=float(cd['par'].rbar),
                rFbar=float(cd['par'].rFbar), rHbar=float(cd['tp'].rHbar), nbar=float(cd['tp'].nbar))
    log('X: %s' % info)
    SS.write_data(outdir, base, title, cd, xd['Prad'])
    SS.write_t2data(outdir, base, title, cd)
    t1 = time.time()
    S = []
    ok, st, _ = KL2.run(cd['par'], cd['tc'], cd['t2'], cd['W0'], cd['R5'],
                        leaf_cb=lambda acc, ts: S.append(tuple(t[0] for t in ts)) or True)
    log('mirror: %d v2 survivors (ok %s), %.0fs; %s' % (len(S), ok, time.time() - t1, st))
    P = np.array([[float(x) for x in row] for row in xd['Prad']]) / SC.TWO_PI          # cycles
    labs, how = SS.choose_labels(S, cd, P, xd['Uf'], label_radius, 'X', search)
    n = len(labs)
    log('labels: %d (%s), largest s = %.5f' % (n, how, float(max(s for _, s, _ in labs))))
    SS.write_labels(outdir, base, title, labs, len(S), how)
    t1 = time.time()
    ok2, st2, hints = KL2.run(cd['par'], cd['tc'], cd['t2'], cd['W0'], cd['R5'], stats={}, labels=labs)
    assert ok2, 'the label-hinted traversal fails'
    kinds = collections.Counter(h % 4 for v in hints.values() for h in v)
    log('label hints: %d hints (%d leaf, %d scalar, %d linear, %d none), %.0fs'
        % (sum(kinds.values()), kinds[3], kinds[1], kinds[2], kinds[0], time.time() - t1))
    SS.write_slabs(outdir, base, title, hints, n)
    t1 = time.time()
    g = SS.label_graph(cd, labs, P, xd['Uf'])
    log('pairs: %s; two cliques found: %s; %d clique calls; %.0fs' % (g['stats'], g['found'], g['calls'],
                                                                      time.time() - t1))
    assert not g['found'], 'the label graph has two cliques'
    g['bitset'] = g['calls'] > SS.BITSET_MIN
    if g['bitset']:
        g['QCH'], g['qcalls'] = SS.bitset_chunks(g['oR'], g['uR'], n)
    SS.write_graph(outdir, base, title, g, n)
    assert 1 + e0 / 4 <= cd['par'].Kbar ** 2, 'e0 too large for Kbar'
    write_xc(outdir, base, title, xd, rho)
    kpack.seal(outdir)
    info.update(survivors=len(S), labels=n, label_how=how, hints=dict(all=sum(kinds.values()), leaf=kinds[3],
                scalar=kinds[1], linear=kinds[2], none=kinds[0]), graph=g['stats'], clique_calls=g['calls'],
                bitset=g['bitset'], gen_s=round(time.time() - t0, 1))
    with open(os.path.join(outdir, '.x_stagec.json'), 'w') as f:
        json.dump(info, f, indent=1)
    return info


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--rho', default='150001/1000000', help='the certified radius (rho + 10^-18 <= rad)')
    ap.add_argument('--rad', default='150002/1000000', help='Stage C r_H = r_F (radians)')
    ap.add_argument('--sigma', default='17319/10000')
    ap.add_argument('--tau', type=float, default=1e-4, help='Cholesky shift of the sigma certificate')
    ap.add_argument('--normal', default='147/8000')
    ap.add_argument('--col', default='21/200')
    ap.add_argument('--label-radius', type=float, default=0.05)
    ap.add_argument('--no-search', dest='search', action='store_false')
    ap.add_argument('--module', default=BASE)
    ap.add_argument('--compile', action='store_true')
    ap.add_argument('--jobs', type=int, default=2)
    ap.add_argument('--resume', action='store_true')
    a = ap.parse_args()
    if a.compile:
        res = SS.compile_ball(a.out, a.module, a.jobs, resume=a.resume)       # its axiom check names SeedC: redone here
        env, lean = SS.lean_env()
        ax = os.path.join(a.out, '.logs', 'AxiomsX.lean')
        with open(ax, 'w') as f:
            f.write('import %s.XC\n#print axioms %s.core\n' % (SS.mod(a.module), a.module))
        r = SS.subprocess.run([lean, ax], cwd=SS.LEAN, env=env, capture_output=True, text=True)
        m = SS.re.search(r'depends on axioms: \[(.*?)\]', r.stdout, SS.re.S)
        res['axioms'] = sorted(x.strip() for x in m.group(1).split(',')) if m else r.stdout + r.stderr
        res['axioms_ok'] = bool(m) and set(res['axioms']) <= SS.AXIOMS
        print(json.dumps({k: v for k, v in res.items() if k != 'modules'}, indent=1))
        return
    info = generate(a.out, a.module, Fr(a.rho), Fr(a.rad), Fr(a.normal), Fr(a.col), Fr(a.sigma), a.tau,
                    a.label_radius, a.search)
    print(json.dumps(info, indent=1))


if __name__ == '__main__':
    main()

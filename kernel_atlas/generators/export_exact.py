"""Export the exact memberships of the `fourier` and `tao` fields (`KernelAtlas/ExactK.lean`).

Usage (repository root): python3 kernel_atlas/generators/export_exact.py [out dir, default kernel_atlas/lean/KernelAtlas/Special]

Writes `Exact.lean` (namespace `NoFourMUBs.KernelAtlas.Special`):
  * `fourierT`: `fourierHadamard` into the atlas Record found by `kexact.find_atlas_member` (alignment, winding,
    the Record's binary64 centre and radius), checked by `memOK` (`decide +kernel`);
  * `taoPos`, `taoNeg`: `taoMatrix ω` and `taoMatrix ω̄` into the zero-dimensional Tao Record of `proof/atlas/tao.py`
    (centre fl(2πK/3), R = 0.08), plain permutations;
  * `fourier`, `tao`: the two fields of `AtlasCertificate` for any atlas containing those Records.
"""
import os, sys
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import kexact as KX
from kbound import inv
from export_record import q_lit


def ilist(xs):
    return '[%s]' % ', '.join(str(int(x)) for x in xs)


def plist(P):
    return '[%s]' % ', '.join('[%s]' % ', '.join(q_lit(x) for x in row) for row in P)


def tgt(al, pt, Rt):
    return ('{ cj := %s, tr := %s, rp := %s, rpi := %s, cp := %s, cpi := %s,\n'
            '    N := %s,\n    Pt := %s, Rt := %s, Y := [], G := [], Th := [] }') % (
        'true' if al['sg'] == -1 else 'false', 'true' if al['tr'] else 'false', ilist(al['rp']), ilist(inv(al['rp'])),
        ilist(al['cp']), ilist(inv(al['cp'])), ilist([x for r in al['N'] for x in r]), pt, q_lit(Rt))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'kernel_atlas/lean/KernelAtlas/Special')
    os.makedirs(out, exist_ok=True)
    t, alF, mF, PtF, RtF = KX.find_atlas_member(KX.fourier_mq())
    PT, RT = KX.tao_centre(), Fr(0.08)
    mP, alP = KX.find_perm_member(KX.tao_mq(1), PT, RT)
    mN, alN = KX.find_perm_member(KX.tao_mq(-1), PT, RT)
    assert alP['sg'] == 1 and not alP['tr'] and alN['sg'] == 1 and not alN['tr']
    L = ['import KernelAtlas.ExactK', '',
         '/-! The exact memberships of the `fourier` and `tao` fields (generated by `export_exact.py`).', '',
         '* `fourierHadamard` lies in atlas Record %d (margin %.3e of R = %s);' % (t, mF, float(RtF)),
         '* `taoMatrix ω`, `taoMatrix ω̄` lie in the zero-dimensional Tao Record of `proof/atlas/tao.py`',
         '  (centre fl(2πK/3), R = 0.08; margins %.3e, %.3e). -/' % (mP, mN), '',
         'namespace NoFourMUBs.KernelAtlas.Special', '', 'open Hadamard6 NoFourMUBs NoFourMUBs.KernelAtlas', '',
         'set_option maxRecDepth 100000', '',
         '/-- `fourierHadamard` into atlas Record %d. -/' % t,
         'def fourierT : BTgt :=', '  ' + tgt(alF, plist(PtF), RtF), '',
         '/-- The centre of the Tao Record. -/', 'def taoPL : List (List ℚ) := %s' % plist(PT), '',
         'def taoPos : BTgt :=', '  ' + tgt(alP, 'taoPL', RT), '',
         'def taoNeg : BTgt :=', '  ' + tgt(alN, 'taoPL', RT), '',
         'theorem fourierT_ok : memOK fourierMq fourierT = true := by decide +kernel', '',
         'theorem taoPos_ok : memOK (taoMq 1) taoPos = true := by decide +kernel', '',
         'theorem taoNeg_ok : memOK (taoMq (-1)) taoNeg = true := by decide +kernel', '',
         '/-- **The `fourier` field** for any atlas whose Record `l` is atlas Record %d. -/' % t,
         'theorem fourier {ι : Type*} (A : ι → RecordCert) (l : ι) (hP : (A l).P = Pmat fourierT.pt)',
         '    (hR : (fourierT.Rt : ℝ) ≤ (A l).R) : Step2.FourierAnchorCertificate (InAtlas A) :=',
         '  fourierK A l fourierT_ok hP hR', '',
         '/-- **The `tao` field** for any atlas whose Record `l` is the Tao Record. -/',
         'theorem tao {ι : Type*} (A : ι → RecordCert) (l : ι) (hP : (A l).P = Pmat taoPos.pt)',
         '    (hR : (taoPos.Rt : ℝ) ≤ (A l).R) :',
         '    ∀ ω, IsPrimitiveCubicPhase ω → ∃ K, InAtlas A K ∧ Equivalent (taoMatrix ω) K :=',
         '  taoK A l taoPos_ok taoNeg_ok ⟨rfl, rfl⟩ ⟨rfl, rfl⟩ hP hR hP hR', '',
         'end NoFourMUBs.KernelAtlas.Special']
    with open(os.path.join(out, 'Exact.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('fourier -> Record %d (margin %.3e); tao margins %.3e, %.3e' % (t, mF, mP, mN))


if __name__ == '__main__':
    main()

"""Export Tao's zero-dimensional Record (`proof/atlas/tao.py`) as a kernel `RecordCert` (`KernelAtlas/RecordK0.lean`).

Usage (repository root): python3 kernel_atlas/generators/export_tao.py [out dir, default kernel_atlas/lean/KernelAtlas/RecTao]

The Record: centre fl(2πK/3) (numpy, as tao.py), R = 0.08, label radius 0.03, frame T = 0 (tangent dimension 0), so
g = λ = t = 0, r_H = 0 and the Stage C radii are all n = n̄ = 2e₀/(σ + s_lo).  Written (namespace
`NoFourMUBs.KernelAtlas.RecTao`), with the v1 Stage C generators on the zero frame:
  * `Data.lean` (export_record.export, no direct-test slabs), `TangentData.lean`, `LabelData.lean`, `Graph.lean`,
    `StageC.lean`, `TangentSlab*.lean`, `TangentCover.lean` (export_tangent);
  * `Sigma.lean`: the table `tabN`, σ = 2 on the whole horizontal space (`sigmaOK` with the zero frame), e₀, j₁ = 0,
    and `frameZero`;
  * `Record.lean`: `cert := recordK0 …` and the match with `Special.taoPos` (centre and radius of the `tao` field).
"""
import json, math, os, sys
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, 'proof', 'atlas'))
import kexact as KX
import knormal as KN
import export_record as ER
import export_tangent as ET
from export_record import q_lit

BASE = 'NoFourMUBs.KernelAtlas.RecTao'
MOD = 'KernelAtlas.RecTao'
SIGMA = Fr(2)
R = Fr(0.08)
LABEL_RADIUS = 0.03


def consts():
    P = KX.tao_centre()
    X, eps = KN.tabN_data(P)
    F = [[[Fr(0)] * 6 for _ in range(6)] for _ in range(4)]
    s, Lrows, st = KN.sigma_cert(X, eps, F, SIGMA)
    e0, j1 = KN.e0_j1(X, eps, F)
    assert j1 == 0
    D = SIGMA * SIGMA - 4 * KN.S3HI * e0
    assert D > 0 and 2 * KN.S3HI * R < SIGMA
    slo = KN.sqrt_down(D)
    nbar = 2 * e0 / (SIGMA + slo)
    return dict(P=P, X=X, eps=eps, s=s, Lrows=Lrows, st=st, e0=e0, j1=j1, slo=slo, nbar=nbar)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'kernel_atlas/lean/KernelAtlas/RecTao')
    os.makedirs(out, exist_ok=True)
    kc = consts()
    P = kc['P']
    rec = dict(phi=[float(P[j][i]).hex() for j in range(6) for i in range(6)], R=float(R), label_radius=LABEL_RADIUS)
    assert all(Fr(float.fromhex(rec['phi'][6 * j + i])) == P[j][i] for j in range(6) for i in range(6))
    n = kc['nbar']
    rads = (n, n, Fr(0), n)                                     # r_col, r_F, r_H, n (radians)
    info_d = ER.export(rec, 'Tao', out, BASE, rads=rads, slabs=False)
    That = [[[0] * 6 for _ in range(6)] for _ in range(4)]
    par, tc, tp, W0, R5, info = ET.record_data(None, rec=rec, That=That, rads=rads)
    ET.write_data(out, BASE, 'Tao', par, tc, tp, info)
    info['labels'] = ET.write_labels(out, BASE, 'Tao', par, tc, tp, W0, R5, label_radius=LABEL_RADIUS)
    ET.write_tslabs(out, BASE, 'Tao', '(leafL labs)', 'LabelData')
    # the normal bound on the whole horizontal space
    L = ['import %s.TangentData' % MOD, 'import KernelAtlas.RecordK0', '',
         '/-! Tao\'s Record: the bound `σ = %s` on the whole horizontal space (zero frame; generated by `export_tao.py`;'
         % SIGMA, 'γ = %.2e, smallest remainder diagonal %.2e), e₀ = %.3e, j₁ = 0. -/' % (
             kc['st']['gamma'], kc['st']['min_diag'], float(kc['e0'])), '',
         'namespace %s' % BASE, '', 'open NoFourMUBs.KernelAtlas', '',
         'def tabN : Tab where', '  p := %d' % KN.PN, '  nT := %d' % KN.NTN, '  EUL := []',
         '  EPL := [%s]' % ', '.join('[%s]' % ', '.join('(%d, %d)' % e for e in row) for row in kc['X']),
         '  PqL := tab.PqL', '  epsU := 0', '  epsP := %s' % q_lit(kc['eps']), '',
         'set_option maxHeartbeats 0 in', 'def sigq : SigQ where', '  cpen := 10', '  s := %s' % q_lit(kc['s']),
         '  Lrows := [%s]' % ', '.join('[%s]' % ', '.join(str(v) for v in row) for row in kc['Lrows']),
         '  Lden := %d' % KN.LDEN, '',
         'theorem frameZero_ : frameZero (frameOf tcfg tq) = true := by decide +kernel', '',
         'set_option maxHeartbeats 0 in',
         'theorem sigmaOK_ : sigmaOK tabN (frameOf tcfg tq) sigq %s = true := by decide +kernel' % q_lit(SIGMA), '',
         'def e0q : ℚ := %s' % q_lit(kc['e0']), '',
         'set_option maxHeartbeats 0 in', 'theorem e0OK_ : e0OK tabN e0q = true := by decide +kernel', '',
         'set_option maxHeartbeats 0 in', 'theorem j1OK_ : j1OK tabN (frameOf tcfg tq) 0 = true := by decide +kernel', '',
         'end %s' % BASE]
    with open(os.path.join(out, 'Sigma.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    L = ['import %s.StageC' % MOD, 'import %s.Sigma' % MOD, 'import KernelAtlas.Special.Exact',
         'import KernelAtlas.Assembly', '',
         '/-! Tao\'s zero-dimensional Record as a `RecordCert`, every field checked by the kernel (generated by',
         '`export_tao.py`): R = 0.08, σ = 2, n̄ = %.3e rad. -/' % float(kc['nbar']), '',
         'namespace %s' % BASE, '', 'open Hadamard6 NoFourMUBs NoFourMUBs.StageC NoFourMUBs.KernelAtlas', '',
         'def bars : BarsQ where', '  R := %s' % q_lit(R), '  sigma := %s' % q_lit(SIGMA), '  e0 := e0q', '  j1 := 0',
         '  slo := %s' % q_lit(kc['slo']), '',
         'theorem barsOK_ : barsOK0 bars pq tq = true := by decide +kernel', '',
         '/-- **Tao\'s Record, certified.** -/', 'noncomputable def cert : RecordCert :=',
         '  recordK0 (tb := tab) (tbN := tabN) (F := frameOf tcfg tq) (S := sigq) (B := bars) (pq := pq) (tq := tq)',
         '    rfl frameZero_ sigmaOK_ e0OK_ j1OK_ barsOK_',
         '    fun hK0 hK hKb hr hrF hrH hn => by rw [frameOf_toR]; exact stageC hK0 hK hKb hr hrF hrH hn', '',
         '/-- The centre and radius of the `tao` field\'s target. -/',
         'theorem cert_P : cert.P = Pmat Special.taoPos.pt := by',
         '  show Pmat tab.pq = Pmat Special.taoPos.pt',
         '  congr 1', '',
         'theorem cert_R : (Special.taoPos.Rt : ℝ) ≤ cert.R := by',
         '  show (Special.taoPos.Rt : ℝ) ≤ (bars.R : ℝ)',
         '  exact_mod_cast (show Special.taoPos.Rt ≤ bars.R by decide +kernel)', '',
         '/-- **The `tao` field** for any atlas containing Tao\'s Record. -/',
         'theorem tao {ι : Type*} (A : ι → RecordCert) (l : ι) (hl : A l = cert) :',
         '    ∀ ω, IsPrimitiveCubicPhase ω → ∃ K, InAtlas A K ∧ Equivalent (taoMatrix ω) K :=',
         '  Special.tao A l (by rw [hl]; exact cert_P) (by rw [hl]; exact cert_R)', '',
         'theorem nbar_lt : bars.nbar0 < bars.R := by decide +kernel', '',
         '/-- **The boundary field of Tao\'s Record**: empty, since `T = 0` and `n < R`. -/',
         'theorem boundary {ι : Type*} (A : ι → RecordCert) (l : ι) (hl : A l = cert) :',
         '    Nonempty (BoundaryCover A l) := by',
         '  obtain ⟨h0, h1⟩ := nroot_bars0 barsOK_',
         '  have hn : (A l).n = nroot (bars.sigma : ℝ) bars.e0 := by',
         '    rw [hl]',
         '    show nroot (bars.sigma : ℝ) ((bars.e0 : ℝ) + ((0 : ℚ) : ℝ) * (0 * bars.R) +',
         '      Real.sqrt 3 * 0 * (0 * bars.R) ^ 2) = _',
         '    congr 1; push_cast; ring',
         '  have hR : (A l).R = bars.R := by rw [hl]; rfl',
         '  refine boundary_zero A l (fun k => by rw [hl]; exact frameZero_toR frameZero_ k) (by rw [hn]; exact h0) ?_',
         '  rw [hn, hR]',
         '  exact lt_of_le_of_lt h1 (by exact_mod_cast nbar_lt)', '',
         'end %s' % BASE]
    with open(os.path.join(out, 'Record.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(json.dumps(dict(e0=float(kc['e0']), nbar=float(kc['nbar']), sigma=float(SIGMA), sigma_stats=kc['st'],
                          direct=info_d['mirror'], **info), indent=1, default=float))

    import kpack
    kpack.seal(out)

if __name__ == '__main__':
    main()

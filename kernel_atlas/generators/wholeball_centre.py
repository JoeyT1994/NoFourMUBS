"""Generate a kernel-checked matched centre for a certificate seed ball.

This reuses the existing exact seed arithmetic and side/forced-block checker.
NumPy only proposes roots and inverses. The output proves centre facts and
enclosures, not the positive-radius whole-ball hC1 claim.

The input seed angles must already be exact on the existing 2^-60 grid. No
floating-point reduction modulo 2*pi is performed on the certified angles.
"""

import argparse
from fractions import Fraction as Q
import gzip
import json
from pathlib import Path

import numpy as np

import seed_c1 as S
from wholeball_scalar import rational, write_module, OUTPUT_ROOT


def exact_grid(value):
    scaled = rational(value) * S.SC
    if scaled.denominator != 1:
        raise ValueError("seed angle is not exactly on the 2^-60 grid")
    return scaled.numerator


def prepare(seed):
    if seed.get("gauge") != "hor" or seed["o"] not in (-1, 1):
        raise ValueError("expected a horizontal seed with orientation ±1")
    if len(seed["theta0"]) != 4 or len(seed["P"]) != 36:
        raise ValueError("invalid seed dimensions")
    angles = [exact_grid(x) for x in seed["theta0"]]
    theta = np.array([float(Q(x, S.SC)) for x in angles])
    phase = np.array([float(rational(x)) for x in seed["P"]]).reshape(6, 6)
    dephased = phase - phase[:, :1] - phase[:1, :] + phase[0, 0]
    gh, gv = S.grams(theta)
    phh, okh = S.newton(dephased[1:3, 3:6].ravel(), gh)
    phv, okv = S.newton(dephased[3:6, 1:3].T.ravel(), gv)
    if not okh or not okv:
        raise ArithmeticError("centre root proposal failed")
    # Keep the lift near the stored record; independent principal reductions
    # would introduce a spurious record error of order 2*pi.
    forced, side, _, _ = S.Df(theta, phh, phv)
    approx_inverse = np.linalg.inv(side.conj().T).ravel()
    arg = np.angle(forced)
    arg += 2 * np.pi * np.round((dephased[3:6, 3:6] - arg) / (2 * np.pi))
    b = dict(th0=angles, Mth=[0] * 16, P=[0] * 36, U=[0] * 144, n=0, o=int(seed["o"]))
    d = dict(wc=[0] * 4, hb=[0] * 4,
             phH=[S.const((S.gz(v), 0)) for v in phh],
             phV=[S.const((S.gz(v), 0)) for v in phv],
             YH=[S.gz(v) for v in np.linalg.inv(S.Jf(phh)).ravel()],
             YV=[S.gz(v) for v in np.linalg.inv(S.Jf(phv)).ravel()],
             tubeH=0, tubeV=0,
             Xp=[S.const((S.gz(v.real), S.gz(v.imag))) for v in forced.ravel()],
             A0=[(S.gz(v.real), S.gz(v.imag)) for v in approx_inverse],
             argA=[S.gz(v) for v in arg.ravel()], wind=[0] * 36)
    e = [S.expI(d["hb"], S.thetaT(b, d, k)) for k in range(4)]
    d["_GH"], d["_GV"] = S.gramH(d["hb"], e), S.gramV(d["hb"], e)
    S.tune_tubes(d)
    del d["_GH"], d["_GV"]
    # c1Box's final remainder test is irrelevant to a centre core. A generous
    # temporary bound allows its existing exact mirror to test the core too.
    accepted, details = S.c1Box(b, d, n=100 * S.SC)
    if not accepted:
        raise ArithmeticError(f"exact centre core mirror rejected the proposal: {details}")
    for side, gram in (("H", S.gramH(d["hb"], e)), ("V", S.gramV(d["hb"], e))):
        ok, error, _, _ = S.sideK(d["hb"], gram, d["ph" + side], d["Y" + side], d["tube" + side])
        rows = S.tubeRows(d["hb"], d["ph" + side], error)
        intervals = [S.ivc(d["hb"], row) for row in rows]
        jacobian = [[S.jI(intervals, i, j) for j in range(6)] for i in range(6)]
        if not ok or any(q >= S.SC for q in S.qRowsI(d["Y" + side], jacobian)):
            raise ArithmeticError(f"centre side {side} Jacobian regularity check failed")
    return b, d


def emit(seed, index, output):
    b, d = prepare(seed)
    rel = Path(output).resolve().relative_to(OUTPUT_ROOT.resolve()).with_suffix("")
    if not all(p.isidentifier() and p.isascii() for p in rel.parts):
        raise ValueError("output module components must be ASCII identifiers")
    ns = "NoFourMUBs.KernelAtlas.WholeBall." + ".".join(rel.parts)
    orientation = "(1 : ℤˣ)" if b["o"] == 1 else "(-1 : ℤˣ)"
    source = (
        "import KernelAtlas.WholeBall.CentreRegular\n\n"
        f"-- Generated by wholeball_centre.py from seed {index}; centre facts only.\n"
        "set_option maxHeartbeats 0\nset_option maxRecDepth 1000000\n\n"
        "open Matrix Hadamard6 NoFourMUBs.SeedAtlas NoFourMUBs.Step2\n"
        "open NoFourMUBs.KernelAtlas.Seed\n\n"
        f"namespace {ns}\n\n" + S.lean_ball("ball", b) + "\n" + S.lean_box("centre", d) + "\n"
        "theorem checked : regularCentreCheck ball centre = true := by decide +kernel\n\n"
        f"theorem regular_centre : Nonempty (RegularCentre (th0R ball) {orientation}) :=\n"
        "  regularCentreCheck_sound checked (by decide +kernel)\n\n"
        "theorem centre_facts :\n"
        "    0 < seedR (seedOf (th0R ball)) ∧ ∃ Q : NoFourMUBs.RMat6,\n"
        f"      Hadamard6.IsHadamard (NoFourMUBs.phaseMat Q) ∧ MatchedO {orientation}\n"
        "        (seedOf (th0R ball)) (NoFourMUBs.phaseMat Q) ∧\n"
        "      (∀ i j, (gT (qModels ball centre) (ix i j)).Has 0 (Q i j : ℂ)) ∧\n"
        "      ∀ i j, (gT (kModels ball centre) (ix i j)).Has 0 (NoFourMUBs.phaseMat Q i j) :=\n"
        "  centreCheck_sound (regularCentreCheck_centre checked) (by decide +kernel)\n\n"
        f"end {ns}\n"
    )
    write_module(output, source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("certificate", type=Path)
    parser.add_argument("index", type=int)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    opener = gzip.open if args.certificate.suffix == ".gz" else open
    with opener(args.certificate, "rt") as stream:
        data = json.load(stream)
    if args.index < 0 or args.index >= len(data["seeds"]):
        parser.error("seed index out of range")
    emit(data["seeds"][args.index], args.index, args.output)
    print(f"emitted centre-only certificate for seed {args.index} of {len(data['seeds'])}")


if __name__ == "__main__":
    main()

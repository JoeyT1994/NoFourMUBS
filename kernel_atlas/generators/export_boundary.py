"""Export the kernel boundary cover of one atlas Record (`KernelAtlas/BoundaryK.lean`, `docs/KERNEL_BOUNDARY.md`).

Usage (repository root): python3 kernel_atlas/generators/export_boundary.py <idx> <out dir> [--module NS]

Writes into <out dir> (the Record's folder, next to its `Data.lean` and `TangentData.lean`):
  * `Boundary.lean`: `bd : BData` (constants, tables, targets, the packed tree) and the kernel checks
    `gOK_`, `tOK_`, `walk_` (`decide +kernel`);
  * `BoundaryCover.lean`: `boundary`, a `BoundaryCover A l` for any family `A` with `A l = cert` whose targets
    `A (tg j)` have the centres and radii of the data (imports `Record.lean`).
The data come from `kbound.py`, an exact mirror of the Lean checker; the kernel re-derives every claim.
"""
import argparse, os, sys, time
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kbound as KBD
from export_record import q_lit


def mod(base):
    return base.replace('NoFourMUBs.KernelAtlas.', 'KernelAtlas.', 1)


def ilist(xs):
    return '[%s]' % ', '.join(str(int(x)) for x in xs)


def flat(M):
    return [M[a][b] for a in range(6) for b in range(6)]


def tgt_lit(t, depth):
    return ('{ cj := %s, tr := %s, rp := %s, rpi := %s, cp := %s, cpi := %s,\n'
            '      N := %s,\n      Pt := [%s],\n      Rt := %s,\n      Y := %s,\n      G := %s,\n      Th := %s }') % (
        'true' if t['sg'] == -1 else 'false', 'true' if t['tr'] else 'false', ilist(t['rp']), ilist(t['rpi']),
        ilist(t['cp']), ilist(t['cpi']), ilist(flat(t['N'])),
        ', '.join('[%s]' % ', '.join(q_lit(x) for x in row) for row in t['Pt']), q_lit(t['Rt']),
        ilist(flat(t['Y'])), ilist([x for row in t['G'] for x in row]), ilist(t['Th'][:depth + 1]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('idx', type=int)
    ap.add_argument('out')
    ap.add_argument('--module', default=None)
    ap.add_argument('--v2', action='store_true', help='a v2 Record: `T2Data` (tcfg2, tq2) and `Record2.lean`')
    a = ap.parse_args()
    tdata, tcn, tqn, recm = ('T2Data', 'tcfg2', 'tq2', 'Record2') if a.v2 else ('TangentData', 'tcfg', 'tq', 'Record')
    base = a.module or 'NoFourMUBs.KernelAtlas.Rec%d' % a.idx
    t0 = time.time()
    B, kc = KBD.record_boundary(a.idx)
    B.search()
    ntg = len(B.tg)
    B.prune()
    code = B.packed()
    assert B.walk(code) == 0
    depth = max(d for d, c in enumerate(B.stats['depth']) if c)
    t1 = time.time()
    assert all(len(t['G']) == 5 for t in B.tg)
    st = B.stats
    L = ['import %s.%s' % (mod(base), tdata), 'import KernelAtlas.BoundaryK', '',
         '/-! Record %d: the boundary cover (generated by `export_boundary.py`).' % a.idx, '',
         '%d targets (of %d stored transfers), a tree of %d boxes (%d off, %d transfer leaves, %d splits, depth %d). -/' % (
             len(B.tg), ntg, len(B.codes), st['off'], st['leaf'], st['split'], depth), '',
         'namespace %s' % base, '', 'open Hadamard6 NoFourMUBs.KernelAtlas', '', 'set_option maxRecDepth 100000', '',
         'noncomputable def bd : BData where',
         '  DT := %d' % B.DT, '  Wn := %d' % B.Wn, '  Wd := %d' % B.Wd, '  L := %d' % B.L,
         '  R := %s' % q_lit(B.R), '  rH := %s' % q_lit(B.rH), '  lam := %s' % q_lit(B.lam),
         '  nbar := %s' % q_lit(B.nbar), '  slam := %s' % q_lit(B.slam), '  sq := %s' % q_lit(B.sq),
         '  GT := %s' % ilist([B.GT[k][l] for k in range(4) for l in range(4)]),
         '  Bd := %s' % ilist(B.Bd[:depth + 1]), '  Phi := %s' % ilist(B.Phi[:depth + 1]),
         '  tg := [']
    L.append(',\n'.join('    ' + tgt_lit(t, depth) for t in B.tg) + ']')
    L += ['  base := %d' % KBD.BASE, '  fuel := %d' % (depth + 1), '  code := 0x%x' % code, '',
          'set_option maxHeartbeats 0 in', 'theorem gOK_ : gOK bd (tcTh %s) = true := by decide +kernel' % tcn, '',
          'set_option maxHeartbeats 0 in', 'theorem tOK_ : bd.tg.all (tOK bd tab.pq (tcTh %s)) = true := by decide +kernel' % tcn, '',
          'set_option maxHeartbeats 0 in', 'theorem walk_ : walk bd bd.fuel 0 0 0 0 0 bd.code = some 0 := by decide +kernel', '',
          'end %s' % base]
    with open(os.path.join(a.out, 'Boundary.lean'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    C = ['import %s.%s' % (mod(base), recm), 'import %s.Boundary' % mod(base), '',
         '/-! Record %d: `BoundaryCover` from the kernel checks of `Boundary.lean` (generated by `export_boundary.py`). -/'
         % a.idx, '', 'namespace %s' % base, '', 'open NoFourMUBs NoFourMUBs.KernelAtlas', '',
         'set_option maxHeartbeats 0 in', 'theorem bdOK_ : bdMatch bd fq bars %s = true := by decide +kernel' % tqn, '',
         '/-- **The boundary cover of Record %d**, for any atlas `A` with `A l = cert` and targets `A (tg j)` with the' % a.idx,
         'centres and radii of `bd.tg`. -/',
         'theorem boundary {ι : Type*} (A : ι → RecordCert) (l : ι) (hl : A l = cert) (tg : ℕ → ι)',
         '    (htP : ∀ j t, bd.tg[j]? = some t → (A (tg j)).P = Pmat t.pt)',
         '    (htR : ∀ j t, bd.tg[j]? = some t → (t.Rt : ℝ) ≤ (A (tg j)).R) : Nonempty (BoundaryCover A l) :=',
         '  boundaryK hl gOK_ tOK_ walk_ bdOK_ tg htP htR', '',
         'end %s' % base]
    with open(os.path.join(a.out, 'BoundaryCover.lean'), 'w') as f:
        f.write('\n'.join(C) + '\n')
    print('Record %d: %d of %d targets used, %d boxes %s, depth %d, code %d bits, %.1fs' % (
        a.idx, len(B.tg), ntg, len(B.codes), st, depth, code.bit_length(), t1 - t0))


if __name__ == '__main__':
    main()

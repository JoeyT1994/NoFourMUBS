"""Check the smaller existing matrix binding, then resume retained classification.

The two proof tasks are independent. A failed matrix check is recorded as a
failure, never retried unchanged; the existing classification work can proceed.
No coefficients or mathematical sources are generated by this sequence.
"""
from pathlib import Path
import datetime
import hashlib
import json
import os
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
AUDIT = ROOT / 'audit'


def main():
    names = ['MATCHED_THIRD_CONSTANT_BINDING10', 'CRITICAL_NONZERO_SUM_REMAINING']
    manifests = {name: hashlib.sha256((AUDIT / (name + '_MANIFEST.json')).read_bytes()).hexdigest()
                 for name in names}
    assert json.loads((AUDIT / 'KERNEL_AUDIT_MATCHED_THIRD_CONSTANT_IMAGE_REDUCTION_STATUS.json')
                      .read_text())['status'] == 'PASS'
    path = AUDIT / 'REDUCED_CONSTANT10_THEN_CRITICAL_STATUS.json'
    state = dict(status='RUNNING', pid=os.getpid(), outcomes={},
                 manifest_pins=manifests,
                 started_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                 atlas_certification=False)
    commands = [
        (names[0], [sys.executable, '-u', 'audit/run_third_moment_adapter.py',
                    names[0], '--exclusive']),
        (names[1], [sys.executable, '-u', 'audit/run_nonzero_sum_remaining.py', '--jobs', '1']),
    ]
    for name, command in commands:
        if (AUDIT / 'SOS_CANONICAL_BUILD_STOP').exists():
            state['status'] = 'YIELDED_BEFORE_NEXT_PHASE'
            path.write_text(json.dumps(state, indent=2) + '\n')
            return
        assert hashlib.sha256((AUDIT / (name + '_MANIFEST.json')).read_bytes()).hexdigest() == manifests[name]
        state['phase'] = name
        path.write_text(json.dumps(state, indent=2) + '\n')
        result = subprocess.run(command, cwd=ROOT)
        outcome = json.loads((AUDIT / (name + '_RUN_STATUS.json')).read_text())
        state['outcomes'][name] = dict(returncode=result.returncode, run_status=outcome)
        path.write_text(json.dumps(state, indent=2) + '\n')
    state['status'] = ('PASS' if all(x['returncode'] == 0 and x['run_status']['status'] == 'PASS'
                                    for x in state['outcomes'].values()) else 'PARTIAL_OR_FAILED')
    state['completed_utc'] = datetime.datetime.now(datetime.timezone.utc).isoformat()
    path.write_text(json.dumps(state, indent=2) + '\n')


if __name__ == '__main__':
    main()

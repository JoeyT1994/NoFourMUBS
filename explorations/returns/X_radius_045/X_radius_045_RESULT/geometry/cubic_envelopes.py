"""Exact rational bounds for distance to the cubic normal predictor.
Mathematical constants are independently regenerated by predictor_residual.py
and certify_symmetric_cross.py; the analytic inequalities are in GEOMETRY.md.
"""
from fractions import Fraction as F
from pathlib import Path
from math import factorial
import importlib.util,json
spec=importlib.util.spec_from_file_location('normal',Path(__file__).with_name('normal_bounds_symmetric.py'));nmod=importlib.util.module_from_spec(spec);spec.loader.exec_module(nmod)
sqrtup=nmod.sqrtup;ceiling=nmod.ceiling
B=F(463,1000);C=F(297,500)
D3=sqrtup(F(4,3))
RES={4:sqrtup(F(1,648)),5:sqrtup(F(173,8398080)),6:sqrtup(F(4,98415))}
def mul(a,b):
 out={}
 for i,x in a.items():
  for j,y in b.items():out[i+j]=out.get(i+j,F(0))+x*y
 return out

def envelope(rho,starting_normal=None):
 q2=sqrtup(rho**4/12);p3=sqrtup(rho**6/288);p=sqrtup(rho**4/12+rho**6/288)
 assert p*p<=F(3,2)*rho*rho
 R0=sqrtup(rho*rho+p*p);rp=sqrtup(rho*rho/3)+sqrtup(F(1,2))*p
 low=sum(v*rho**k for k,v in RES.items())
 polynomial={0:F(1)};atom={1:rho,2:q2,3:p3};high=F(0)
 for m in range(1,7):
  polynomial=mul(polynomial,atom)
  if m>=2:
   coefficient=sqrtup(F(2**(m+1),3))/factorial(m)
   high+=coefficient*sum(v for k,v in polynomial.items() if k>=7)
 remainder=sqrtup(F(256,3))*R0**7/factorial(7)
 residual=ceiling(low+high+remainder)
 old=nmod.bounds(rho);n=F(old['normal']);history=[];eps=None
 if starting_normal is not None:n=min(n,F(starting_normal))
 for _ in range(100):
  nr=max(n,p);r=max(nmod.column(rho,n),rp)
  L=ceiling(B*rho+2*C*nr+D3*r*R0)
  if L>=1:break
  error=ceiling(residual/(1-L));new=min(n,ceiling(p+error))
  history.append({'normal':str(n),'L':str(L),'error':str(error),'next_normal':str(new)})
  eps=error
  if new==n:break
  n=new
 out={'rho':str(rho),'predictor_norm':str(p),'cubic_component_norm':str(p3),'predictor_residual':str(residual),'residual_parts':{'degrees4to6':str(low),'composed_terms_degrees7plus':str(high),'Taylor_order7':str(remainder)},'normal':str(n),'column':str(ceiling(nmod.column(rho,n))),'error_to_Q_plus_P3':None if eps is None else str(eps),'error_to_Q':None if eps is None else str(ceiling(p3+eps)),'iterations':history}
 return out

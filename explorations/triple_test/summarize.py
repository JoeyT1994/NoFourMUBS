"""Summarise triples.py output (all *.jsonl in a directory) into SUMMARY.md, and optionally a CSV."""
import argparse, collections, csv, glob, json, os

import numpy as np


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('dir')
    ap.add_argument('--csv')
    a = ap.parse_args()
    rows = {}
    for p in sorted(glob.glob(os.path.join(a.dir, '*.jsonl'))):
        for l in open(p):
            if l.strip():
                r = json.loads(l); rows[r['idx']] = r
    rows = [rows[k] for k in sorted(rows)]
    err = [r for r in rows if 'error' in r]
    ok = [r for r in rows if 'error' not in r]
    trip = [t for r in ok for t in r['triples']]
    cls = collections.Counter(t['class'] for t in trip)
    rec_cls = collections.Counter(' + '.join(r['classes']) or 'none' for r in ok)
    nconv = sum(r['n_converged'] for r in ok); nfail = sum(r['n_failed'] for r in ok)
    unexpl = [(r['idx'], t) for r in ok for t in r['triples'] if t['class'] == 'unexplained']
    dist = np.array([r['min_dist'] for r in ok if r['min_dist'] is not None])
    d3c = np.array([r['delta3'] if r['delta3'] is not None else np.nan for r in ok])
    L = ['# Triple-conjecture test across the atlas (NUMERICAL)', '',
         'Generated by `summarize.py` from `triples.py` output.', '',
         '| | |', '|---|---|',
         '| Records processed | %d (errors %d) |' % (len(rows), len(err)),
         '| candidate starts (6-sets of unbiased vectors) | %d |' % (nconv + nfail),
         '| converged to a triple (residual < 1e-11) | %d |' % nconv,
         '| failed to converge | %d |' % nfail,
         '| distinct triples found | %d |' % len(trip),
         '| Records with no triple found | %d |' % rec_cls.get('none', 0), '',
         '## Classes of the triples found', '', '| class | triples |', '|---|---|']
    L += ['| %s | %d |' % kv for kv in sorted(cls.items())]
    L += ['', '## Classes per Record', '', '| classes | Records |', '|---|---|']
    L += ['| %s | %d |' % kv for kv in sorted(rec_cls.items())]
    if len(dist):
        L += ['', '## Distance ||H* - H||_F from the centre to the nearest triple found', '',
              '| quantile | 0 | 10% | 50% | 90% | 100% |', '|---|---|---|---|---|---|',
              '| distance | ' + ' | '.join('%.3g' % q for q in np.quantile(dist, [0, .1, .5, .9, 1])) + ' |']
        L += ['', '| delta3 bin | Records | median distance |', '|---|---|---|']
        dd = np.array([r['min_dist'] if r['min_dist'] is not None else np.nan for r in ok])
        for lo, hi in ((0, .01), (.01, .05), (.05, .1), (.1, .2), (.2, 9)):
            m = (d3c >= lo) & (d3c < hi)
            L.append('| [%g, %g) | %d | %.3g |' % (lo, hi, m.sum(), np.nanmedian(dd[m]) if m.any() else np.nan))
    L += ['', '## Unexplained triples (candidate counterexamples)', '']
    L += ['- Record %d: %s' % (i, json.dumps(t)) for i, t in unexpl[:50]] or ['None.']
    if err:
        L += ['', '## Errors', ''] + ['- Record %d: %s' % (r['idx'], r['error']) for r in err[:20]]
    open(os.path.join(a.dir, 'SUMMARY.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))
    if a.csv:
        with open(a.csv, 'w', newline='') as f:
            w = csv.writer(f)
            w.writerow(['idx', 'R', 'n_unbiased', 'delta3', 'n_candidates', 'n_converged', 'n_failed', 'n_triples',
                        'classes', 'min_dist', 'wall_s'])
            for r in ok:
                w.writerow([r['idx'], r['R'], r['n_unbiased'], r['delta3'], r['n_candidates'], r['n_converged'],
                            r['n_failed'], len(r['triples']), '+'.join(r['classes']), r['min_dist'], r['wall_s']])


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Replay every exact check of ProvenResults/EdgeRigidity.

Run as `python3 verify.py` from this folder.  Each sub-check recomputes its
exact algebra, asserts its internal identities, and compares its full output
with data/expected_results.json.  That file was generated by these scripts and
coincides with the corresponding archive receipts after removal of their
source-hash fields (no hash of any archive document is checked here).
Prints one PASS line per sub-check; exits nonzero on any failure.

`python3 verify.py --write-expected` regenerates the expected-results file.
"""
from pathlib import Path
import json
import runpy
import sys
import time

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
EXPECTED = HERE/'data'/'expected_results.json'


def cubic_incidence():
    return runpy.run_path(str(HERE/'cubic_incidence.py'), run_name='cubic_incidence')['result']


def checks():
    import block_zero3, quartet_boundary, quartet_corollary, spectral_identities
    import cubic_pair, ternary_rigidity, negative_cubic, one_binary, projector_rank5
    import hx_nonbinary, balanced_rank_two, karlsson_pairing
    return [
        ('zero3_antipodal_block_equivalence', 'BlockZero3Equivalence.md', block_zero3.calculate),
        ('singular_corner_fourier_normal_form', 'SingularCornerNormalForm.md', quartet_boundary.verify),
        ('quartet_edge_corollary_conventions', 'QuartetEdgeCorollary.md', quartet_corollary.calculate),
        ('spectral_slack_cauchy_binet', 'SpectralSlackIdentities.md', spectral_identities.calculate),
        ('cubic_pair_rigidity', 'CubicPairRigidity.md', cubic_pair.calculate),
        ('ternary_matching_positive_sign', 'TernaryMatchingRigidity.md', ternary_rigidity.calculate),
        ('ternary_matching_negative_sign', 'NegativeCubicMatchingExclusion.md', negative_cubic.calculate),
        ('hx_nonbinary_control', 'HXNonbinaryCounterexample.md', hx_nonbinary.calculate),
        ('one_binary_matching', 'OneBinaryMatching.md', one_binary.calculate),
        ('projector_rank5', 'ProjectorRank5.md', projector_rank5.calculate),
        ('balanced_rank_two', 'BalancedRankTwoRigidity.md', balanced_rank_two.calculate),
        ('cubic_incidence', 'CubicIncidence.md', cubic_incidence),
        ('karlsson_pairing_detector', 'KarlssonPairingDetector.md', karlsson_pairing.calculate),
    ]


def main():
    if not __debug__:
        raise SystemExit('Assertions must remain enabled (do not run with -O)')
    write = '--write-expected' in sys.argv
    expected = {} if write else json.loads(EXPECTED.read_text())
    produced, failures = {}, []
    start = time.monotonic()
    for name, proof, function in checks():
        t = time.monotonic()
        try:
            result = json.loads(json.dumps(function(), sort_keys=True))
            produced[name] = result
            if not write and result != expected.get(name):
                raise AssertionError('output differs from data/expected_results.json')
            print(f'PASS {name} [{proof}] ({time.monotonic()-t:.1f}s)', flush=True)
        except Exception as error:  # report and continue, then fail overall
            failures.append(name)
            print(f'FAIL {name} [{proof}]: {type(error).__name__}: {error}', flush=True)
    if write and not failures:
        EXPECTED.parent.mkdir(exist_ok=True)
        EXPECTED.write_text(json.dumps(produced, indent=1, sort_keys=True)+'\n')
        print('wrote', EXPECTED.relative_to(HERE))
    status = 'FAIL' if failures else 'PASS'
    total = len(checks())
    print(f'{status}: EdgeRigidity {total-len(failures)}/{total} sub-checks ({time.monotonic()-start:.1f}s). '
          'Exact identities and certificates for the written proofs; no MUB bound is proved.')
    return 1 if failures else 0


if __name__ == '__main__':
    raise SystemExit(main())

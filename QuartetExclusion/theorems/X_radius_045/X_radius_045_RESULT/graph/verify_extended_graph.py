#!/usr/bin/env python3
"""Exact stronger phase-ball graph certificate; standard library only.

Base centers/quantized-center identities are regenerated by base_48.py.
The new orthogonality tests use radial Taylor support.  Low-overlap
certificates use a universal sine bound and an antipodal-pair dual bound.
All phase radii are radians.
"""
from fractions import Fraction as F
from pathlib import Path
import io,contextlib,json,math
with contextlib.redirect_stdout(io.StringIO()):
    import base_48 as A

Z=A.Z;ONE=A.ONE;rays=A.rays

def sqrt_upper(x,bits=80):
    assert x>=0
    if not x:return F(0)
    q=(x.numerator<<(2*bits))//x.denominator
    n=math.isqrt(q)
    v=F(n+1,1<<bits)
    assert v*v>x
    return v

def positive_upper(x):
    lo,hi=A.iev(x)
    assert hi>=0
    return hi

def absfield(a):return A.abs2(a)

# Reusable exact algebraic pair data.
data=[]
for i,a in enumerate(rays):
    row=[]
    for j,b in enumerate(rays):
        Q=[A.cm(A.cj(x),y) for x,y in zip(a,b)]
        S=A.CZERO
        for q in Q:S=A.ca(S,q)
        s2=A.abs2(S); slo,shi=A.iev(s2)
        tangent_radial2=Z
        for q in Q:
            v=A.cm(A.cj(S),q)[1]
            tangent_radial2=A.ra(tangent_radial2,A.rm(v,v))
        support_sqrt=sqrt_upper(positive_upper(tangent_radial2))
        abs_s=sqrt_upper(max(F(0),shi))
        antipodal_constant=None;antipodal_type=None
        if S==A.CZERO:
            left=Q.copy();reps=[]
            while left:
                q=left.pop()
                k=next((k for k,v in enumerate(left) if v==A.cn(q)),None)
                if k is None:break
                left.pop(k);reps.append(q)
            if len(reps)==3:
                c2=c4=A.CZERO
                for q in reps:
                    q2=A.cm(q,q);q4=A.cm(q2,q2)
                    c2=A.ca(c2,q2);c4=A.ca(c4,q4)
                a2=A.rs(A.abs2(c2),F(19,80)**2)
                b2=A.rs(A.abs2(c4),F(23,960)**2)
                if c2==A.CZERO:
                    extra=sqrt_upper(positive_upper(b2));antipodal_type='C2_zero'
                elif c4==A.CZERO:
                    extra=sqrt_upper(positive_upper(a2));antipodal_type='C4_zero'
                elif A.cm(A.cm(c2,c2),A.cj(c4))[0]==Z:
                    extra=sqrt_upper(positive_upper(A.ra(a2,A.rs(b2,4))));antipodal_type='quadrature'
                else:
                    extra=sqrt_upper(positive_upper(a2))+sqrt_upper(positive_upper(b2));antipodal_type='generic'
                antipodal_constant=F(251,320)+extra
        row.append({'s2':s2,'lo':slo,'hi':shi,'radial':support_sqrt,'abs_s':abs_s,
                    'zero':S==A.CZERO,'antipodal_constant':antipodal_constant,'antipodal_type':antipodal_type})
    data.append(row)

# Rational constants in the antipodal scalar lemma.
assert F(79,240)*F(7,16)**3>F(1,40)
# h(t)=2/3 sin²t-23/120 sin⁴t
assert F(1,2)+F(1,6)==F(2,3)
assert F(1,40)+F(1,6)==F(23,120)
assert F(2,3)/2-F(23,120)*F(3,8)==F(251,960)
assert -F(2,3)/2+F(23,120)/2==-F(19,80)
assert -F(23,120)/8==-F(23,960)

configs=[
    {'name':'G_111_200_B_101_200','gaussian':F(111,200),'bjork':F(101,200),'gap':F(1,1000)},
    {'name':'G_223_400_B_101_200','gaussian':F(223,400),'bjork':F(101,200),'gap':F(1,4000)},
    {'name':'G_11_20_B_51_100','gaussian':F(11,20),'bjork':F(51,100),'gap':F(1,1000)},
    {'name':'G_11_20_B_1_2','gaussian':F(11,20),'bjork':F(1,2),'gap':F(1,250)},
]
receipts=[]
for conf in configs:
    radii=[conf['gaussian']]*12+[conf['bjork']]*36
    threshold=F(1,6)-conf['gap']
    O=[];U=[];rules={};rejection_bounds={}
    for i in range(48):
        oi=0;ui=(1<<48)-1  # Loops deliberately retained: the result is a low-overlap bound.
        for j in range(48):
            d=data[i][j];r=radii[i]+radii[j]
            assert r< F(6,5) < A.pi_lo  # Jensen/sine lemma domain, and r/sqrt6<1.
            if i!=j:
                direct_reject=d['lo']>6*r*r
                radial_reject=d['lo']>r*d['radial']+d['abs_s']*r*r/2
                if not(direct_reject or radial_reject):oi|=1<<j
            else:
                assert d['lo']>6*r*r
            if d['zero']:
                # cos(sqrt t) Jensen and orthogonal projection yield sin²(r/sqrt6).
                # Alternating fifth-degree sine upper bound, expressed rationally.
                sine_upper=(r*r/F(6))*(1-r*r/F(36)+r**4/F(4320))**2
                upper=sine_upper;rule='orthogonal_sine'
                if d['antipodal_constant'] is not None:
                    anti_upper=(r*r+d['antipodal_constant'])**2/F(36)
                    if anti_upper<upper:upper=anti_upper;rule='antipodal_'+d['antipodal_type']
                if upper<threshold:
                    ui&=~(1<<j)
                    if i<j:
                        rules[rule]=rules.get(rule,0)+1
                        rejection_bounds[f'{i},{j}']=upper
        O.append(oi);U.append(ui)
    assert all(bool(O[i]>>j&1)==bool(O[j]>>i&1) for i in range(48) for j in range(48))
    assert all(bool(U[i]>>j&1)==bool(U[j]>>i&1) for i in range(48) for j in range(48))
    cliques=[]
    def enum(a,p):
        if len(a)==6:cliques.append(a);return
        if len(a)+p.bit_count()<6:return
        while p:
            j=(p&-p).bit_length()-1;p&=p-1
            enum(a+[j],p&O[j])
    enum([], (1<<48)-1)
    assert len(cliques)==52
    # Stronger than a disjoint-clique search: all ordered clique pairs, including
    # overlapping pairs, must have a cross edge with the proved low-overlap bound.
    witnesses=[]
    for a in cliques:
        row=[]
        for b in cliques:
            pair=next(((i,j) for i in a for j in b if not(U[i]>>j&1)),None)
            assert pair is not None,(conf['name'],a,b)
            assert data[pair[0]][pair[1]]['zero']
            row.append(list(pair))
        witnesses.append(row)
    receipts.append({
        'name':conf['name'],'gaussian_radius':str(conf['gaussian']),'bjork_radius':str(conf['bjork']),
        'quantized_gaussian_radius':str(conf['gaussian']-F(1,1000)),
        'quantized_bjork_radius':str(conf['bjork']-F(1,1000)),
        'guaranteed_probability_gap':str(conf['gap']),
        'guaranteed_minimum_cross_probability_upper':str(threshold),
        'orthogonality_edges':sum(x.bit_count() for x in O)//2,
        'retained_unbiased_edges_excluding_loops':(sum(x.bit_count() for x in U)-48)//2,
        'orthogonality_6_cliques':cliques,
        'low_overlap_rejection_rule_counts':rules,
        'largest_low_overlap_upper_bound':str(max(rejection_bounds.values())),
        'all_ordered_clique_pairs_have_low_overlap_witness':True,
        'ordered_clique_pair_count':len(cliques)**2,
        'cross_witnesses':witnesses,
    })
print(json.dumps({'status':'CERTIFIED','configurations':receipts},indent=2))

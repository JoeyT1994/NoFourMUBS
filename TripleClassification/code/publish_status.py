#!/usr/bin/env python3
"""Publish an audited assembly into TripleClassification/: the README status block, results/balls.tsv,
results/summary.json and results/open.txt.

  python code/publish_status.py RESULTS_DIR [--when "29 October 2026, 11:10"]

RESULTS_DIR is an assemble.py output (balls.tsv, summary.json). The README block between the STATUS markers is
regenerated; nothing else in the README changes.
"""
import argparse, collections, csv, json, os, shutil, time

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.dirname(HERE)
BEGIN, END = '<!-- STATUS:BEGIN (generated by code/publish_status.py) -->', '<!-- STATUS:END -->'


def reason(v):
    st = (v or {}).get('status', 'no tree')
    if st == 'closed': return 'closed'
    if 'missing or unexpected rows' in st or 'JSONDecodeError' in st: return 'refinement running'
    if 'Stage C' in st: return 'computed; Stage C check pending'
    if st.startswith('open below'): return 'cells open at the deepest level so far'
    return st[:80]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('results'); ap.add_argument('--when')
    a = ap.parse_args()
    when = a.when or time.strftime('%-d %B %Y, %H:%M')
    s = json.load(open(os.path.join(a.results, 'summary.json')))
    rows = list(csv.DictReader(open(os.path.join(a.results, 'balls.tsv')), delimiter='\t'))
    tree = s.get('tree', {})
    final = collections.Counter(r['final'] for r in rows)
    whole = final['classified'] + final['empty']
    by_rule = collections.Counter(tree[r['ball']].get('rule', 'certifier') for r in rows
                                  if r['final'].startswith('tree') and r['ball'] in tree)
    leaves = sum(tree[r['ball']].get('leaves', 0) for r in rows if r['final'].startswith('tree') and r['ball'] in tree)
    opened = [(int(r['ball']), reason(tree.get(r['ball']))) for r in rows if r['final'] == 'open']
    closed = len(rows) - len(opened)
    why = collections.Counter(x for _, x in opened)
    lines = [BEGIN, '## Status (%s; audited, runs in progress)' % when, '',
             '**{:,} of {:,} seed balls are closed; {:,} are open.** Every closed ball is closed on one route:'.format(closed, len(rows), len(opened)),
             '- the frozen whole-ball certifier on the original ball; or',
             '- one dyadic tree of sub-balls covering the whole original ball, verified by `code/audit_select.py`'
             ' (`TREE_PROOF.md`), with the Stage C preconditions of every closed sub-ball checked, including those a rule'
             ' closed.', '',
             'No ball is replaced by a smaller one: a tree covers the entire original ball.', '',
             '| Seed balls | Count |', '|---|---:|',
             '| **Closed** | **{:,}** |'.format(closed),
             '| · whole ball, every third basis of known type (certifier) | %d |' % final['classified'],
             '| · whole ball, no third basis (certifier) | {:,} |'.format(final['empty']),
             '| · tree, every leaf closed by the certifier | %d |' % by_rule['certifier'],
             '| · tree, some leaves closed by the labelled Fourier score, Γ_F ≤ 19/50 (`GAMMA_PROOF.md`) | %d |' % by_rule['fourier'],
             '| · tree, some leaves closed by the minimum-transition ordering (`GAMMA_PROOF.md`) | %d |' % by_rule['ordering'],
             '| · tree, some leaves closed by anchored-column exclusions (`ANCHORED_PROOF.md`) | %d |' % by_rule['anchored'],
             '| · tree, some leaves closed by whole-cell graph exclusions (`GRAPH_PROOF.md`) | %d |' % by_rule['graph'],
             '| · tree, some cells closed by replayed whole-cell proofs (PR #4, `PLANE_COLUMN_PROOF.md`) | %d |' % by_rule['plane'],
             '| **Open** | **%d** |' % len(opened)]
    for k, n in sorted(why.items(), key=lambda x: -x[1]): lines.append('| · %s | %d |' % (k, n))
    lines += ['', 'Certified pieces: {:,} whole balls and {:,} sub-balls in trees.'.format(whole, leaves),
              'The two score rules, the anchored-column exclusion and the graph exclusion come from the collaborator\'s returns of 29 October and'
              ' await independent review.'
              ' Closures by the ordering rule hold in the restricted sense of that theorem, so they count only once'
              ' every ball is closed.', '']
    if opened:
        lines += ['Open balls (`results/open.txt` gives the reason for each): ' +
                  ', '.join(str(b) for b, _ in sorted(opened)) + '.', '']
    lines.append(END)
    block = '\n'.join(lines)
    readme = os.path.join(TOP, 'README.md'); text = open(readme).read()
    if BEGIN in text:
        i = text.index(BEGIN); j = text.index(END) + len(END)
        text = text[:i] + block + text[j:]
    else:
        raise SystemExit('README has no STATUS markers')
    open(readme, 'w').write(text)
    res = os.path.join(TOP, 'results')
    for name in ('balls.tsv', 'summary.json'): shutil.copy(os.path.join(a.results, name), os.path.join(res, name))
    with open(os.path.join(res, 'open.txt'), 'w') as f:
        f.write('# ball\treason (audited %s)\n' % when)
        for b, x in sorted(opened): f.write('%d\t%s\n' % (b, x))
    print('%d closed, %d open; trees by rule %s; %d whole balls + %d sub-balls' % (closed, len(opened), dict(by_rule), whole, leaves))


if __name__ == '__main__': main()
